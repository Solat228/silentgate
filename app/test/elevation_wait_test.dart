import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// РЕЗУЛЬТАТ КОМАНДЫ НАДО ДОЖДАТЬСЯ, А НЕ ВЫДУМАТЬ.
///
/// ⚠️ ЖАЛОБА ВЛАДЕЛЬЦА 07.09.2026: «перестал создаваться UAC совсем, приложение
/// запущено от админа, никаких окон не было», а на экране — «Не удалось создать
/// задачу (UAC отклонён или запрещено политикой)».
///
/// Сообщение врало дважды. UAC в этом случае не запрашивается вовсе: права уже
/// есть, и код идёт прямой веткой. А настоящую причину отказа `schtasks` никто
/// не видел — процесс запускался ОТСОЕДИНЁННЫМ (`ProcessStartMode.detached`),
/// его код возврата и stderr уходили в никуда, и функция возвращала `true`
/// независимо от того, что там случилось.
///
/// Дальше `install()` десять секунд ждал появления задачи, не дожидался и
/// возвращал `false` — но объяснить, почему, было уже нечем.
///
/// ⚠️ ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ЖДАТЬ ВСЕГДА. Хелпер TUN обязан ПЕРЕЖИТЬ нас: он
/// держит туннель, и ожидание его завершения повесило бы подключение целиком.
/// Отсюда два режима, а не один.
void main() {
  String src(String rel) => File(rel).readAsStringSync();

  test('⚠️ создание задачи Планировщика ЖДЁТ результат', () {
    final s = src('lib/engine/windows/tun/tun_scheduled_task.dart');
    final i = s.indexOf("runElevatedAsync('schtasks.exe'");
    expect(i, greaterThan(0), reason: 'вызов schtasks не найден');
    // Смотрим сам вызов, а не весь файл: параметр мог остаться в соседнем.
    final call = s.substring(i, s.indexOf(';', i));
    expect(call, contains('waitForExit: true'),
        reason: 'создание задачи снова рапортует об успехе, ничего о нём не '
            'зная — и человек снова увидит «UAC отклонён» там, где UAC не '
            'участвовал');
  });

  test('⚠️ хелпер TUN, наоборот, НЕ ждём', () {
    // Обратная сторона того же: дождавшись хелпера, мы висели бы всё время
    // жизни туннеля. Проверяем, что режим по умолчанию остался прежним.
    final s = src('lib/engine/windows/elevation.dart');
    expect(s, contains('bool waitForExit = false'),
        reason: 'ожидание стало умолчанием — подключение будет висеть');
  });

  test('⚠️ причина отказа попадает в журнал, а не теряется', () {
    // Без кода возврата и stderr «не удалось» неотличимо от «отказали в
    // правах», и человек ищет беду не там — ровно это и случилось.
    final s = src('lib/engine/windows/elevation.dart');
    expect(s, contains('r.exitCode'),
        reason: 'код возврата команды снова не проверяется');
    expect(s, contains('r.stderr'),
        reason: 'stderr команды снова уходит в никуда');
  });
}
