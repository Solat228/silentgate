import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// РУССКИЙ ЯЗЫК, ЗАШИТЫЙ В ЛОГИКУ, А НЕ В ПЕРЕВОДЫ.
///
/// ⚠️ КЛАСС БАГОВ, КОТОРЫЙ НЕ ЛОВИТ НИЧТО ОСТАЛЬНОЕ. Интерфейс переведён на
/// десять языков, и тесты локализации стерегут паритет ключей ARB. Но строка,
/// сравниваемая в КОДЕ, через ARB не проходит вовсе — ни компилятор, ни
/// `l10n_test` её не видят. Снаружи это выглядит не как «не переведено», а как
/// «не работает»: у нерусского пользователя молча пропадает кнопка или ветка.
///
/// Пойман 21.08.2026 в `server_tile.dart`: кнопка «Обновить» у notice-сервера
/// показывалась, только если текст ПАНЕЛИ содержал `нажмите` или `обнов`.
/// Панель пишет на своём языке — англоязычному провайдеру кнопки не доставалось,
/// и человек оставался наедине с сообщением, объясняющим, что ему нажать.
///
/// ⚠️ ТЕСТ ИЩЕТ САМ, А НЕ СВЕРЯЕТСЯ СО СПИСКОМ ИЗВЕСТНЫХ ФАЙЛОВ. Список руками
/// в этом проекте уже отставал от кода (разбор — CHANGELOG 1.9.3). Здесь список
/// служит другому: он фиксирует УЖЕ ПРИНЯТЫЕ решения с обоснованием, и любое
/// новое место обязано быть обосновано отдельно, а не проскользнуть молча.
void main() {
  /// Файлы, где сравнение с русским литералом ЗАКОННО, и почему.
  ///
  /// Общее у всех трёх: текст приходит от СИСТЕМЫ или от нас самих, а не от
  /// пользователя и не от панели. Разбирать чужой текст на неизвестном языке —
  /// вот что запрещено.
  const accepted = <String, String>{
    'lib/engine/engine_base.dart':
        'сообщение об ошибке от Windows — оно локализовано системой. Рядом '
            'лежит разбор по КОДУ ошибки (errno 2/3), то есть язык здесь '
            'подспорье, а не единственная опора.',
    'lib/engine/windows/tun/tun_scheduled_task.dart':
        'вывод schtasks — Windows локализует статус задачи. ⚠️ Покрыты только '
            'en и ru: на немецкой Windows проверка «задача ещё бежит» вернёт '
            'false. Влияние малое (это цикл ожидания), но это тот же класс.',
    'lib/ui/widgets/geo_bases_section.dart':
        'разбирается НАШ СОБСТВЕННЫЙ текст ошибки гео-баз, чтобы выбрать '
            'подсказку. ⚠️ Хрупко по построению: локализуем эти строки — '
            'разбор молча перестанет срабатывать. Переводить их без правки '
            'этого файла нельзя.',
  };

  /// Сравнения строк, где литерал содержит кириллицу.
  final pattern = RegExp(
    r"""(contains|startsWith|endsWith|indexOf)\(\s*'[^']*[а-яА-ЯёЁ]""",
  );

  List<String> scan() {
    final root = Directory('lib');
    final hits = <String>[];
    for (final e in root.listSync(recursive: true)) {
      if (e is! File || !e.path.endsWith('.dart')) continue;
      final rel = e.path.replaceAll(Platform.pathSeparator, '/');
      // Сгенерированные переводы и сами ARB — не логика.
      if (rel.startsWith('lib/l10n/')) continue;
      final lines = e.readAsLinesSync();
      for (var i = 0; i < lines.length; i++) {
        final t = lines[i].trimLeft();
        if (t.startsWith('//') || t.startsWith('///')) continue;
        if (pattern.hasMatch(lines[i])) hits.add('$rel:${i + 1}');
      }
    }
    return hits;
  }

  group('⚠️ Сравнение с русским литералом — только там, где обосновано', () {
    test('новых мест не появилось', () {
      final unexpected = scan()
          .where((h) => !accepted.keys.any((f) => h.startsWith('$f:')))
          .toList();
      expect(unexpected, isEmpty,
          reason: 'Код сравнивает строку с русским литералом в новом месте.\n'
              'Если текст приходит от ПАНЕЛИ или от ПОЛЬЗОВАТЕЛЯ — так нельзя: '
              'они пишут на своём языке, и ветка молча не сработает.\n'
              'Если это текст СИСТЕМЫ или наш собственный — добавьте файл в '
              'accepted вместе с объяснением, почему иначе не выходит.');
    });

    test('обоснования не пустые', () {
      // Запись без причины бесполезна: следующий читатель не сможет решить,
      // можно ли это трогать.
      for (final e in accepted.entries) {
        expect(e.value.length, greaterThan(40), reason: '${e.key} без причины');
      }
    });
  });

  group('⚠️ Кнопка «Обновить» у notice-сервера', () {
    late String tile;
    setUp(() =>
        tile = File('lib/ui/widgets/server_tile.dart').readAsStringSync());

    test('⚠️ показывается ВСЕГДА, а не по угаданному языку', () {
      // Notice-сервер — подделка вместо настоящих серверов (оплата не прошла,
      // подписка истекла, лимит устройств). Во всех случаях осмысленное
      // действие ровно одно: перезапросить подписку. Угадывать нечего.
      expect(tile.contains("low.contains('нажмите')"), isFalse,
          reason: 'вернулось угадывание по русским словам');
      expect(tile.contains('if (actionable)'), isFalse,
          reason: 'кнопка снова спрятана за условием');
    });

    test('кнопка на месте и зовёт обновление подписки', () {
      final at = tile.indexOf('Widget _noticeTile(');
      expect(at, greaterThan(0));
      final body = tile.substring(at, at + 2600);
      expect(body, contains('l.srvTileRefresh'));
      expect(body, contains('state.refreshSubscription()'));
    });
  });
}
