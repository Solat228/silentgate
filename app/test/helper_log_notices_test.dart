import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/engine/windows/tun/helper_log_notices.dart';

/// Мост «важное из журнала элевейтнутого помощника → общий журнал».
///
/// ⚠️ ЗАЧЕМ. Настоящий kill switch поднимает не приложение, а помощник
/// (`TunHelper`), запущенный с правами администратора отдельным процессом. Он
/// пишет в `singbox.log` через свой колбэк, и строки уровня отказа — «kill
/// switch НЕ поднят», «нет связи с интерфейсом», исключение при подъёме — в
/// едином журнале не появлялись ВООБЩЕ. А именно их ищут, когда пропал
/// интернет: при поднятой блокировке и неподнятом туннеле машина без сети
/// выглядит как «приложение сломалось», и в `app.log` тому нет ни следа.
void main() {
  test('строки отказа вытаскиваются, а успешные — нет', () {
    const log = '''
--- разведка kill switch: {"ok":true}
--- kill switch: состав обновлён под выбранные программы
--- kill switch НЕ поднят: нет связи с интерфейсом
--- sing-box завершился, код 0
--- kill switch не поднялся: PathAccessException
''';
    final found = killSwitchFailures(log);
    expect(found, [
      '--- kill switch НЕ поднят: нет связи с интерфейсом',
      '--- kill switch не поднялся: PathAccessException',
    ]);
  });

  test('пустой и бессвязный журнал не роняет разбор', () {
    expect(killSwitchFailures(''), isEmpty);
    expect(killSwitchFailures('   \n\n  '), isEmpty);
    expect(killSwitchFailures('обычная строка ядра dial tcp'), isEmpty);
  });

  test('⚠️ ядро умерло при поднятой блокировке — это тоже отказ', () {
    // Машина в этот момент БЕЗ СЕТИ, и это самое важное сообщение из всех:
    // человек видит мёртвый интернет и не знает, что его держит наша защита.
    const log = '--- ядро умерло, блокировка ДЕРЖИТСЯ: жду команду';
    expect(killSwitchFailures(log), [log]);
  });

  test('одна и та же строка не дублируется', () {
    const line = '--- kill switch не поднялся: сбой';
    expect(killSwitchFailures('$line\n$line\n'), [line],
        reason: 'помощник может повторить попытку — в журнал приложения это '
            'должно попасть один раз, иначе он забьётся одинаковыми строками');
  });

  // ── Только последняя сессия ──────────────────────────────────────────────

  test('⚠️ берём только последнюю сессию: старые отказы не воскрешаем', () {
    // Журнал помощника переживает перезапуски НАМЕРЕННО (иначе журнал аварии
    // уничтожался бы тем самым перезапуском, который аварией и вызван).
    // Значит в хвосте лежат отказы прошлых сессий, и мост, не глядя на
    // границу, кричал бы о давно почившей беде при исправном подключении.
    const log = '''
--- запуск sing-box 2026-09-01T10:00:00.000: sing-box.exe run -c a.json
--- kill switch не поднялся: старая беда
--- запуск sing-box 2026-09-02T06:00:00.000: sing-box.exe run -c a.json
--- kill switch НЕ поднят: нет связи с интерфейсом
''';
    expect(killSwitchFailures(lastHelperSession(log)),
        ['--- kill switch НЕ поднят: нет связи с интерфейсом']);
  });

  test('журнал без заголовка сессии разбирается целиком', () {
    // Помощник мог не успеть написать заголовок (упал на открытии лога) —
    // молча отдать пусто здесь значит спрятать ровно ту аварию, ради которой
    // мост и заводится.
    const log = '--- kill switch не поднялся: сбой';
    expect(lastHelperSession(log), log);
  });

  // ── Страж ────────────────────────────────────────────────────────────────

  test('⚠️ КАЖДАЯ строка отказа из tun_helper.dart покрыта маркерами', () {
    // ⚠️ Список маркеров, написанный руками, устаревает молча: поменяли
    // формулировку в помощнике — мост замолчал, и узнать об этом можно только
    // по следующей жалобе «интернет пропал, а в логах пусто». Поэтому страж
    // читает НАСТОЯЩИЙ исходник помощника, а не свою копию строк.
    final src = File('lib/engine/windows/tun/tun_helper.dart');
    expect(src.existsSync(), isTrue, reason: 'страж читает исходник помощника');
    final text = src.readAsStringSync();

    // Строковые литералы, уходящие в журнал помощника.
    final written = RegExp(r"log\.write\(\s*'([^']*)'", multiLine: true)
        .allMatches(text)
        .map((m) => m.group(1)!)
        .toList();
    expect(written, isNotEmpty, reason: 'контроль: литералы вообще нашлись');

    // Что мы считаем отказом — по словам, а не по номерам строк.
    final failureWords = RegExp(
        'НЕ ЗАПУСКАЮ|НЕ УДАЛОСЬ|НЕ поднят|не поднялся|не удалось|ДЕРЖИТСЯ|'
        'не выполнилась');
    final failures = written.where(failureWords.hasMatch).toList();
    expect(failures, isNotEmpty,
        reason: 'контроль: строки отказа в помощнике есть');

    for (final line in failures) {
      expect(killSwitchFailures(line), isNotEmpty,
          reason: 'строка отказа помощника не попадает в общий журнал: «$line». '
              'Добавьте её маркер в helperFailureMarkers.');
    }
  });
}
