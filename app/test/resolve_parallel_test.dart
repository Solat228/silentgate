import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/engine/engine_base.dart';

/// РЕЗОЛВ АДРЕСОВ ИДЁТ ПАРАЛЛЕЛЬНО, А НЕ СКЛАДЫВАЕТСЯ В МИНУТЫ.
///
/// ⚠️ ЖАЛОБА ВЛАДЕЛЬЦА 03.09.2026: обрыв держался **3 минуты 17 секунд**, и в
/// журнале видно, куда ушло это время — два с половиной десятка строк
/// «Не удалось отрезолвить адрес №N (Timeout 5 сек)» подряд.
///
/// Механика беды складывается из двух вещей, и каждая по отдельности безобидна:
///
///  1. Резолв шёл ПОСЛЕДОВАТЕЛЬНЫМ циклом с таймаутом 5 с на адрес. У владельца
///     42 выхода («Сторож выходов вооружён: 42 шт.»), то есть до 210 секунд
///     только на ожидание — ровно те 3,5 минуты.
///  2. При поднятой блокировке DNS не отвечает В ПРИНЦИПЕ: правило «блок DNS
///     мимо туннеля» стоит выше разрешения локальной сети, а на Windows
///     DNS-запрос принадлежит `svchost.exe`, а не нашему бинарю (память
///     `windows-dns-belongs-to-svchost`). Значит КАЖДЫЙ из 42 запросов
///     гарантированно доживает до полного таймаута.
///
/// Само падение канала короткое — длинной его делает процедура восстановления,
/// и она же удлиняется с каждым новым выходом в подписке. Отсюда «провалы стали
/// втрое длиннее»: у владельца выросло число выходов, а не ухудшился сервер.
///
/// ⚠️ ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Не «быстро ли работает DNS» — сети здесь нет
/// вовсе. Проверяется, что N адресов обрабатываются ОДНОВРЕМЕННО: суммарное
/// время близко к времени одного запроса, а не к их сумме.
void main() {
  test('⚠️ 42 адреса резолвятся за время ОДНОГО, а не сорока двух', () async {
    // Держим счётчик одновременно летящих запросов: именно он отвечает на
    // вопрос «параллельно ли», а не секундомер, который зависит от машины.
    var inFlight = 0;
    var peak = 0;
    final hosts = [for (var i = 0; i < 42; i++) 'node$i.example'];

    await VpnEngineBase.resolveHostsForTest(hosts, (host) async {
      inFlight++;
      if (inFlight > peak) peak = inFlight;
      // Имитируем таймаут: настоящий длится 5 с, здесь достаточно уступить
      // очередь — важно, что запросы ПЕРЕСЕКАЮТСЯ во времени.
      await Future<void>.delayed(const Duration(milliseconds: 20));
      inFlight--;
      throw Exception('timeout');
    });

    expect(peak, greaterThan(1),
        reason: 'последовательный цикл даёт пик 1 — это и есть исходный дефект');
  });

  test('⚠️ но НЕ все разом: параллельность ограничена', () async {
    // Сорок два одновременных запроса к резолверу — это уже не диагностика, а
    // мини-шторм: домашний роутер отвечает на такое отказами, и мы получили бы
    // ложные «адрес не резолвится» там, где сеть исправна.
    var inFlight = 0;
    var peak = 0;
    final hosts = [for (var i = 0; i < 42; i++) 'node$i.example'];

    await VpnEngineBase.resolveHostsForTest(hosts, (host) async {
      inFlight++;
      if (inFlight > peak) peak = inFlight;
      await Future<void>.delayed(const Duration(milliseconds: 10));
      inFlight--;
      return ['203.0.113.1'];
    });

    expect(peak, lessThanOrEqualTo(VpnEngineBase.resolveConcurrency));
  });

  test('порядок и состав ответа не зависят от параллельности', () async {
    // Конфиг ядра собирается из этой карты; «дышащий» между запусками порядок
    // ломал бы сверку живого туннеля с будущим (см. `_tunConfigPreview`).
    final hosts = ['b.example', 'a.example', 'c.example'];
    final got = await VpnEngineBase.resolveHostsForTest(
        hosts, (host) async => ['203.0.113.${host.length}']);
    expect(got.keys.toList(), hosts,
        reason: 'порядок — как во входном списке, а не как ответил резолвер');
  });

  test('повторы в списке спрашиваются один раз', () async {
    var calls = 0;
    await VpnEngineBase.resolveHostsForTest(
        ['a.example', 'a.example', 'b.example'], (host) async {
      calls++;
      return ['203.0.113.7'];
    });
    expect(calls, 2, reason: 'дубликат адреса не стоит второго запроса');
  });
}
