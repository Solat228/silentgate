import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/core/platform/cp866.dart';

/// КОДИРОВЩИК CP866 — ТАБЛИЦА, ГРАНИЦЫ И ПОВЕДЕНИЕ НА ЧУЖОМ СИМВОЛЕ.
///
/// ⚠️ РАДИ ЧЕГО ЭТОТ ФАЙЛ. `cmd` перечитывает `.bat` по БАЙТОВЫМ СМЕЩЕНИЯМ и на
/// многобайтном UTF-8 сбивается: исполнение продолжается с середины строки, в
/// выводе появляются обрывки. Правило проекта (`CLAUDE.md`, пункт 3) поэтому
/// требует OEM-кодировку. Единственный генератор батников в коде —
/// восстановление сети, и он запускается ОТ ИМЕНИ АДМИНИСТРАТОРА и правит
/// winsock/IP-стек: сбившееся на середине исполнение здесь стоит дороже всего.
///
/// Ожидаемые байты ниже посчитаны НЕ этим кодом, а сторонним кодеком cp866
/// (Python), чтобы тест проверял таблицу, а не повторял её.
void main() {
  /// Границы четырёх диапазонов и две отдельные буквы.
  ///
  /// ⚠️ Именно ГРАНИЦЫ: таблица кириллицы в cp866 разорвана — «а»–«п» лежат
  /// подряд с 0xA0, а «р»–«я» уезжают на 0xE0 через блок псевдографики.
  /// Ошибка на единицу в любом краю даёт правдоподобный, но чужой байт, и
  /// проверка «где-то в середине» её не заметит.
  const boundaries = <String, int>{
    'А': 0x80, // начало прописных
    'Я': 0x9F, // конец прописных
    'а': 0xA0, // начало первой половины строчных
    'п': 0xAF, // конец первой половины
    'р': 0xE0, // начало второй половины (разрыв таблицы!)
    'я': 0xEF, // конец строчных
    'Ё': 0xF0, // вне алфавитных диапазонов
    'ё': 0xF1, // вне алфавитных диапазонов
  };

  group('Cp866.encode', () {
    test('границы диапазонов кириллицы дают ожидаемые байты', () {
      for (final e in boundaries.entries) {
        expect(Cp866.encode(e.key), [e.value],
            reason: 'символ «${e.key}» закодирован не тем байтом — таблица '
                'cp866 сдвинута, и cmd прочитает .bat с середины строки');
      }
    });

    test('целая фраза совпадает байт в байт со сторонним кодеком', () {
      // Ровно та строка, что идёт в батник восстановления сети.
      expect(Cp866.encode('Восстановление сети SilentGate...'), const [
        0x82, 0xAE, 0xE1, 0xE1, 0xE2, 0xA0, 0xAD, 0xAE, 0xA2, 0xAB, //
        0xA5, 0xAD, 0xA8, 0xA5, 0x20, 0xE1, 0xA5, 0xE2, 0xA8, 0x20, //
        0x53, 0x69, 0x6C, 0x65, 0x6E, 0x74, 0x47, 0x61, 0x74, 0x65, //
        0x2E, 0x2E, 0x2E,
      ]);
    });

    test('вторая фраза батника — тоже байт в байт', () {
      expect(
          Cp866.encode(
              'Готово. Перезагрузите компьютер для применения сброса winsock/IP.'),
          const [
            0x83, 0xAE, 0xE2, 0xAE, 0xA2, 0xAE, 0x2E, 0x20, 0x8F, 0xA5, //
            0xE0, 0xA5, 0xA7, 0xA0, 0xA3, 0xE0, 0xE3, 0xA7, 0xA8, 0xE2, //
            0xA5, 0x20, 0xAA, 0xAE, 0xAC, 0xAF, 0xEC, 0xEE, 0xE2, 0xA5, //
            0xE0, 0x20, 0xA4, 0xAB, 0xEF, 0x20, 0xAF, 0xE0, 0xA8, 0xAC, //
            0xA5, 0xAD, 0xA5, 0xAD, 0xA8, 0xEF, 0x20, 0xE1, 0xA1, 0xE0, //
            0xAE, 0xE1, 0xA0, 0x20, 0x77, 0x69, 0x6E, 0x73, 0x6F, 0x63, //
            0x6B, 0x2F, 0x49, 0x50, 0x2E,
          ]);
    });

    test('ASCII проходит как есть, включая CR и LF', () {
      // Команды батника — чистый ASCII, и он обязан дойти неизменным:
      // именно по нему cmd находит границы строк.
      const ascii = 'netsh winsock reset\r\n@echo off\r\n';
      expect(Cp866.encode(ascii), ascii.codeUnits);
    });

    test('весь диапазон ASCII 0x00…0x7F тождественен себе', () {
      final all = String.fromCharCodes(List.generate(128, (i) => i));
      expect(Cp866.encode(all), List.generate(128, (i) => i));
    });

    test('⚠️ незнакомый символ становится «?», а не уезжает сырым UTF-8', () {
      // Одна такая буква вернула бы ровно ту беду, от которой уходим:
      // «…» в UTF-8 — три байта, и cmd после них считает строку с середины.
      for (final ch in const ['…', ' ', '€', '漢', 'ﬁ']) {
        expect(Cp866.encode(ch), [0x3F],
            reason: 'символ ${ch.codeUnitAt(0).toRadixString(16)} '
                'просочился в файл не одним байтом');
      }
    });

    test('⚠️ суррогатная пара (эмодзи) не даёт двух «?» вместо одного знака',
        () {
      // Эмодзи в Dart — две кодовые единицы. Наивный обход по codeUnits дал бы
      // «??», то есть ЛИШНИЙ байт и сдвиг всех последующих смещений.
      expect(Cp866.encode('🙂'), [0x3F]);
      expect(Cp866.encode('a🙂b'), [0x61, 0x3F, 0x62]);
    });

    test('пустая строка даёт пустой список', () {
      expect(Cp866.encode(''), isEmpty);
    });

    test('каждый байт результата помещается в байт', () {
      final bytes = Cp866.encode('Проверка ABC 123 Ёё');
      for (final b in bytes) {
        expect(b, inInclusiveRange(0x00, 0xFF));
      }
    });
  });

  group('Cp866.isEncodable', () {
    test('кириллица и ASCII — да, прочее — нет', () {
      expect(Cp866.isEncodable('Восстановление сети SilentGate...'), isTrue);
      expect(Cp866.isEncodable('Ёё АЯая'), isTrue);
      // ⚠️ Этим гейтом стерегутся будущие правки текста батника: автор,
      // вставивший «…», должен узнать об этом от теста, а не от пользователя,
      // у которого сброс сети выполнился наполовину.
      expect(Cp866.isEncodable('Готово…'), isFalse);
      expect(Cp866.isEncodable('нераз рывный'), isFalse);
    });
  });
}
