import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/core/platform/singbox_log_format.dart';

/// Чтение лога sing-box в отчёте поддержки.
///
/// ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ ПРАВИТСЯ. Владелец прислал строку и спросил «чё за +700»:
///
///     +0700 2026-08-11 02:09:08 <ESC>[31mERROR<ESC>[0m … download finished
///
/// Данные верные — это смещение часового пояса, — но sing-box печатает его
/// ПЕРЕД датой, и строка начинается с числа, похожего на код ошибки. Плюс
/// управляющие последовательности цвета, которые в текстовом файле становятся
/// мусором и вдобавок ломают поиск по слову ERROR.
///
/// Формат задаётся самим ядром и в конфиге не настраивается, поэтому приводим
/// его в порядок при чтении. ⚠️ Именно ПРИ ЧТЕНИИ: сам файл не трогаем, иначе
/// потеряли бы возможность сверить его с выводом ядра один в один.
void main() {
  //  — символ ESC. Пишем его кодом, а не самим байтом: невидимый
  // управляющий символ в исходнике не увидеть и не сверить глазами.
  final esc = String.fromCharCode(0x1b);

  group('Смещение часового пояса', () {
    test('переезжает из начала строки в конец', () {
      final out = tidySingboxLog('+0700 2026-08-11 02:09:08 INFO router: тест');
      expect(out, '2026-08-11 02:09:08 +0700 INFO router: тест');
    });

    test('отрицательное смещение тоже', () {
      final out = tidySingboxLog('-0500 2026-08-11 02:09:08 INFO x');
      expect(out, '2026-08-11 02:09:08 -0500 INFO x');
    });

    test('строки без смещения не трогаются', () {
      // В файле есть и НАШИ строки — метки запуска ядра. Их формат другой, и
      // переписывать их нельзя.
      const our = '--- запуск прокси-ядра 2026-08-11T02:09:10.184221';
      expect(tidySingboxLog(our), our);
    });

    test('смещение в СЕРЕДИНЕ строки не трогается', () {
      // Иначе поехали бы адреса и цифры внутри сообщений.
      const l = 'INFO connection to 1.2.3.4 +0700 done';
      expect(tidySingboxLog(l), l);
    });
  });

  group('Цветовые последовательности', () {
    test('убираются, а текст уровня остаётся', () {
      final out = tidySingboxLog('$esc[31mERROR$esc[0m connection closed');
      expect(out, 'ERROR connection closed');
      expect(out.contains(esc), isFalse);
    });

    test('поиск по слову ERROR снова работает', () {
      // Ровно то, ради чего это делается: в отчёте ищут «ERROR», а находили
      // раскрашенную строку и промахивались.
      final raw = '+0700 2026-08-11 02:09:08 $esc[31mERROR$esc[0m dial failed';
      expect(tidySingboxLog(raw), '2026-08-11 02:09:08 +0700 ERROR dial failed');
    });

    test('многострочный лог обрабатывается целиком', () {
      final raw = [
        '+0700 2026-08-11 02:09:08 $esc[36mINFO$esc[0m один',
        '+0700 2026-08-11 02:09:09 $esc[31mERROR$esc[0m два',
      ].join('\n');
      expect(tidySingboxLog(raw).split('\n'), [
        '2026-08-11 02:09:08 +0700 INFO один',
        '2026-08-11 02:09:09 +0700 ERROR два',
      ]);
    });
  });

  group('Границы', () {
    test('пустой вход не роняет', () {
      expect(tidySingboxLog(''), '');
    });

    test('перевод строки в конце сохраняется', () {
      // Хвост лога склеивается с остальным отчётом — потеря перевода строки
      // слепила бы последнюю строку со следующим заголовком.
      expect(tidySingboxLog('INFO x\n'), 'INFO x\n');
    });
  });
}
