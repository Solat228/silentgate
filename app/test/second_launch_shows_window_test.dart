import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/core/url_scheme.dart';

/// ПОВТОРНЫЙ ЗАПУСК ПОКАЗЫВАЕТ УЖЕ ОТКРЫТОЕ ПРИЛОЖЕНИЕ, А НЕ МОЛЧИТ.
///
/// ⚠️ ЖАЛОБА ВЛАДЕЛЬЦА 05.09.2026: «юзер мог свернуть программу в трей, и
/// дальше она НЕ запускается через .exe — просто ничего не происходит, хотя
/// сама программа уже запущена».
///
/// Причина ровно в одной ветке `main.dart`: второй экземпляр пересылал первому
/// только ССЫЛКУ, а при обычном двойном клике по `.exe` ссылки нет вовсе —
/// значит не пересылалось НИЧЕГО, и процесс тихо завершался. Первый экземпляр
/// при этом сидит в трее и о попытке запуска не узнаёт.
///
/// Для человека это выглядит как сломанный ярлык: он жмёт по нему второй и
/// третий раз, а на экране не происходит ничего. Именно на такое поведение
/// заводят трей — и именно оно делало его ловушкой.
void main() {
  group('⚠️ Команда «показать окно»', () {
    test('распознаётся как управляющее действие', () {
      expect(AppUrlScheme.controlAction('silentgate://show'), 'show');
      // Регистр и хвостовой слэш — как у остальных действий.
      expect(AppUrlScheme.controlAction('SilentGate://Show/'), 'show');
    });

    test('входит в общий список действий', () {
      // ⚠️ Список — единственный источник правды и для разрешения, и для
      // исполнения. Разъехавшиеся списки в этом проекте уже давали обход
      // проверки токена; повторять не будем.
      expect(AppUrlScheme.controlActions, contains('show'));
    });

    test('⚠️ показ окна — ОТДЕЛЬНОЕ действие, не связанное с состоянием',
        () {
      // Показ окна ничего не включает, не выключает и не меняет: он обязан
      // существовать рядом с управляющими командами, но не путаться с ними.
      // Токен здесь не при чём — секрет сокета требуется для ЛЮБОГО
      // сообщения (см. `SingleInstance.listen`), и подставляет его наш же
      // второй экземпляр, которому файл секрета доступен.
      expect(AppUrlScheme.showWindowUrl, 'silentgate://show');
      expect(AppUrlScheme.controlAction(AppUrlScheme.showWindowUrl), 'show');
    });
  });

  test('⚠️ второй экземпляр ПОСЫЛАЕТ команду, а не выходит молча', () {
    // Страж на вызов, а не на код: сама команда может существовать и
    // разбираться верно, но если `main.dart` её не отправляет, поведение
    // остаётся прежним — «ничего не происходит». В этом проекте «написано и
    // не вызывается» случалось четыре раза подряд.
    final src = File('lib/main.dart').readAsStringSync();
    final i = src.indexOf('tryBecomePrimary');
    expect(i, greaterThan(0), reason: 'ветка второго экземпляра не найдена');
    // ⚠️ Границу берём по КОДУ, а не отсчётом символов: окно в N символов
    // рвётся от любого дописанного комментария, и тест падает на правке,
    // которую должен пропускать. Ветка кончается выходом процесса.
    final end = src.indexOf('exit(0)', i);
    expect(end, greaterThan(i), reason: 'выход из второго экземпляра не найден');
    final branch = src.substring(i, end);
    expect(branch, contains('showWindowUrl'),
        reason: 'второй экземпляр не просит первого показать окно — при '
            'запуске без ссылки пользователь снова увидит тишину');
  });
}
