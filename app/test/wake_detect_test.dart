import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/core/platform/network_watcher.dart';

/// Страж эвристики «выход из сна».
///
/// Она опознаёт пробуждение по разрыву в ряду тактов таймера. На настольных
/// системах это верно: пока машина спала, ОС успела пересоздать интерфейсы уже
/// без нашего туннеля, и отпечаток при этом может совпасть до символа.
///
/// ⚠️ На Android посылка неверна дважды: таймеры Dart замирают при КАЖДОМ
/// гашении экрана, а туннелем владеет `VpnService`, который сон переживает.
/// Цена ошибки измерена по журналу владельца за двое суток: 201 ложное
/// «выход из сна» и 204 переподключения, на которых ловились гонки за
/// собственный порт и падал весь VPN-сервис.
void main() {
  test('на настольной системе эвристика включена по умолчанию', () {
    // Тесты идут на Windows — платформенное умолчание обязано это учитывать.
    expect(NetworkWatcher().detectWakeFromSleep, isTrue,
        reason: 'на Windows сон реален: система пересоздаёт интерфейсы, '
            'и без этой эвристики DNS после resume утекал бы провайдеру');
  });

  test('флаг можно выключить явно — это и делает мобильная платформа', () {
    expect(NetworkWatcher(detectWakeFromSleep: false).detectWakeFromSleep,
        isFalse);
  });

  test('выключение эвристики не трогает обычное сравнение отпечатков', () {
    // Настоящая смена сети на Android ловится как везде — сравнением адресов
    // с дебаунсом. Если бы выключение ломало и его, мобильный клиент перестал
    // бы замечать переход Wi-Fi → мобильная сеть.
    const wifi = ['192.168.1.10'];
    const lte = ['10.20.30.40'];
    expect(NetworkWatcher.fingerprintOf(wifi),
        isNot(NetworkWatcher.fingerprintOf(lte)));
    expect(NetworkWatcher.fingerprintOf(wifi),
        NetworkWatcher.fingerprintOf(wifi));
  });

  test('свои TUN-адреса в отпечаток не идут ни на какой платформе', () {
    // Иначе подъём собственного туннеля читался бы как смена сети — тот самый
    // самоподдерживающийся цикл, который чинили в 0.8.3.
    expect(NetworkWatcher.fingerprintOf(['192.168.1.10', '172.19.0.1']),
        NetworkWatcher.fingerprintOf(['192.168.1.10']));
  });
}
