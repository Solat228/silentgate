import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/ui/home_screen.dart';

/// БЛОКУ ПРОВЕРОК ДАЁТСЯ ПОТОЛОК, А НЕ ДОЛЯ ОСТАТКА.
///
/// ⚠️ ЖАЛОБА ВЛАДЕЛЬЦА 03.09.2026 (со снимком целого окна): «хочу, чтобы всё
/// было вписано в это разрешение» — при четырнадцати сервисах блок с
/// информацией о подключении уезжал за край, при шести срезались счётчики.
///
/// ⚠️ ПОЧЕМУ ЭТО ВООБЩЕ СЛУЧИЛОСЬ. Сжатие блока по высоте написано и подключено
/// давно (`ServiceChecksSides` → `FittedBox`), но включается только при
/// `constraints.hasBoundedHeight`. А блок стоит ребёнком `Column`, и дети
/// `Column` получают `maxHeight: infinity` — значит условие не выполнялось
/// НИКОГДА. Код был, вызывался и не делал ничего: тот же почерк, что у связок
/// провайдеров без `lazy: false`.
///
/// ⚠️ ПЕРВАЯ ПОПЫТКА ПОЧИНИТЬ БЫЛА НЕВЕРНОЙ И ОТКАЧЕНА (коммит 1b9560e). Блок
/// обернули в `Flexible` — он сжал содержимое НИЖЕ минимума, и на снимке из VM
/// «Автонастройка» легла поверх кнопки Connect. Отсюда пол в расчёте.
///
/// ⚠️ ЧЕГО ЭТОТ ТЕСТ НЕ ДОКАЗЫВАЕТ. Он проверяет ЧИСЛО, а не картинку.
///
/// ⚠️ ПОПРАВКА 10.09.2026: панель больше НЕ приватна (`ConnectPane`), и
/// картинку теперь тоже держит тест — `test/auto_pick_placement_test.dart`
/// поднимает её целиком, замеряет резерв по настоящей вёрстке и ловит
/// переполнение. Раньше стража на панель написать было нечем, и ровно поэтому
/// дефект проскочил мимо всех стражей вёрстки: они поднимали публичный
/// `ConnectCenterpiece` с его собственными ограничениями.
void main() {
  test('в тесном окне потолок оставляет место блоку под кнопкой', () {
    // Минимум окна Windows — 980×800; на панель приходится примерно 700.
    final got = checksHeightBudget(paneHeight: 700);
    expect(got, lessThan(700),
        reason: 'без вычета резерва блок снизу опять уедет за край');
    // ⚠️ РЕЗЕРВ ОБЯЗАН РАВНЯТЬСЯ ТОМУ, ЧТО ЛЕЖИТ ВНЕ `ConstrainedBox`:
    // просвет 16 + статус 24 + просвет 20 + строка кнопок 48 + счётчики 58.
    // Сумма сходится: 166.
    //
    // ⚠️ ЧТО УШЛО 10.09.2026: строка «Информация о сервере» (8 + 40 = 48)
    // уехала значком в полосу плашки, вторая кнопка своей строкой (8 + 48 =
    // 56) встала в ту же строку `Wrap`. Прежней раскладке под потолком было
    // нужно 166 + 48 + 56 = 270, а в коде стояло 214 — на 56 меньше нужного.
    // Числа 254 не существовало ни разу: оно жило только в комментарии и не
    // сходилось ни с чем. Раскладка, которая не сходится, хуже отсутствующей.
    //
    // ⚠️ ЧИСЛО НЕ СЛОЖЕНО НА ГЛАЗ, А ЗАМЕРЕНО по настоящей панели —
    // `test/auto_pick_placement_test.dart`, «резерв под потолком равен тому,
    // что реально ниже него». Здесь стоит вторая половина той же проверки:
    // арифметика потолка. Разъедутся — покраснеет один из двух.
    expect(kChecksReserveBelow, 166);
    expect(got, 700 - kChecksReserveBelow);
  });

  test('⚠️ крупный системный шрифт отодвигает потолок', () {
    // Всё, что лежит ниже потолка, — текст: статус, подпись кнопки, счётчики.
    // При масштабе 1,3 они занимают на треть больше, и потолок, оставшийся
    // прежним, отправил бы низ панели за край ровно у того, кто увеличил
    // шрифт, чтобы читать.
    expect(checksHeightBudget(paneHeight: 700, textScale: 1.3),
        700 - kChecksReserveBelow * 1.3);
    // Мелкий шрифт места не возвращает: высота кнопки — это область нажатия,
    // а отступы заданы числами и не сжимаются вовсе.
    expect(checksHeightBudget(paneHeight: 700, textScale: 0.8),
        700 - kChecksReserveBelow);
    expect(checksHeightBudget(paneHeight: 700, textScale: double.nan),
        700 - kChecksReserveBelow);
  });

  test('⚠️ есть пол: тесное окно не складывает интерфейс сам на себя', () {
    // Ровно та беда, что дала откаченная попытка: содержимому оставили меньше,
    // чем занимает кнопка, и подписи легли друг на друга. Пусть лучше срежется
    // низ — это видно и понятно, а наложение выглядит поломкой приложения.
    // Пол 186: плашка 38 + кнопка 148. Ниже — кнопка не помещается физически.
    expect(checksHeightBudget(paneHeight: 300), 186);
    expect(checksHeightBudget(paneHeight: 210), 186);
    expect(checksHeightBudget(paneHeight: 0), double.infinity);
  });

  test('⚠️ неограниченная высота остаётся неограниченной', () {
    // Узкий телефон прокручивается целиком (`_MaybeScroll`), и `LayoutBuilder`
    // внутри прокрутки отдаёт бесконечность. Вернуть здесь число значило бы
    // сжимать блок там, где сжимать не от чего, — то есть испортить телефон
    // правкой, сделанной ради тесного окна на ПК.
    expect(checksHeightBudget(paneHeight: double.infinity), double.infinity);
    expect(checksHeightBudget(paneHeight: double.nan), double.infinity);
  });

  /// ⚠️ ПЛАШКА KILL SWITCH И СТРОКА ОШИБКИ ЛЕЖАТ НИЖЕ ПОТОЛКА И В РЕЗЕРВ НЕ
  /// ВХОДИЛИ ВОВСЕ.
  ///
  /// Замер ревьюера: при четырнадцати сервисах и поднятой защите панель
  /// переполнялась НА ВСЕХ окнах (964×761 — на 61 px, 980×800 — на 37,
  /// 1024×781 — на 9). Это ровно случай владельца: у него включены все
  /// четырнадцать, и красная плашка появляется в тот момент, когда интерфейс
  /// обязан быть понятным, — иначе человек выключит VPN с перепугу, то есть
  /// сделает ровно то, от чего защита оберегала.
  ///
  /// Картинку держит `test/auto_pick_placement_test.dart` (настоящая панель во
  /// всех сочетаниях врезок и при шрифте ×1,3); здесь — арифметика потолка.
  group('⚠️ врезки под потолком отодвигают потолок', () {
    test('каждая врезка вычитается, и обе сразу — тоже', () {
      const base = 700.0;
      expect(checksHeightBudget(paneHeight: base, blockingNotice: 52),
          base - kChecksReserveBelow - 52);
      expect(checksHeightBudget(paneHeight: base, errorLine: 28),
          base - kChecksReserveBelow - 28);
      // ⚠️ ОБЕ СРАЗУ — НЕ ТЕОРИЯ: ошибка подключения при поднятом kill switch
      // показывает и плашку, и строку.
      expect(
          checksHeightBudget(
              paneHeight: base, blockingNotice: 52, errorLine: 28),
          base - kChecksReserveBelow - 80);
    });

    test('⚠️ врезки не умножаются на масштаб шрифта второй раз', () {
      // Их высота уже посчитана настоящим `TextScaler`-ом по настоящему
      // тексту. Умножить ещё раз значило бы отобрать у блока проверок треть
      // высоты врезки дважды — и значки сжались бы без причины.
      expect(
          checksHeightBudget(
              paneHeight: 700, textScale: 1.3, blockingNotice: 52),
          700 - kChecksReserveBelow * 1.3 - 52);
    });

    test('⚠️ мусорное слагаемое не РАСШИРЯЕТ потолок', () {
      // Расчёт врезки приходит извне; ошибка в нём обязана стоить лишних
      // пикселей, а не наложения кнопки на счётчики.
      expect(checksHeightBudget(paneHeight: 700, blockingNotice: -100),
          700 - kChecksReserveBelow);
      expect(checksHeightBudget(paneHeight: 700, errorLine: double.nan),
          700 - kChecksReserveBelow);
      expect(checksHeightBudget(paneHeight: 700, errorLine: double.infinity),
          700 - kChecksReserveBelow);
    });

    test('пол держится и под врезками', () {
      // Врезка не имеет права сложить интерфейс сам на себя: пусть лучше
      // срежется низ — это видно и понятно, а наложение выглядит поломкой.
      expect(checksHeightBudget(paneHeight: 400, blockingNotice: 300), 186);
    });
  });

  test('чем выше окно, тем больше места — монотонно', () {
    var prev = 0.0;
    for (final h in [400.0, 600.0, 800.0, 1200.0, 2000.0]) {
      final got = checksHeightBudget(paneHeight: h);
      expect(got, greaterThanOrEqualTo(prev));
      prev = got;
    }
  });
}
