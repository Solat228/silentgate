import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/ui/home_screen.dart';

/// БЛОКУ ПРОВЕРОК ДАЁТСЯ ПОТОЛОК, А НЕ ДОЛЯ ОСТАТКА.
///
/// ⚠️ ЖАЛОБА ВЛАДЕЛЬЦА 03.09.2026 (со снимком целого окна): «хочу, чтобы всё
/// было вписано в это разрешение» — при четырнадцати сервисах блок с
/// информацией о подключении уезжал за край, при шести срезались счётчики.
///
/// ⚠️ ПОЧЕМУ ЭТО ВООБЩЕ СЛУЧИЛОСЬ. Сжатие блока по высоте написано и подключено
/// давно (`ServiceChecksSides` → `FittedBox`), но включается только при
/// `constraints.hasBoundedHeight`. А блок стоит ребёнком `Column`, и дети
/// `Column` получают `maxHeight: infinity` — значит условие не выполнялось
/// НИКОГДА. Код был, вызывался и не делал ничего: тот же почерк, что у связок
/// провайдеров без `lazy: false`.
///
/// ⚠️ ПЕРВАЯ ПОПЫТКА ПОЧИНИТЬ БЫЛА НЕВЕРНОЙ И ОТКАЧЕНА (коммит 1b9560e). Блок
/// обернули в `Flexible` — он сжал содержимое НИЖЕ минимума, и на снимке из VM
/// «Автонастройка» легла поверх кнопки Connect. Отсюда пол в расчёте.
///
/// ⚠️ ЧЕГО ЭТОТ ТЕСТ НЕ ДОКАЗЫВАЕТ. Он проверяет ЧИСЛО, а не картинку. Стража
/// на саму панель написать нечем: `_ConnectPane` приватна и в тест не
/// поднимается — именно поэтому дефект и проскочил мимо всех стражей вёрстки,
/// которые поднимают публичный `ConnectCenterpiece` с его собственными
/// ограничениями. Картинку проверяем глазами в VM, тест держит арифметику.
void main() {
  test('в тесном окне потолок оставляет место блоку под кнопкой', () {
    // Минимум окна Windows — 980×800; на панель приходится примерно 700.
    final got = checksHeightBudget(paneHeight: 700);
    expect(got, lessThan(700),
        reason: 'без вычета резерва блок снизу опять уедет за край');
    // ⚠️ 214: подпись ушла наверх, но «Автонастройка» при меньшем резерве срезалась: подпись «Доступность сервисов…» переехала
    // НАВЕРХ, над блоком, и её строка из резерва ушла. Число списано с
    // кода, а проверяется здесь другое — что резерв вообще вычитается.
    expect(got, 700 - 214);
  });

  test('⚠️ есть пол: тесное окно не складывает интерфейс сам на себя', () {
    // Ровно та беда, что дала откаченная попытка: содержимому оставили меньше,
    // чем занимает кнопка, и подписи легли друг на друга. Пусть лучше срежется
    // низ — это видно и понятно, а наложение выглядит поломкой приложения.
    expect(checksHeightBudget(paneHeight: 300), 200);
    expect(checksHeightBudget(paneHeight: 210), 200);
    expect(checksHeightBudget(paneHeight: 0), double.infinity);
  });

  test('⚠️ неограниченная высота остаётся неограниченной', () {
    // Узкий телефон прокручивается целиком (`_MaybeScroll`), и `LayoutBuilder`
    // внутри прокрутки отдаёт бесконечность. Вернуть здесь число значило бы
    // сжимать блок там, где сжимать не от чего, — то есть испортить телефон
    // правкой, сделанной ради тесного окна на ПК.
    expect(checksHeightBudget(paneHeight: double.infinity), double.infinity);
    expect(checksHeightBudget(paneHeight: double.nan), double.infinity);
  });

  test('чем выше окно, тем больше места — монотонно', () {
    var prev = 0.0;
    for (final h in [400.0, 600.0, 800.0, 1200.0, 2000.0]) {
      final got = checksHeightBudget(paneHeight: h);
      expect(got, greaterThanOrEqualTo(prev));
      prev = got;
    }
  });
}
