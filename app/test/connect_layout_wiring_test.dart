import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// ⚠️ ВЫБРАННАЯ РАСКЛАДКА ОБЯЗАНА ДОХОДИТЬ ДО ВИДЖЕТА.
///
/// ⚠️ ЭТОТ БАГ В ПРОЕКТЕ УЖЕ БЫЛ ДВАЖДЫ: раскладку писали, а в вызов включить
/// забывали — человек выбирал новое оформление и продолжал видеть старое, при
/// том что код новой раскладки лежал в репозитории и даже покрывался тестами.
/// Здесь ловушка та же по устройству: у `ConnectCenterpiece.layout` есть
/// значение по умолчанию (оно нужно десятку существующих тестов, которые
/// поднимают виджет без параметра), поэтому ЗАБЫТЫЙ параметр компилятор не
/// поймает — вызов молча получит `rows` вместо выбора пользователя.
///
/// Проверить это прогоном виджета нельзя: тест сам передаёт раскладку и потому
/// всегда зелёный. Единственное честное место проверки — исходник настоящего
/// экрана.
void main() {
  /// Исходник без комментариев: упоминание в пояснении не должно считаться
  /// доказательством того, что параметр действительно передан.
  String code(String path) => File(path)
      .readAsLinesSync()
      .where((l) {
        final t = l.trimLeft();
        return !t.startsWith('//') && !t.startsWith('///');
      })
      .join(String.fromCharCode(10));

  group('⚠️ Страж по исходнику: раскладка доходит до виджета', () {
    late String home;
    setUp(() => home = code('lib/ui/home_screen.dart'));

    test('⚠️ настоящий экран передаёт выбранную раскладку', () {
      final at = home.indexOf('ConnectCenterpiece(');
      expect(at, greaterThan(0),
          reason: 'виджет середины главного экрана не вызывается вовсе');
      expect(home.substring(at, at + 600),
          contains('layout: settings.serviceChecksLayout'),
          reason: 'выбор пользователя не доходит до виджета — вызов получит '
              'значение по умолчанию, и настройка станет декоративной');
    });

    test('⚠️ раскладка берётся из настроек, а не из зашитого значения', () {
      // Прямое указание конкретной раскладки в боевом вызове означало бы, что
      // настройка есть, а выбор игнорируется.
      final at = home.indexOf('ConnectCenterpiece(');
      final call = home.substring(at, at + 600);
      for (final v in const ['adaptive', 'rows', 'sides', 'grid', 'hidden']) {
        expect(call.contains('layout: ServiceChecksLayout.$v'), isFalse,
            reason: 'в боевом вызове зашита раскладка «$v» вместо настройки');
      }
    });
  });
}
