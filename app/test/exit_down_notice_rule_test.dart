import 'package:flutter_test/flutter_test.dart';
import 'package:silentgate/engine/engine_base.dart';

/// КОГДА О МЁРТВОМ ВЫХОДЕ ГОВОРИТЬ ЧЕЛОВЕКУ, А КОГДА МОЛЧАТЬ.
///
/// ⚠️ ЖАЛОБА ВЛАДЕЛЬЦА 03.09.2026. Он получил ШЕСТЬ заметок подряд, накрывших
/// пол-экрана: «Германия 2.7», «Польша 1.1», «Нидерланды 1.1», «Германия 1.1»,
/// «Эстония 1.1», «Германия 2.9». Столько выходов не умирает одновременно —
/// умер общий для них ответчик (Clash API ядра либо сам запрос задержки).
/// Шесть заметок были шестью ошибками сразу.
///
/// Тот же урок в проекте уже усвоен на сервис-чипах: четырнадцать красных
/// кружков человек читает как «не работает ничего», хотя проверялось ядро,
/// которое ещё не встало.
void main() {
  test('один выход из нескольких — говорим', () {
    expect(VpnEngineBase.tellUserExitDown(down: 1, total: 6), isTrue);
    expect(VpnEngineBase.tellUserExitDown(down: 5, total: 6), isTrue);
  });

  test('⚠️ ВСЕ выходы разом — молчим: это отказ пробы', () {
    expect(VpnEngineBase.tellUserExitDown(down: 6, total: 6), isFalse);
    expect(VpnEngineBase.tellUserExitDown(down: 2, total: 2), isFalse);
  });

  test('⚠️ единственный выход — говорим ВСЕГДА', () {
    // Иначе правило «все разом» съело бы единственный настоящий случай:
    // при одном выходе «все» и «один» — одно и то же, и молчание означало бы
    // не сказать никогда.
    expect(VpnEngineBase.tellUserExitDown(down: 1, total: 1), isTrue);
  });
}
