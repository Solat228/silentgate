/// Длительность сессии в человеческом виде — ОДИН источник на всё приложение.
///
/// ⚠️ ЖИВЁТ ЗДЕСЬ, А НЕ В ВИДЖЕТЕ, И ЭТО НЕ УБОРКА РАДИ УБОРКИ. Счётчик
/// показывается в двух разных местах — под кнопкой Connect и в шторке
/// «Информация о сервере», — и это РАЗНЫЕ виджеты в разных файлах. Формула,
/// скопированная во второе место, разъезжается с первым на первой же правке
/// (кто-то добавит дни, кто-то поменяет разделитель), и пользователь увидит
/// два несовпадающих числа про одно и то же подключение. Такое расхождение
/// не ловится ни компилятором, ни тестом отдельного виджета.
String formatUptime(Duration d) {
  final total = d.inSeconds;
  final hh = total ~/ 3600;
  final mm = (total ~/ 60) % 60;
  final ss = total % 60;
  String two(int v) => v.toString().padLeft(2, '0');
  // «7:12» до часа, дальше «1:07:12» — как в плеере: ведущий ноль у минут не
  // нужен, а у секунд обязателен, иначе цифры прыгают при переходе через 10.
  return hh > 0 ? '$hh:${two(mm)}:${two(ss)}' : '$mm:${two(ss)}';
}
