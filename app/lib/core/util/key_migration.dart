import '../parser/share_link_parser.dart';

/// Перевод сохранённых данных на канонические ключи серверов.
///
/// ⚠️ ЗАЧЕМ ЭТО НУЖНО И ЧТО БЫЛО БЕЗ НЕГО. Ключ сервера — его share-ссылка, и
/// по ключу лежат пин, ручная правка и результат пинга. Одни и те же данные
/// приходят в разных написаниях: у gRPC имя сервиса бывает `serviceName=`, а
/// бывает `path=`. Разбор понимал оба, сборка писала одно — и ключ зависел от
/// того, каким форматом ответила панель (Remnawave выбирает его по
/// `User-Agent`). Стоило формату смениться, как ВСЕ gRPC-серверы получали новые
/// ключи, а сохранённое по старым осиротевало.
///
/// Замерено на живых данных владельца 13.08.2026: из 374 результатов пинга
/// осиротели 273, из них 190 gRPC.
///
/// Канонизацию ключа чинит парсер; здесь — перенос УЖЕ СОХРАНЁННОГО.
///
/// ⚠️ Функции чистые и идемпотентные: повторный прогон ничего не портит.
/// Это важно, потому что зовутся они при каждой загрузке, а не один раз.
class KeyMigration {
  /// Перенести ключи словаря на канонические.
  ///
  /// [merge] решает столкновение, когда два старых ключа сводятся в один
  /// канонический (так бывает, если сервер лежал в обоих написаниях сразу).
  ///
  /// ⚠️ БЕЗ [merge] ПОБЕЖДАЕТ ПЕРВОЕ ВХОЖДЕНИЕ — А ЭТО, КАК ПРАВИЛО, САМАЯ
  /// СТАРАЯ ЗАПИСЬ. Прежний комментарий обещал обратное («у первого больше
  /// шансов быть тем, что пользователь видел последним»), и это была неправда:
  /// словарь на диске хранит порядок вставки, прочитанное с диска ложится в
  /// него первым, а свежие измерения дописываются в конец. Там, где значение
  /// имеет ВРЕМЯ (результаты пинга и скорости), вызывающий обязан передать
  /// [merge] и выбрать свежее — так делает `ResultsStore.migrate`. Для пинов и
  /// ручных правок первое вхождение выбрано осознанно: там это порядок,
  /// заданный человеком, а не хронология.
  static Map<String, T> remapMap<T>(
    Map<String, T> src, {
    T Function(T existing, T incoming)? merge,
    String? logLabel,
  }) {
    if (src.isEmpty) return src;
    final out = <String, T>{};
    var moved = 0;
    src.forEach((key, value) {
      final canon = ShareLinkParser.canonicalKey(key);
      if (canon != key) moved++;
      final have = out[canon];
      out[canon] = have == null ? value : (merge?.call(have, value) ?? have);
    });

    // ⚠️ ПРОФИЛИ ПАНЕЛИ — ВТОРЫМ ПРОХОДОМ И ПЕРЕНОСОМ, А НЕ ДУБЛЕМ.
    //
    // Вторым проходом — потому что настоящая запись по новому ключу (её пишет
    // уже исправленная версия) сильнее старой: старая общая на все подписки и
    // неизвестно, чью именно проверку показывает. Поэтому псевдоним заполняет
    // только пустое место и никогда не перебивает существующее.
    //
    // Переносом — потому что дубль оказался НЕВЫКЛЮЧАЕМЫМ. Прежде старая запись
    // оставалась рядом с новой и копировалась в неё при КАЖДОЙ загрузке, а
    // снимают правку `AppState.clearOverride`/`setJsonOverride` только по
    // каноническому ключу. Снятая руками правка JSON (или вариация) у профиля
    // «Авто», заведённая до 1.4.2, воскресала после перезапуска — и снять её
    // было нечем вообще.
    //
    // ⚠️ Кто читает ключи из файла, который канонизацию не проходит
    // (`subscriptions.json` со списком серверов), обязан спросить
    // [panelAliasOf] сам: там старый ключ остаётся и после переноса. Так делает
    // `AppState._serverFromStoredLink` — без этого профиль «Авто» пропал бы из
    // списка, потому что его конфиг уже уехал на новый ключ.
    var aliased = 0;
    for (final entry in Map<String, T>.from(out).entries) {
      final alias = _panelAliases[entry.key];
      if (alias == null) continue;
      out.remove(entry.key);
      if (out.containsKey(alias)) continue; // запись по новому ключу сильнее
      out[alias] = entry.value;
      aliased++;
    }

    _report(logLabel, moved, src.length, out.length, aliased);
    return out;
  }

  // ── Профили «Авто …» от панели ──────────────────────────────────────────────

  /// Псевдонимы: ключ профиля до 1.4.2 (`panel://<имя>`) → нынешний
  /// (`panel://<имя>?sub=<отпечаток подписки>`).
  ///
  /// ⚠️ СПИСОК, А НЕ ПРАВИЛО, И ЭТО ВЫНУЖДЕННО: из старого ключа отпечаток
  /// подписки не вывести — его в нём никогда не было. Заполняет список тот, у
  /// кого на руках сам конфиг панели.
  ///
  /// ⚠️ ЗАПОЛНЯЕТСЯ ПРИ ЧТЕНИИ `panel_outbounds.json`
  /// (`PanelOutboundsStore.load` → `XrayJsonSubscription.registerLegacyPanelKeys`)
  /// и при разборе свежей подписки. Порядок задан явно там, где цена ошибки
  /// необратима: `AppState.init()` читает конфиги панели ПЕРВЫМИ, до правок
  /// серверов и пинов — эти переезжают вместе с конфигом.
  ///
  /// ⚠️ СПИСОК СЕРВЕРОВ ПОДПИСКИ СЮДА НЕ ВХОДИТ. `subscriptions.json` ключи не
  /// канонизирует вовсе: там остаётся старая ссылка, пока состав не сохранят
  /// заново. Спасает не миграция, а разовый фолбэк при чтении
  /// (`AppState._serverFromStoredLink` спрашивает `panelAliasOf`) — то есть
  /// профиль поднимается, но запись на диске так и остаётся старой.
  ///
  /// ⚠️ НА ВСЕХ ЧИТАТЕЛЕЙ СРАЗУ ЭТО НЕ РАСПРОСТРАНЯЕТСЯ, И ОБЕЩАТЬ ТАКОГО
  /// НЕЛЬЗЯ. `ProbeController` с результатами пинга поднимается отдельно от
  /// `AppState`, и кто из них прочитает первым — не задано ничем. Проиграет
  /// профиль — его прошлый пинг останется по старому ключу и покажется как «не
  /// проверен»; сама запись при этом цела и переедет на той загрузке, где
  /// конфиги панели будут прочитаны раньше (либо её заменит новый замер).
  static final Map<String, String> _panelAliases = {};

  static void registerPanelKey(String legacy, String canonical) {
    if (legacy.isEmpty || canonical.isEmpty || legacy == canonical) return;
    _panelAliases[legacy] = canonical;
  }

  /// Нынешний ключ профиля по его старому написанию (null — псевдонима нет).
  static String? panelAliasOf(String legacy) => _panelAliases[legacy];

  /// Забыть псевдонимы. ⚠️ Только для тестов: список статический и живёт весь
  /// процесс, поэтому без сброса тесты подсказывали бы ответы друг другу.
  static void resetPanelKeys() => _panelAliases.clear();

  /// Перенести список ключей (пины) на канонические, сохранив ПОРЯДОК.
  ///
  /// ⚠️ Порядок здесь — пользовательский: пины показываются сверху списка
  /// именно в нём. Дубли после сведения убираем, оставляя первое вхождение.
  ///
  /// ⚠️ ПСЕВДОНИМЫ ПРОФИЛЕЙ ПРИМЕНЯЮТСЯ И ЗДЕСЬ — ИНАЧЕ ПИН РАСХОДИЛСЯ С
  /// КОНФИГОМ. Конфиг профиля [remapMap] переносит на новый ключ, а закреплён
  /// профиль был по старому: остался бы пин, указывающий в пустоту, и профиль
  /// исчез бы из списка. Оба хранилища обязаны переезжать вместе, поэтому
  /// правило одно на карту и на список. Псевдонима нет — ключ остаётся старым,
  /// и конфиг остаётся по старому там же (`PanelOutboundsStore` заводит
  /// псевдоним ровно тогда, когда сам его и переносит).
  static List<String> remapList(List<String> src, {String? logLabel}) {
    if (src.isEmpty) return src;
    final out = <String>[];
    final seen = <String>{};
    var moved = 0;
    var aliased = 0;
    for (final key in src) {
      var canon = ShareLinkParser.canonicalKey(key);
      final alias = _panelAliases[canon];
      if (alias != null) {
        canon = alias;
        aliased++;
      }
      if (canon != key) moved++;
      if (seen.add(canon)) out.add(canon);
    }
    _report(logLabel, moved, src.length, out.length, aliased);
    return out;
  }

  /// Куда писать отчёт о переносе.
  ///
  /// ⚠️ ХУК, А НЕ ПРЯМОЙ ВЫЗОВ `AppLog`, И ЭТО НЕ УКРАШЕНИЕ. Этот файл читают
  /// настройки (`AppSettings.fromJson`), а рядом с их импортами стоит явное
  /// предупреждение: `app_log` тянет `app_paths` → `path_provider` →
  /// `package:flutter` → `dart:ui`, из-за чего переставали работать
  /// `dart run tool/emit_*.dart`. Хук ставится один раз при запуске приложения.
  static void Function(String message)? onReport;

  static void _report(
      String? label, int moved, int before, int after, int aliased) {
    final log = onReport;
    if (log == null || label == null || (moved == 0 && aliased == 0)) return;
    // Пишем в журнал ТОЛЬКО счётчики: сами ключи — это ссылки с учётными
    // данными, им в логе не место (тот же запрет, что для токена подписки).
    // ⚠️ Псевдоним теперь ПЕРЕНОСИТ запись, а не дублирует, поэтому число
    // записей от него не растёт и поправка на него больше не нужна.
    final lost = before - after;
    log('Миграция ключей ($label): приведено $moved из $before'
        '${lost > 0 ? ', сведено дублей: $lost' : ''}'
        '${aliased > 0 ? ', профилей панели перенесено: $aliased' : ''}');
  }
}
