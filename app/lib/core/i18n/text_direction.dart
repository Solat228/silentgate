import 'package:flutter/widgets.dart';

/// Направление текста по его СОДЕРЖИМОМУ (первый «сильный» символ), а не по языку
/// приложения. Для провайдерских/пользовательских строк — название подписки,
/// объявление, notice-сообщение, имена серверов: латиница/кириллица → LTR (имена
/// НЕ зеркалятся даже в арабском/фарси интерфейсе), арабский/иврит/фарси → RTL
/// (текст читается правильно). Слабые символы (цифры, пунктуация, эмодзи-флаги,
/// пробелы) не решают — идём к следующему. По умолчанию LTR.
///
/// `null`/пусто → `null` (пусть наследует направление от локали — например, для
/// пустых значений, где показывается локализованный фолбэк).
TextDirection? autoTextDirection(String? text) {
  final s = text ?? '';
  if (s.trim().isEmpty) return null;
  for (final r in s.runes) {
    // RTL: иврит (0590–05FF), арабский+фарси/урду (0600–06FF), доп. арабский
    // (0750–077F), арабские презентационные формы (FB1D–FEFF).
    if ((r >= 0x0590 && r <= 0x06FF) ||
        (r >= 0x0750 && r <= 0x077F) ||
        (r >= 0xFB1D && r <= 0xFEFF)) {
      return TextDirection.rtl;
    }
    // Сильные LTR-буквы: латиница (0041–024F), греческий/кириллица (0370–052F).
    if ((r >= 0x0041 && r <= 0x024F) || (r >= 0x0370 && r <= 0x052F)) {
      return TextDirection.ltr;
    }
    // остальное (цифры/пунктуация/эмодзи/пробелы) — не решает, продолжаем.
  }
  return TextDirection.ltr;
}
