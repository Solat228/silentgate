import 'package:flutter/widgets.dart';

/// Направление текста по его СОДЕРЖИМОМУ (первый «сильный» символ), а не по языку
/// приложения. Для провайдерских/пользовательских строк — название подписки,
/// объявление, notice-сообщение, имена серверов: латиница/кириллица → LTR (имена
/// НЕ зеркалятся даже в арабском/фарси интерфейсе), арабский/иврит/фарси → RTL
/// (текст читается правильно). Слабые символы (цифры, пунктуация, эмодзи-флаги,
/// пробелы) не решают — идём к следующему. По умолчанию LTR.
///
/// `null`/пусто → `null` (пусть наследует направление от локали — например, для
/// пустых значений, где показывается локализованный фолбэк).
TextDirection? autoTextDirection(String? text) {
  final s = text ?? '';
  if (s.trim().isEmpty) return null;
  for (final r in s.runes) {
    // RTL: иврит, арабский, сирийский, тана, нко (0590–08FF), презентационные
    // формы иврита и арабского-A (FB1D–FDFF) и арабского-B (FE70–FEFC).
    //
    // ⚠️ НЕ «FB1D–FEFF» целиком: туда попадали селекторы вариантов
    // (FE00–FE0F) — U+FE0F стоит за каждым вторым эмодзи, и «❤️ Name»
    // уходило справа налево (аудит 25.10.2026, I). И BOM (FEFF) тоже.
    if ((r >= 0x0590 && r <= 0x08FF) ||
        (r >= 0xFB1D && r <= 0xFDFF) ||
        (r >= 0xFE70 && r <= 0xFEFC)) {
      return TextDirection.rtl;
    }
    if (_isStrongLtr(r)) return TextDirection.ltr;
    // остальное (цифры/пунктуация/эмодзи/пробелы) — не решает, продолжаем.
  }
  return TextDirection.ltr;
}

/// Буквы письменностей слева направо. Только БУКВЫ: прежний диапазон
/// 0041–024F включал `[`, `_`, `{`, `©`, `×` и подобное — скобка перед
/// арабским названием делала его LTR.
bool _isStrongLtr(int r) =>
    (r >= 0x41 && r <= 0x5A) ||
    (r >= 0x61 && r <= 0x7A) ||
    (r >= 0xC0 && r <= 0x24F && r != 0xD7 && r != 0xF7) ||
    (r >= 0x370 && r <= 0x52F && r != 0x37E && r != 0x387) ||
    // CJK, кана, хангыль — тоже слева направо.
    (r >= 0x3040 && r <= 0x9FFF) ||
    (r >= 0xAC00 && r <= 0xD7AF);
