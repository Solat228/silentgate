/// Приватные и служебные диапазоны — вместо ссылки `geoip:private`.
///
/// ⚠️ Зачем список, а не категория. Любое упоминание `geoip:` заставляет
/// Xray загрузить `geoip.dat` (18,9 МБ), иначе ядро не стартует вовсе. При
/// этом НАШИ собственные конфиги ссылались ровно на одну категорию —
/// `geoip:private`, — то есть 19 МБ поставки существовали ради фиксированного
/// списка подсетей, который меняется раз в десятилетие.
///
/// Со списком гео-файлы нужны только панельным профилям «Авто»: они приходят
/// с сервера со своими правилами (`geoip:ru` и подобное) и подгружают базы
/// по требованию.
///
/// Состав повторяет категорию `private` из
/// github.com/v2fly/geoip (RFC 1918, RFC 6598, loopback, link-local,
/// broadcast, multicast и их IPv6-аналоги).
const kPrivateNetworksV4 = <String>[
  '0.0.0.0/8', // «этот» хост
  '10.0.0.0/8', // RFC 1918
  '100.64.0.0/10', // RFC 6598, CGNAT
  '127.0.0.0/8', // loopback
  '169.254.0.0/16', // link-local (APIPA)
  '172.16.0.0/12', // RFC 1918
  '192.0.0.0/24', // IETF protocol assignments
  '192.0.2.0/24', // TEST-NET-1
  '192.168.0.0/16', // RFC 1918
  '198.18.0.0/15', // benchmark
  '198.51.100.0/24', // TEST-NET-2
  '203.0.113.0/24', // TEST-NET-3
  '224.0.0.0/4', // multicast
  '240.0.0.0/4', // зарезервировано + broadcast
];

/// ⚠️ Здесь НЕТ `::ffff:0:0/96` (IPv4-mapped) и `64:ff9b::/96` (NAT64), хотя в
/// категории `private` они есть: маршрутизатор Xray разбирает такие адреса как
/// IPv4 и отвергает маску /96 целиком — «invalid network mask for router: 96»,
/// то есть ядро не стартует вовсе. Проверено настоящим `xray run -test`.
/// Потери нет: IPv4-mapped диапазон уже покрыт списком v4 выше.
const kPrivateNetworksV6 = <String>[
  '::/128', // не указан
  '::1/128', // loopback
  '100::/64', // discard-only
  '2001::/32', // Teredo
  '2001:10::/28', // ORCHID
  '2001:db8::/32', // документация
  'fc00::/7', // unique local
  'fe80::/10', // link-local
  'ff00::/8', // multicast
];

/// Полный список для поля `ip` в правилах Xray.
const kPrivateNetworks = <String>[...kPrivateNetworksV4, ...kPrivateNetworksV6];
