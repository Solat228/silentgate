/// Оценка сервера с учётом скорости — «взвешенно относительно своего канала».
///
/// ## Зачем не просто «кто быстрее»
///
/// Абсолютные мегабиты сами по себе бессмысленны: если канал пользователя даёт
/// 50 Мбит/с, то сервер на 300 Мбит/с и сервер на 60 Мбит/с для него одинаковы —
/// оба упрутся в его же канал. Поэтому скорость считается ДОЛЕЙ от собственной
/// скорости, и доля насыщается: всё, что даёт [_saturation] и выше, получает
/// полный балл, а дальше решает задержка.
///
/// Без насыщения выбор уезжал бы к серверу, который «быстрее на бумаге», но
/// отвечает вдвое дольше, — и человеку становилось бы хуже, а не лучше.
class SpeedScore {
  /// Доля собственного канала, начиная с которой сервер считается «не узким
  /// местом». 0.9, а не 1.0: замеры шумят, и требовать точного совпадения
  /// значило бы наказывать сервер за случайный провал на пол-процента.
  static const _saturation = 0.9;

  /// Задержка, при которой множитель падает вдвое. 200 мс — граница, за которой
  /// отклик уже заметен человеку в разговоре и в игре.
  static const _halfLatencyMs = 200.0;

  /// Вес скорости против веса задержки. Скорости больше, потому что задержка уже
  /// участвует в отборе кандидатов до замера.
  static const _speedWeight = 0.65;

  /// Итоговая оценка, 0..1 — больше значит лучше.
  ///
  /// [serverMbps] — скорость через сервер, [ownMbps] — скорость собственного
  /// канала мимо VPN, [latencyMs] — задержка через сервер.
  ///
  /// Если своя скорость неизвестна или нулевая, сравнивать не с чем: тогда
  /// сервера сравниваются между собой по лучшему из них — это честнее, чем
  /// молча выкинуть скорость из оценки.
  static double of({
    required double? serverMbps,
    required double? ownMbps,
    required int? latencyMs,
    double? bestServerMbps,
  }) {
    final latencyPart = _latencyPart(latencyMs);
    if (serverMbps == null || serverMbps <= 0) {
      // Скорость не замерили — оцениваем только по задержке, но с понижением:
      // сервер без замера не должен обгонять измеренный и подтверждённо быстрый.
      return latencyPart * (1 - _speedWeight);
    }
    final reference = (ownMbps != null && ownMbps > 0)
        ? ownMbps
        : (bestServerMbps != null && bestServerMbps > 0
            ? bestServerMbps
            : serverMbps);
    final share = (serverMbps / (reference * _saturation)).clamp(0.0, 1.0);
    return _speedWeight * share + (1 - _speedWeight) * latencyPart;
  }

  static double _latencyPart(int? latencyMs) {
    if (latencyMs == null || latencyMs < 0) return 0.0;
    return 1 / (1 + latencyMs / _halfLatencyMs);
  }

  /// Человеческое пояснение, почему сервер занял своё место.
  ///
  /// Нужно рядом с цифрой: «0,79» пользователю не говорит ничего, а «даёт 95 %
  /// вашего канала при 200 мс» — говорит.
  static int? sharePercent({double? serverMbps, double? ownMbps}) {
    if (serverMbps == null || ownMbps == null || ownMbps <= 0) return null;
    return ((serverMbps / ownMbps) * 100).round().clamp(0, 999);
  }
}
