export '../xray/harness_config_builder.dart' show HarnessEntry, HarnessPorts;

/// Проброс-харнесс: отдельный экземпляр движка (Xray) с http-inbound'ами на 127.0.0.1,
/// по одному на кандидата. Используется для пинга «via Proxy» и проб автонастройки.
/// НИКОГДА не устанавливает системный прокси.
abstract class ProbeHarness {
  /// Запускает харнесс для набора кандидатов. Порядок [entries] задаёт индексы портов.
  Future<HarnessHandle> start(List<HarnessEntry> entries);

  /// Можно ли пропускать через кандидата ПРОИЗВОЛЬНЫЕ запросы.
  ///
  /// Windows поднимает http-инбаунд и отдаёт порт — через него проверяется хоть
  /// YouTube, хоть ChatGPT. Android меряет через `LibXray.ping`: ядро
  /// поднимается ВНУТРИ вызова, возвращает миллисекунды и тут же гаснет, порта
  /// наружу нет вовсе. Задержку это даёт, доступность СЕРВИСОВ — нет.
  ///
  /// ⚠️ Флаг нужен, чтобы отличать «не удалось поднять» от «здесь так не
  /// работает». Автонастройка проверяла `proxyPortFor() <= 0` и молча
  /// пропускала кандидата — на Android это верно ВСЕГДА, поэтому подбор
  /// показывал ход по всем серверам и заканчивался «найдено 0» на полностью
  /// рабочей подписке, не написав в лог ни строчки.
  bool get supportsProxyRequests => true;
}

abstract class HarnessHandle {
  /// Локальный http-прокси порт для кандидата с индексом [index] (0-based).
  ///
  /// **Может вернуть -1**: часть кандидатов обслуживает второе ядро, и если оно
  /// не поднялось, остальные всё равно проверяются. Вызывающий обязан считать
  /// неположительный порт отсутствием прокси, а не портом.
  int proxyPortFor(int index);

  /// Остановить харнесс (убить процесс движка).
  /// Готовая задержка кандидата, если платформа меряет её САМА и порта не
  /// даёт (Android: `LibXray.ping` возвращает миллисекунды, а не поднимает
  /// прокси). `null` — мерить через [proxyPortFor], как на Windows.
  Future<int?> delayMs(int index) async => null;

  Future<void> stop();
}
