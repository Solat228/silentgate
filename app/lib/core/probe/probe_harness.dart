/// Свежий пароль инбаундов харнесса — НА КАЖДЫЙ ПРОГОН.
///
/// ⚠️ `Random.secure`, а не `Random()`: обычный генератор предсказуем, и пароль
/// от порта, ведущего в туннель, обязан быть криптографическим.
///
/// ⚠️ ПАРОЛЬ ПИШЕТСЯ НА ДИСК — НА ОБЕИХ ПЛАТФОРМАХ. Здесь до 1.4.2 стояло
/// «живёт только в памяти процесса: на диск не пишется», и это было неправдой
/// с самого начала: ядру конфиг передаётся ТОЛЬКО файлом (`xray.exe -c <путь>`,
/// `LibXray.ping(configPath)`), а пароль лежит внутри него — в
/// `inbounds[].settings.accounts` у Xray и в `inbounds[].users` у sing-box.
/// По этому абзацу принимают решения о модели угроз, поэтому дословно, где он
/// оказывается и кто его убирает:
///
///   * **Android** — `<каталог данных приложения>/probe_<i>.json`, по файлу на
///     кандидата (`ProbeHarnessAndroid.start`). Убирает их `stop()` в конце
///     прогона, а если запись упала на полпути — сам `start()` перед тем, как
///     бросить исключение (хендла ещё нет, и звать `stop()` вызывающему не на
///     чем). Каталог приложения приватный: соседнему приложению он без root
///     недоступен — в отличие от самого порта, который на loopback открыт
///     любому, у кого есть разрешение INTERNET (ради этого пароль и заведён).
///   * **Windows** — `%APPDATA%\SilentGate\harness_config.json` (Xray) и
///     `%APPDATA%\SilentGate\singbox_harness.json` (sing-box). ⚠️ ИХ НЕ УДАЛЯЕТ
///     НИКТО: `stop()` там гасит процесс ядра и на этом заканчивается, файл
///     лежит до следующего прогона, который его перезапишет. То есть пароль
///     последнего прогона доступен на диске всё время между прогонами — как и
///     учётные данные проверявшихся серверов, которые в том же файле.
///     Единственное, что ограничивает ущерб: к моменту, когда прогон окончен,
///     процесс ядра убит и порт больше не слушает, — вести этот пароль уже
///     некуда, а следующий харнесс поднимется с новым.
///
/// Что здесь ПРАВДА: между прогонами пароль не переиспользуется. Харнесс
/// создаётся заново на каждый запуск пинга, подбора и замера скорости
/// (`_harnessFactory()` в `ProbeController`), и каждый его экземпляр зовёт эту
/// функцию; общий секрет бывает только у двух ядер ОДНОГО прогона
/// (`MixedProbeHarness`), потому что наружу они выглядят одним харнессом.
/// Проверено тестом на андроидном харнессе (`local_ports_closed_test`,
/// «пароль свой на каждый прогон»); на Windows это тот же вызов в
/// конструкторе, но своего теста у него нет — процесс ядра в тестах не поднять.
String newHarnessSecret() {
  final rnd = Random.secure();
  const alphabet =
      'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
  return List.generate(24, (_) => alphabet[rnd.nextInt(alphabet.length)])
      .join();
}

/// Проброс-харнесс: отдельный экземпляр движка (Xray) с http-inbound'ами на 127.0.0.1,
/// по одному на кандидата. Используется для пинга «via Proxy» и проб автонастройки.
/// НИКОГДА не устанавливает системный прокси.
abstract class ProbeHarness {
  /// Запускает харнесс для набора кандидатов. Порядок [entries] задаёт индексы портов.
  Future<HarnessHandle> start(List<HarnessEntry> entries);

  /// Можно ли пропускать через кандидата ПРОИЗВОЛЬНЫЕ запросы.
  ///
  /// Windows поднимает http-инбаунд и отдаёт порт — через него проверяется хоть
  /// YouTube, хоть ChatGPT. Android меряет через `LibXray.ping`: ядро
  /// поднимается ВНУТРИ вызова, ходит через свой инбаунд само и возвращает
  /// готовые миллисекунды. Задержку это даёт, доступность СЕРВИСОВ — нет.
  ///
  /// ⚠️ «Порт не отдаётся» ≠ «порта нет». Инбаунд на Android такой же
  /// настоящий и всё время замера слушает 127.0.0.1 — поэтому он ОБЯЗАН быть
  /// закрыт паролем, как и на Windows (до 1.4.2 не был).
  ///
  /// ⚠️ Флаг нужен, чтобы отличать «не удалось поднять» от «здесь так не
  /// работает». Автонастройка проверяла `proxyPortFor() <= 0` и молча
  /// пропускала кандидата — на Android это верно ВСЕГДА, поэтому подбор
  /// показывал ход по всем серверам и заканчивался «найдено 0» на полностью
  /// рабочей подписке, не написав в лог ни строчки.
  bool get supportsProxyRequests => true;
}

abstract class HarnessHandle {
  /// Локальный http-прокси порт для кандидата с индексом [index] (0-based).
  ///
  /// **Может вернуть -1**: часть кандидатов обслуживает второе ядро, и если оно
  /// не поднялось, остальные всё равно проверяются. Вызывающий обязан считать
  /// неположительный порт отсутствием прокси, а не портом.
  int proxyPortFor(int index);

  /// Логин и пароль инбаундов этого харнесса.
  ///
  /// ⚠️ ОТДАЮТСЯ ВМЕСТЕ С ПОРТОМ И ЭТО НЕ УКРАШЕНИЕ. Инбаунд закрыт паролем, и
  /// потребитель обязан его предъявить — иначе ядро ответит 407, и КАЖДЫЙ
  /// сервер покажется нерабочим при исправном соединении. Ровно на этом сгорел
  /// v2rayNG (#5549): включили аутентификацию, забыли прокинуть в потребителя.
  /// Поэтому креды едут ТЕМ ЖЕ объектом, что и порт: взять порт и не взять
  /// пароль теперь надо специально постараться.
  ///
  /// Пусто — инбаунд без пароля. Так выглядят ТОЛЬКО тестовые заглушки:
  /// каждая платформенная реализация выдаёт креды (Windows — с 1.4.1,
  /// Android — с 1.4.2; там пустая пара стояла как «заглушка», хотя путь был
  /// боевым и инбаунд поднимался настоящий).
  String get proxyUser => '';
  String get proxyPassword => '';

  /// Готовая задержка кандидата, если платформа меряет её САМА и порта не
  /// даёт (Android: `LibXray.ping` возвращает миллисекунды — он поднимает
  /// инбаунд и ходит через него сам, наружу порт не отдавая). `null` — мерить
  /// через [proxyPortFor], как на Windows.
  Future<int?> delayMs(int index) async => null;

  /// Остановить харнесс: погасить экземпляр ядра (Windows — убить процесс,
  /// Android — его гасит сама нативная сторона по окончании замера).
  ///
  /// ⚠️ ПРО ВРЕМЕННЫЕ КОНФИГИ — ЧЕСТНО, ПЛАТФОРМЫ ЗДЕСЬ РАСХОДЯТСЯ. Раньше тут
  /// было написано «и убрать за собой временные конфиги», а Windows-реализация
  /// этого не делает вовсе: `harness_config.json` / `singbox_harness.json`
  /// остаются в `%APPDATA%\SilentGate` до следующего прогона вместе с паролем
  /// инбаунда и учётными данными проверявшихся серверов. Убирает за собой
  /// только Android (`probe_<i>.json`) — и он же убирает уже записанное, если
  /// `start()` упал на середине списка.
  Future<void> stop();
}
