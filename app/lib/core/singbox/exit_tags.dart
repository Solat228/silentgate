/// Теги outbound-ов и DNS-резолверов для правил, идущих через ОТДЕЛЬНЫЙ сервер.
///
/// ⚠️ ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ОБРАЗУЮТСЯ ЭТИ ИМЕНА. Разойдись построитель
/// правил и сборщик outbound-ов хоть на один символ — правило сошлётся на
/// несуществующий тег, а `sing-box check` этого НЕ ловит: конфиг со ссылкой на
/// отсутствующий outbound принимается с кодом 0 и без единой строчки вывода
/// (проверено настоящим ядром 1.11.15). Трафик такого правила молча уедет
/// в `route.final`, то есть мимо сервера, который выбрал пользователь.
library;

/// Тег прокси-outbound-а для сервера с ключом [serverKey].
String exitTagFor(String serverKey) => 'exit-${_shortId(serverKey)}';

/// Тег DNS-резолвера, ходящего через тот же сервер.
///
/// Резолв обязан идти ТЕМ ЖЕ сервером, что и трафик: иначе сайт «через
/// Германию» спросит имя у резолвера основного туннеля, CDN ответит адресом
/// ближайшего к НЕМУ фронта, и запрос уедет по немецкому маршруту на чужой
/// сервер. Такой дефект у нас уже был в 1.0.1 — тогда между «Прямо» и «Туннель».
String exitDnsTagFor(String serverKey) => 'dns-exit-${_shortId(serverKey)}';

/// Короткий стабильный идентификатор из ключа сервера.
///
/// Ключ сервера — это share-ссылка: в ней есть `@`, `:`, `?`, `&` и UUID.
/// Класть её в тег нельзя (нечитаемо, и в логах ядра засветился бы UUID
/// подписки), а порядковый номер нестабилен — список серверов перестраивается
/// при каждом обновлении подписки. Поэтому хэш: он не меняется между
/// запусками, не зависит от порядка и не раскрывает содержимое ключа.
///
/// FNV-1a 32 бита: коллизия на десятке серверов практически невозможна, а
/// главное — от неё не бывает утечки. Совпади теги у двух серверов, один из
/// них просто не соберётся, и правило честно упадёт в основной туннель
/// (см. проверку живых тегов в построителе), а не уедет к чужому серверу.
String _shortId(String serverKey) {
  var h = 0x811c9dc5;
  for (final c in serverKey.codeUnits) {
    h ^= c;
    // Умножение на простое FNV с обрезкой до 32 бит: в Dart int — 64-битный,
    // без маски хэш разъехался бы с любой другой реализацией.
    h = (h * 0x01000193) & 0xffffffff;
  }
  return h.toRadixString(16).padLeft(8, '0');
}
