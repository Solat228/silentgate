/// Перевод сетевых исключений в то, что человек может прочитать и сделать.
///
/// ⚠️ ЗАЧЕМ ЭТО ЗАВЕДЕНО. Живой клиент 05.09.2026 при импорте подписки получил
/// на экран вот такое:
///
///   HandshakeException: Handshake error in client (OS Error:
///   CERTIFICATE_VERIFY_FAILED: certificate is not yet valid
///   (../../../flutter/third_party/boringssl/src/ssl/handshake.cc:298))
///
/// Текст исключения уходил в интерфейс как есть (`_error = e.toString()`).
/// Человеку в нём нечего делать: ни слова о том, что случилось и как чинить,
/// зато есть путь к файлу внутри BoringSSL. А починка при этом целиком на его
/// стороне и занимает полминуты.
///
/// ⚠️ ПОДСКАЗКА ДАЁТСЯ ТОЛЬКО НА УЗНАННОЕ. Соблазн подстелить общий текст на
/// любую ошибку велик и вреден: человек поверит совету и пойдёт чинить не то.
/// Не узнали — пусть видит исходный текст, он хотя бы правдив и его можно
/// прислать в поддержку.
library;

/// Что именно сломалось — от этого зависит совет.
enum NetworkErrorKind {
  /// Сертификат ещё НЕ начал действовать: часы компьютера отстают.
  clockBehind,

  /// Сертификат истёк: либо часы спешат, либо он правда просрочен на сервере.
  certExpired,

  /// Сертификат выписан на другое имя.
  hostnameMismatch,

  /// Имя не резолвится или соединение не устанавливается.
  noNetwork,
}

/// Распознанная ошибка: что произошло и что делать.
class NetworkErrorHint {
  const NetworkErrorHint(this.kind, this.text);

  final NetworkErrorKind kind;

  /// Готовая фраза для интерфейса: причина и действие, без потрохов.
  final String text;
}

/// Разобрать текст исключения. `null` — не узнали, показывать как есть.
NetworkErrorHint? networkErrorHint(String raw) {
  final s = raw.toLowerCase();
  if (s.isEmpty) return null;

  // ⚠️ «NOT YET VALID» — ЭТО НЕ «ПРОСРОЧЕН», И СОВЕТ ЗДЕСЬ ДРУГОЙ.
  //
  // Сертификат ещё не начал действовать: его срок стартует позже, чем
  // показывают часы компьютера. Значит часы ОТСТАЮТ — севшая батарейка на
  // плате, сбитая дата после переустановки, отключённая синхронизация. Сервер
  // и подписка ни при чём, и «попробуйте позже» тут бессмысленный совет: само
  // это не пройдёт, пока не поставят верное время.
  if (s.contains('not yet valid')) {
    return const NetworkErrorHint(
      NetworkErrorKind.clockBehind,
      'На компьютере неверные дата и время — они отстают, поэтому сертификат '
      'сервера считается ещё не начавшим действовать. Проверьте часы Windows '
      'и включите синхронизацию времени, затем повторите импорт.',
    );
  }

  // Истёкший сертификат — обратная сторона той же монеты, но причин ДВЕ:
  // часы спешат либо он правда просрочен на сервере. Поэтому и текст другой:
  // сначала часы (это проверяется мгновенно), потом поддержка.
  if (s.contains('certificate has expired') || s.contains('cert_has_expired')) {
    return const NetworkErrorHint(
      NetworkErrorKind.certExpired,
      'Срок действия сертификата сервера истёк. Сначала проверьте дату и '
      'время на компьютере — если они спешат, ошибка будет такой же. Если '
      'время верное, сертификат просрочен на стороне сервиса: напишите в '
      'поддержку.',
    );
  }

  if (s.contains('hostname mismatch')) {
    return const NetworkErrorHint(
      NetworkErrorKind.hostnameMismatch,
      'Сертификат выписан на другое имя. Проверьте адрес подписки — возможно, '
      'в нём опечатка, либо соединение подменяет посредник.',
    );
  }

  if (s.contains('failed host lookup') ||
      s.contains('connection refused') ||
      s.contains('network is unreachable') ||
      s.contains('connection timed out')) {
    return const NetworkErrorHint(
      NetworkErrorKind.noNetwork,
      'Не удалось связаться с сервером подписки. Проверьте интернет; если он '
      'есть, адрес может быть заблокирован — попробуйте включить VPN и '
      'повторить импорт.',
    );
  }

  return null;
}
