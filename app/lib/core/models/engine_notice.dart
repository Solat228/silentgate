/// Событие движка, о котором пользователь должен узнать СРАЗУ, а не из журнала.
///
/// ## Зачем отдельная сущность, а не строка статуса
///
/// Строка под кнопкой показывает СОСТОЯНИЕ («Подключено», «Переподключение…»).
/// Она отвечает на вопрос «что сейчас», но не на вопрос «что произошло»: пока
/// пользователь не смотрит на экран, состояние успевает смениться дважды, и он
/// не узнает, что связь рвалась вовсе.
///
/// ⚠️ Ровно это и случилось у владельца 08.08.2026: VPN перестал работать, а он
/// заметил это сам, потому что приложение промолчало. Причина в том, что
/// событие «канал умер» нигде не всплывало — оно только меняло статус, который
/// через пару секунд возвращался в «Подключено».
enum EngineNoticeKind {
  /// Связь оборвалась, идёт восстановление.
  reconnecting,

  /// Связь восстановлена после неудачных попыток.
  recovered,

  /// Попытки исчерпаны — дальше только вручную.
  failed,

  /// Домен отвергнут правилом «Блок».
  ///
  /// ⚠️ Нужен потому, что показать заглушку по https невозможно: любой ответ
  /// едет внутри TLS, а для TLS нужен сертификат на чужой домен. Браузер рвёт
  /// соединение раньше, чем увидит хоть байт от нас, и пользователь получает
  /// безымянное `ERR_CONNECTION_RESET`. Объяснить причину можно только здесь.
  blocked,

  /// Профилю нужны гео-базы, а их нет на диске.
  ///
  /// ⚠️ ДО ЭТОГО ФАКТ УХОДИЛ ТОЛЬКО В ЖУРНАЛ. Движок исправно вычислял, что
  /// правила панели по странам и категориям отброшены, и писал об этом
  /// `AppLog.w` — то есть в файл, который открывают вручную. Владелец так и
  /// сказал: «предложение докачать гео-файлы как будто не происходит». Оно и
  /// не происходило: предложения не существовало, была строка в логе.
  geoAssetsMissing,

  /// Базы на диске ЕСТЬ, но ядро их не открыло.
  ///
  /// ⚠️ Отдельный вид, а не тот же самый: предлагать «скачайте» тому, у кого
  /// файлы уже скачаны, — значит послать его делать бесполезное. Здесь нужен
  /// другой совет (перекачать), и текст обязан отличаться.
  geoAssetsUnusable,

  /// Задача Планировщика `SilentGateTun` устарела (ведёт на другой exe или
  /// другие пути) — автозапуск TUN без окна UAC сломан, подключение идёт
  /// запасным путём (спрашивает права на КАЖДОМ подключении).
  ///
  /// ⚠️ ПОЧИНКА — ОДНО ОКНО UAC, А НЕ НОЛЬ. Задачу можно пересоздать вызовом
  /// `TunScheduledTask.install()`, но это тоже UAC — просто один раз, а не на
  /// каждое подключение. Владелец 29.08.2026: «Это разве не работа
  /// приложения фиксить это?» — молчаливый вечный обход через UAC не годится,
  /// а молчаливая самопочинка обманула бы ожидание «одно окно, а не десять».
  /// Поэтому это заметка с кнопкой, а не автоматическое действие.
  staleScheduledTask,

  /// Включённое правило приложения «по полному пути» указывает на файл,
  /// которого нет на диске — правило не применится в ЭТОМ подключении.
  ///
  /// ⚠️ НЕ «ПО ИМЕНИ НЕ РАБОТАЕТ» — сопоставление по имени исправно
  /// (`CHANGELOG.md` #602). Ломается путь: программа обновилась и переехала
  /// в папку с номером версии (пример владельца — `claude.exe` в
  /// `…claude-code-2.1.238-win32-x64\…`). До этой заметки факт был виден
  /// только в списке правил ([DeadPathBadge]) и в журнале — на главном экране,
  /// где человек и жмёт «Подключиться», не было ничего.
  deadAppRule,
}

class EngineNotice {
  const EngineNotice(this.kind, this.text, {this.detail});

  final EngineNoticeKind kind;

  /// Короткая строка для всплывающего сообщения.
  final String text;

  /// Уточнение: причина обрыва, имя домена. Может быть пустым.
  final String? detail;

  /// Событие требует внимания — показывается как ошибка, а не как обычная
  /// заметка.
  bool get isProblem =>
      kind == EngineNoticeKind.failed || kind == EngineNoticeKind.reconnecting;

  @override
  String toString() => 'EngineNotice(${kind.name}, $text)';
}
