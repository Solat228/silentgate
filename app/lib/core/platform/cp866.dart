/// Кодировщик текста в **CP866 (OEM-кириллица)** — кодировку, в которой `cmd`
/// читает `.bat`-файлы.
///
/// ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. `cmd` перечитывает батник ПО БАЙТОВЫМ СМЕЩЕНИЯМ
/// между командами, а не разбирает его целиком заранее. На UTF-8 многобайтные
/// символы сдвигают смещения, и исполнение продолжается С СЕРЕДИНЫ строки: в
/// выводе появляются обрывки вида `'ate-arm64-v8a.apk" >nul' is not recognized`,
/// а часть команд не выполняется вовсе. Правило проекта (`CLAUDE.md`, пункт 3):
/// батники — только в OEM-кодировке и с CRLF.
///
/// Цена ошибки здесь максимальна: единственный генератор батников в коде —
/// восстановление сети, и он запускается ОТ ИМЕНИ АДМИНИСТРАТОРА, сбрасывая
/// winsock и IP-стек. Сброс, выполнившийся наполовину, оставляет человека без
/// сети и без объяснений.
///
/// В `dart:convert` кодека cp866 нет, поэтому таблица своя. Она короткая:
/// в отличие от ISO/Windows-кодировок, кириллица в cp866 разорвана надвое
/// блоком псевдографики (0xB0…0xDF), и именно из-за этого разрыва её нельзя
/// свести к одному сдвигу.
class Cp866 {
  const Cp866._();

  /// Байт, которым заменяется символ, отсутствующий в таблице.
  ///
  /// ⚠️ ЗАМЕНА, А НЕ ПРОПУСК И НЕ СЫРОЙ UTF-8. Пропуск сдвинул бы текст, а
  /// сырой UTF-8 вернул бы ровно ту беду, от которой уходим, — одной такой
  /// буквы («…», неразрывный пробел) достаточно, чтобы cmd сбился.
  static const int _replacement = 0x3F; // '?'

  /// Кодирует [text] в байты cp866.
  ///
  /// Обход идёт по КОДОВЫМ ТОЧКАМ (`runes`), а не по `codeUnits`: эмодзи и
  /// прочие символы вне BMP занимают в Dart две единицы, и наивный обход дал бы
  /// на них два «?» вместо одного — то есть лишний байт и сдвиг всех
  /// последующих смещений, ту самую поломку, ради которой всё это написано.
  static List<int> encode(String text) {
    final out = <int>[];
    for (final rune in text.runes) {
      out.add(_byteFor(rune));
    }
    return out;
  }

  /// Можно ли передать [text] в cp866 без потерь.
  ///
  /// Нужен генераторам батников как ГЕЙТ НА ЭТАПЕ ТЕСТА: автор, вставивший в
  /// текст «…» или неразрывный пробел, узнаёт об этом от красного теста, а не
  /// от пользователя, у которого сброс сети выполнился до середины.
  static bool isEncodable(String text) {
    for (final rune in text.runes) {
      // '?' сам по себе кодируется — отличаем его от подстановки по исходнику.
      if (_byteFor(rune) == _replacement && rune != _replacement) return false;
    }
    return true;
  }

  static int _byteFor(int rune) {
    // ASCII — как есть. Именно по нему cmd находит границы строк и команд.
    if (rune < 0x80) return rune;
    // 'А'…'Я' (U+0410…U+042F) → 0x80…0x9F.
    if (rune >= 0x0410 && rune <= 0x042F) return 0x80 + (rune - 0x0410);
    // 'а'…'п' (U+0430…U+043F) → 0xA0…0xAF.
    if (rune >= 0x0430 && rune <= 0x043F) return 0xA0 + (rune - 0x0430);
    // ⚠️ Разрыв таблицы: 'р'…'я' (U+0440…U+044F) уезжают на 0xE0…0xEF,
    // потому что 0xB0…0xDF занято псевдографикой. Единого сдвига для строчных
    // букв не существует — не «упрощать» эти две ветки в одну.
    if (rune >= 0x0440 && rune <= 0x044F) return 0xE0 + (rune - 0x0440);
    // 'Ё' и 'ё' лежат вне алфавитных диапазонов и в Unicode, и в cp866.
    if (rune == 0x0401) return 0xF0;
    if (rune == 0x0451) return 0xF1;
    return _replacement;
  }
}
