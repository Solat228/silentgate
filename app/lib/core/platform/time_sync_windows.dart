import 'dart:io';

import '../../engine/windows/elevation.dart';
import 'app_log.dart';

/// Синхронизация системного времени — по кнопке, из самого приложения.
///
/// ⚠️ ЗАЧЕМ ЭТО ЗДЕСЬ. Живой клиент 05.09.2026 не смог импортировать подписку:
/// `CERTIFICATE_VERIFY_FAILED: certificate is not yet valid`. Сертификат
/// сервера считался ЕЩЁ НЕ НАЧАВШИМ действовать, потому что часы его
/// компьютера отставали. Починка целиком на стороне человека и занимает
/// полминуты — но только если знать, куда идти.
///
/// Решение владельца: не отправлять человека в настройки Windows, а
/// предложить кнопку и сделать это за него.
///
/// ⚠️ ПОЧЕМУ НЕ ВЫСТАВЛЯЕМ ВРЕМЯ САМИ. Прямая установка часов (`SetSystemTime`)
/// требует тех же прав, но берёт время НЕОТКУДА: у нас нет доверенного
/// источника, а брать его из HTTP-заголовка сервера, которому мы не смогли
/// довериться из-за сертификата, — замкнутый круг. `w32tm` спрашивает
/// настроенный в системе NTP-сервер, то есть ровно тот источник, которому
/// Windows доверяет сама.
class TimeSyncWindows {
  /// Доступна ли синхронизация на этой платформе.
  static bool get isSupported => Platform.isWindows;

  /// Результат попытки: что показать человеку.
  static const okText = 'Время синхронизировано. Повторите импорт.';

  /// Что показать, если человек отказал в правах или служба не поддалась.
  ///
  /// ⚠️ ОТКАЗ ОТ UAC — ЗАКОННЫЙ ОТВЕТ, А НЕ СБОЙ, и тупик здесь недопустим:
  /// человек уже понял, что виноваты часы, и остаться без способа их
  /// поправить — хуже, чем не иметь кнопки вовсе. Поэтому вторым путём
  /// показываем, куда идти руками; там прав администратора не нужно.
  static const manualHint = 'Не удалось синхронизировать автоматически — '
      'для этого нужны права администратора.\n\n'
      'Поправить вручную: Параметры Windows → Время и язык → Дата и время. '
      'Включите «Установить время автоматически» и нажмите «Синхронизировать '
      'сейчас». Если переключатель уже включён, выключите и включите снова.';

  /// Синхронизировать часы. `true` — получилось.
  ///
  /// ⚠️ СЛУЖБУ НАДО СНАЧАЛА ПОДНЯТЬ. На домашних машинах `W32Time` часто
  /// стоит в «Вручную» и не запущена — тогда `w32tm /resync` отвечает
  /// «Служба не запущена» и человек решает, что кнопка не работает. Поэтому
  /// сначала `start`, и только потом `resync`.
  ///
  /// ⚠️ И ВСЁ ЭТО ТРЕБУЕТ ПРАВ. Отказ от UAC — законный ответ пользователя, а
  /// не сбой: возвращаем `false` молча, без пугающей ошибки.
  static Future<bool> resync() async {
    if (!isSupported) return false;
    final sys = Platform.environment['WINDIR'] ?? r'C:\Windows';
    // ⚠️ Обе команды одной элевацией: два отдельных запроса UAC подряд человек
    // читает как «оно сломалось и просит ещё раз».
    final ok = await Elevation.runElevatedAsync(
      '$sys\\System32\\cmd.exe',
      '/c sc config w32time start= auto & net start w32time & '
          'w32tm /resync /force',
    );
    AppLog.i(ok
        ? 'Синхронизация времени: выполнена по кнопке пользователя'
        : 'Синхронизация времени: не выполнена (отказ в правах или ошибка службы)');
    return ok;
  }

  /// Насколько часы расходятся с временем, которое отдал сервер.
  ///
  /// ⚠️ Нужна не для показа, а для ЧЕСТНОСТИ подсказки: советовать «проверьте
  /// часы» там, где часы верны, значит отправить человека не туда. Заголовок
  /// `Date` есть почти у любого ответа, и он приходит ДО проверки сертификата
  /// только на http — поэтому источник передаётся снаружи, а не берётся здесь.
  static Duration? skewFrom(String? httpDateHeader) {
    if (httpDateHeader == null || httpDateHeader.isEmpty) return null;
    try {
      final server = HttpDate.parse(httpDateHeader);
      return DateTime.now().toUtc().difference(server.toUtc());
    } catch (_) {
      return null;
    }
  }

  /// Стоит ли вообще предлагать синхронизацию: расхождение меньше минуты
  /// сертификату помешать не может, и кнопка была бы шумом.
  static bool worthSyncing(Duration? skew) =>
      skew != null && skew.abs() > const Duration(minutes: 1);
}
