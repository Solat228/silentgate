import 'dart:io';
import 'dart:math';

import 'app_log.dart';
import 'app_paths.dart';

/// Постоянный секрет локального сокета single-instance (порт 47654).
///
/// ⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ СЕКРЕТ, А НЕ ТОКЕН API. Раньше сокет проверял входящие
/// команды токеном API (`AppSettings.apiToken`), и получилась дыра сразу с двух
/// сторон:
///
/// 1. Токен по умолчанию ПУСТ (API выключен), а пересылающая сторона
///    (`SingleInstance.forward`) его не подставляла вообще — ни один процесс не
///    знал, что его надо приложить. В итоге `silentgate://connect|disconnect|
///    toggle|update` при запущенном приложении отбрасывались ВСЕГДА: человек
///    кликал ссылку, второй экземпляр её пересылал, первичный писал в журнал
///    «отвергнута» и молчал.
/// 2. Импорт (`silentgate://import?url=…`) шёл БЕЗ проверки вовсе — то есть
///    самая опасная команда (подмена подписки, а при включённом
///    автоподключении сразу и подключение к чужим серверам) была единственной
///    открытой. Ровно то, ради чего порт и закрывали.
///
/// Секрет этого сокета обязан существовать ВСЕГДА и не зависеть от того,
/// включил ли пользователь API. Оба конца — наши собственные процессы одного
/// пользователя, поэтому файл рядом с данными приложения им доступен, а чужому
/// процессу — нет (`%APPDATA%\SilentGate` доступен только этой учётке).
///
/// Образец взят с пароля Clash API на Android (`android_engine.dart`,
/// `_rotateApiSecret`/`_restoreApiSecret`): генерируется, пишется рядом с
/// данными, перечитывается другим процессом.
///
/// ⚠️ ХОЛОДНЫЙ СТАРТ ПО ССЫЛКЕ ИДЁТ МИМО. Когда приложение не запущено, ссылка
/// приходит АРГУМЕНТОМ командной строки (`main.dart`, `incomingUrl`) и никакого
/// сокета не касается — этот секрет к ней отношения не имеет.
class InstanceSecret {
  /// Имя файла рядом с данными приложения. Без расширения — как у
  /// `clash_api_secret` на Android, чтобы файл не открывался двойным кликом.
  static const fileName = 'instance_secret';

  /// Значение в памяти: файл читается один раз за запуск. Секрет постоянный,
  /// перечитывать его на каждое сообщение сокета незачем — а вот файловый
  /// ввод-вывод в обработчике входящего соединения задержал бы как раз ту
  /// ссылку, которую нетерпеливо ждёт пользователь.
  static String? _cached;

  static Future<File> _file() async {
    final dir = await AppPaths.supportDir();
    return File('${dir.path}${Platform.pathSeparator}$fileName');
  }

  /// Случайная строка. ⚠️ Своя, а не `VpnEngineBase.randomSecret`: это
  /// `core/platform`, и тянуть сюда движок ради трёх строк значило бы
  /// развернуть зависимость слоёв наизнанку. Алгоритм («32 hex из
  /// `Random.secure`») имеет ровно одно толкование и разойтись не может.
  static String _generate() {
    final rnd = Random.secure();
    return List.generate(32, (_) => rnd.nextInt(16).toRadixString(16)).join();
  }

  /// Первичный экземпляр: прочитать существующий секрет либо создать новый.
  ///
  /// ⚠️ Не бросает никогда. Если файл создать не удалось, секрет всё равно
  /// возвращается (живёт в памяти этого процесса) — сокет остаётся закрытым, а
  /// не открывается «на всякий случай». Тогда пересылка ссылок перестанет
  /// работать, и об этом будет ПО СТРОКЕ в журнале с обеих сторон: это
  /// диагностируемо, а молча открытый порт — нет.
  static Future<String> ensure() async {
    final known = _cached;
    if (known != null && known.isNotEmpty) return known;
    try {
      final f = await _file();
      if (await f.exists()) {
        final v = (await f.readAsString()).trim();
        if (v.isNotEmpty) return _cached = v;
      }
    } catch (e) {
      AppLog.w('Не удалось прочитать секрет локального сокета: $e');
    }
    final fresh = _generate();
    try {
      final f = await _file();
      await f.writeAsString(fresh, flush: true);
    } catch (e) {
      // ⚠️ ERROR, а не WARN: с этого момента ссылки, кликнутые при запущенном
      // приложении, до него не дойдут — второй экземпляр не сможет прочитать
      // секрет и его сообщение будет отвергнуто.
      AppLog.e('Не удалось сохранить секрет локального сокета: $e. '
          'Ссылки silentgate:// при уже запущенном приложении работать не '
          'будут до устранения причины.');
    }
    return _cached = fresh;
  }

  /// Вторичный экземпляр: прочитать секрет первичного. Пустая строка — файла
  /// нет или он не читается; создавать его здесь НЕЛЬЗЯ (первичный уже слушает
  /// со своим значением, и новый файл сделал бы только хуже).
  static Future<String> read() async {
    final known = _cached;
    if (known != null) return known;
    try {
      final f = await _file();
      if (!await f.exists()) return _cached = '';
      return _cached = (await f.readAsString()).trim();
    } catch (e) {
      AppLog.w('Не удалось прочитать секрет локального сокета: $e');
      return _cached = '';
    }
  }

  /// Сбросить кэш (между тестами).
  static void resetForTests() => _cached = null;
}
