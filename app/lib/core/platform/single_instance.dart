/// Сравнение секрета в ПОСТОЯННОЕ время (без раннего выхода на первом
/// несовпадающем байте и без утечки через сравнение длин).
///
/// ⚠️ ДУБЛИКАТ `_constantTimeEquals` из `core/net/api_server.dart` — и это
/// осознанный выбор, не забывчивость. Та функция приватна (ведущее `_`) в
/// чужом файле, который параллельно правит другая задача; тащить её в общий
/// модуль означало бы редактировать активно меняющийся файл ради источника
/// правды у примитива, который в принципе не может разойтись в толковании —
/// в отличие от разбора `needsToken` выше (там «что считать командой» было
/// вопросом ИНТЕРПРЕТАЦИИ, и два разных ответа на него — баг; здесь же
/// «побайтовое сравнение без утечки по времени» имеет одно определение, и
/// вторая копия того же алгоритма ничем не хуже первой). Модель угрозы тоже
/// слабее, чем у HTTP-токена: это сырой TCP-порт без keep-alive, каждая
/// попытка — новое соединение, и точность измерения тайминга поверх этого
/// джиттера ниже, чем у постоянно живущего HTTP-сервера.
bool _constantTimeEquals(String a, String b) {
  final ab = utf8.encode(a);
  final bb = utf8.encode(b);
  final maxLen = ab.length > bb.length ? ab.length : bb.length;
  var diff = ab.length ^ bb.length;
  for (var i = 0; i < maxLen; i++) {
    final x = i < ab.length ? ab[i] : 0;
    final y = i < bb.length ? bb[i] : 0;
    diff |= x ^ y;
  }
  return diff == 0;
}

/// Single-instance через локальный сокет. Первый экземпляр слушает порт на 127.0.0.1;
/// последующие (например, запущенные браузером по deep link) пересылают ему URL и завершаются.
class SingleInstance {
  static const int _basePort = 47654;

  /// Потолок одного сообщения и время на его доставку.
  ///
  /// ⚠️ ОБА ОГРАНИЧЕНИЯ ДЕЙСТВУЮТ ДО ПРОВЕРКИ СЕКРЕТА — в этом весь смысл.
  /// Разбор идёт по `onDone`, то есть по закрытию соединения отправителем;
  /// пока он не закрыл, мы копим байты в памяти и ничего о нём не знаем.
  /// Наше настоящее сообщение — 32 символа секрета плюс ссылка, поэтому 8 КБ
  /// и несколько секунд — щедрый запас для штатного пути и жёсткий предел
  /// для всего остального.
  static const int maxMessageBytes = 8 * 1024;
  static const Duration readTimeout = Duration(seconds: 5);

  /// Изолированная копия (SILENTGATE_PORT_OFFSET) слушает свой порт и не конфликтует
  /// с установленной версией.
  static int get _port => _basePort + AppEnv.portOffset;

  /// Пытается стать первичным экземпляром: вернёт сервер-сокет, либо null если уже запущен.
  static Future<ServerSocket?> tryBecomePrimary() async {
    try {
      return await ServerSocket.bind(InternetAddress.loopbackIPv4, _port);
    } catch (_) {
      return null;
    }
  }

  /// Разобрать сообщение сокета: `<секрет>\n<ссылка>` либо просто `<ссылка>`.
  ///
  /// Форма без перевода строки осталась разбираемой намеренно — так выглядит
  /// сообщение ЧУЖОГО процесса (или нашей старой сборки), и оно обязано
  /// доехать до проверки и быть честно отвергнутым, а не упасть на разборе.
  static ({String? secret, String url}) splitMessage(String raw) {
    final i = raw.indexOf('\n');
    if (i < 0) return (secret: null, url: raw.trim());
    return (
      secret: raw.substring(0, i).trim(),
      url: raw.substring(i + 1).trim()
    );
  }

  /// Первичный экземпляр: принимать входящие URL.
  ///
  /// [secret] — постоянный секрет этого сокета (`InstanceSecret`). Он требуется
  /// для ЛЮБОГО сообщения, а не только для управляющих команд.
  ///
  /// ⚠️ ПОЧЕМУ ИМПОРТ ТОЖЕ ЗАКРЫТ. Раньше здесь был разбор `needsToken`:
  /// управляющие команды требовали токен API, импорт проходил свободно «потому
  /// что его инициировал человек». На деле человек инициировал КЛИК В БРАУЗЕРЕ,
  /// а до сокета доходил уже наш второй экземпляр — то есть по эту сторону
  /// «подтверждения человеком» не было ни у одной формы. И открытой оказалась
  /// самая опасная: `silentgate://import?url=…` подменяет подписку целиком, а
  /// при включённом автоподключении сразу и подключает к чужим серверам —
  /// ровно то, что в спеке названо мотивом закрытия порта. Штатный путь при
  /// этом не сломан: секрет подставляет `forward`, то есть наш же процесс,
  /// которому файл секрета доступен.
  ///
  /// ⚠️ И БОЛЬШЕ НЕТ РАЗБОРА ССЫЛКИ. Прежний `needsToken` решал по СОДЕРЖИМОМУ
  /// строки, нужна ли проверка, — а второй разбор той же строки уже дважды
  /// оказывался дырой (`silentgate://connect#x`, `silentgate:///connect`
  /// проходили мимо него). Единое требование ко всем сообщениям убирает этот
  /// класс ошибок целиком: решать по содержимому больше нечего.
  ///
  /// [timeout] переопределяется ТОЛЬКО тестами: ждать в тесте настоящие
  /// [readTimeout] значило бы держать прогон впустую, а непроверенный предел
  /// — это предел, про который мы знаем только из комментария.
  static void listen(ServerSocket server, void Function(String url) onUrl,
      {required String secret, Duration timeout = readTimeout}) {
    server.listen((socket) {
      final buf = <int>[];
      // ⚠️ ЗАКРЫЛИ ЛИ МЫ ЭТО СОЕДИНЕНИЕ САМИ. Без флага таймаут и `onDone`
      // могли бы отработать оба: `destroy()` завершает поток, то есть сам
      // приводит к `onDone` — и отброшенное по лимиту сообщение всё равно
      // доехало бы до разбора.
      var finished = false;
      Timer? deadline;
      void finish(String? rejection) {
        if (finished) return;
        finished = true;
        deadline?.cancel();
        socket.destroy();
        if (rejection != null) {
          AppLog.w('Сообщение через локальный сокет отвергнуто: $rejection');
        }
      }

      deadline = Timer(timeout, () => finish('истекло время чтения'));
      socket.listen(
        (chunk) {
          if (finished) return;
          // ⚠️ ПОТОЛОК ОБЯЗАТЕЛЕН, И ОН ДО АУТЕНТИФИКАЦИИ. Секрет проверяется
          // только по `onDone`, то есть когда отправитель ЗАКРОЕТ своё
          // соединение, — а закрывать его никто не обязан. Локальный процесс
          // мог лить в порт сколько угодно, и всё это копилось в памяти
          // приложения, не предъявив ни одного байта секрета. Наше настоящее
          // сообщение — секрет плюс ссылка, то есть сотни байт; 8 КБ здесь с
          // запасом, а всё, что длиннее, — не наш формат по определению.
          if (buf.length + chunk.length > maxMessageBytes) {
            finish('длина превысила $maxMessageBytes байт');
            return;
          }
          buf.addAll(chunk);
        },
        onDone: () {
          if (finished) return;
          finished = true;
          deadline?.cancel();
          final raw = utf8.decode(buf, allowMalformed: true).trim();
          socket.destroy();
          if (raw.isEmpty) return;
          final m = splitMessage(raw);
          if (secret.isEmpty || !_constantTimeEquals(m.secret ?? '', secret)) {
            // ⚠️ Молчать нельзя: «команда отвергнута» и «команда выполнена»
            // снаружи неотличимы, и разбор жалобы начинался бы с нуля.
            AppLog.w('Сообщение через локальный сокет отвергнуто: '
                'неверный или отсутствующий секрет экземпляра');
            return;
          }
          onUrl(m.url);
        },
        // Сорванное соединение — не повод для строки в журнале: это
        // обыденность, а не попытка что-то нам сказать.
        onError: (_) => finish(null),
      );
    });
  }

  /// Вторичный экземпляр: переслать URL первичному, приложив секрет.
  ///
  /// ⚠️ Секрет подставляется ЗДЕСЬ, а не вызывающим. Раньше `forward` слал
  /// голую ссылку, и подставить секрет было некому вовсе — проверка на
  /// принимающей стороне отвергала всё, что через неё шло, при полностью
  /// «правильном» на вид коде с обеих сторон.
  static Future<void> forward(String url) async {
    final secret = await InstanceSecret.read();
    if (secret.isEmpty) {
      // Дошли сюда — значит первичный экземпляр запущен (порт занят), а файл
      // секрета мы не прочитали. Ссылка будет отвергнута; сказать об этом
      // обязаны, иначе снаружи это выглядит как «клик не сработал».
      AppLog.w('Секрет локального сокета не прочитан — ссылка не будет '
          'передана уже запущенному приложению');
    }
    try {
      final socket = await Socket.connect(
        InternetAddress.loopbackIPv4,
        _port,
        timeout: const Duration(seconds: 2),
      );
      socket.add(utf8.encode('$secret\n$url'));
      await socket.flush();
      await socket.close();
    } catch (_) {}
  }
}
