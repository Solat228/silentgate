import 'dart:io';

import 'package:flutter/services.dart';

import 'app_log.dart';

/// РАЗРЕШЕНЫ ЛИ УВЕДОМЛЕНИЯ ПРИЛОЖЕНИЮ (Android).
///
/// ## Что теряется при отказе — и почему это перестало быть мелочью
///
/// Раньше в коде стояло: «разрешение не критично для работы, туннель
/// поднимается всё равно». На момент, когда это писалось, так и было. С
/// 20.08.2026 — уже нет, и цена отказа выросла дважды:
///
///  1. **Постоянное уведомление сервиса.** В нём кнопка «Отключить» —
///     единственный способ снять туннель при закрытом приложении, и вся
///     индикация «VPN включён».
///  2. **Разовое уведомление об обрыве** (`vpn/AlertNotice.kt`). Ради него всё
///     и затевалось: на телефоне приложение свёрнуто ВСЕГДА, и без системного
///     уведомления обрыв не виден нигде. При отказе оно молча не покажется —
///     а «молча» здесь худшее слово: человек считает, что за каналом следят.
///
/// ## ⚠️ ПОЧЕМУ СПРАШИВАЕМ СИСТЕМУ, А НЕ СВОЁ РАЗРЕШЕНИЕ
///
/// `POST_NOTIFICATIONS` и «уведомления включены» — РАЗНЫЕ вещи. Разрешение
/// может быть выдано, а человек потом отключил уведомления приложению целиком
/// или заглушил наш канал в системных настройках. Проверка своего разрешения
/// показала бы «всё в порядке» ровно там, где ничего не показывается.
/// Поэтому нативная сторона спрашивает `areNotificationsEnabled()` — факт, а не
/// намерение.
///
/// ## ⚠️ «НЕ ЗНАЮ» ВЕДЁТ СЕБЯ КАК «РАЗРЕШЕНО»
///
/// Здесь это осознанный перекос, обратный тому, что принят в kill switch. Цена
/// ошибки несимметрична: лишняя плашка у человека, у которого всё в порядке, —
/// это назойливость; пропущенная — это молчащая защита. Но плашка, всплывшая
/// из-за сбоя канала на не-Android или на экзотической прошивке, раздражает
/// всех и не чинит ничего. Поэтому: сомневаешься — молчи.
abstract final class NotificationAccess {
  static const _channel = MethodChannel('lol.silentgate/vpn');

  /// Показывать ли предупреждение. `false` — всё в порядке ЛИБО выяснить не
  /// удалось (см. выше, почему это одно и то же).
  static Future<bool> blocked() async {
    if (!Platform.isAndroid) return false;
    try {
      final ok = await _channel.invokeMethod<bool>('notificationsEnabled');
      // `null` — канал ответил пустотой: это «не знаю», а не «выключено».
      return ok == false;
    } catch (e) {
      AppLog.w('Состояние уведомлений недоступно: $e');
      return false;
    }
  }

  /// Открыть системный экран уведомлений приложения. `false` — открыть нечем.
  ///
  /// Включить уведомления из кода нельзя ни на одной версии Android: это
  /// намеренный запрет платформы. Единственный честный ход — довести человека
  /// до нужного экрана.
  static Future<bool> openSettings() async {
    if (!Platform.isAndroid) return false;
    try {
      return await _channel.invokeMethod<bool>('openNotificationSettings') ??
          false;
    } catch (e) {
      AppLog.w('Не удалось открыть системные настройки уведомлений: $e');
      return false;
    }
  }
}
