/// Символ ESC (0x1B) — начало любой управляющей последовательности терминала.
///
/// ⚠️ ЗАДАЁТСЯ КОДОМ, А НЕ САМИМ БАЙТОМ. Невидимый управляющий символ в
/// исходнике нельзя ни увидеть, ни сверить глазами, и он легко теряется при
/// правке файла. Ровно это уже случилось: байт пропал из выражения ниже, цвет
/// снимался наполовину («ESC» оставался, «[31m» уходило), и в логе вместо
/// уровня был мусор. Поймал тест — глазами такое не увидеть по определению.
final _esc = String.fromCharCode(0x1b);

/// Привести лог sing-box к читаемому виду.
///
/// ⚠️ ДВЕ ВЕЩИ, КОТОРЫЕ МЕШАЮТ ЧИТАТЬ ЭТОТ ЛОГ.
///
/// 1. Смещение часового пояса стоит ПЕРЕД датой: «+0700 2026-08-11 02:09:08».
///    Это собственный формат sing-box, в конфиге он не настраивается.
///    Владелец прочитал это как поломку («чё за +700»), и его можно понять:
///    строка начинается с числа, похожего на код ошибки. Переставляем
///    смещение в конец — «2026-08-11 02:09:08 +0700», как принято везде.
///
/// 2. Управляющие последовательности цвета (ESC + «[31m» и подобные). В
///    терминале они красят уровень, а в текстовом файле превращаются в мусор,
///    который вдобавок сбивает поиск по слову ERROR.
///
/// Данные при этом не меняются: время то же самое, просто записано привычно.
///
/// ⚠️ Приводим ТОЛЬКО ПРИ ПОКАЗЕ. Сам файл не трогаем: иначе потеряли бы
/// возможность сверить его с выводом ядра один в один, а дописывать в него
/// ядро продолжает в своём формате.
///
/// Живёт в `core/`, а не рядом с отчётом поддержки: формат у ядра один и тот
/// же на обеих платформах, и экран логов на Android читает его же.
String tidySingboxLog(String raw) {
  final ansi = RegExp('$_esc\\[[0-9;]*m');
  // Смещение в начале строки: знак, четыре цифры, пробел, дата и время.
  // ⚠️ Якорь `^` обязателен: без него поехали бы числа внутри сообщений.
  final head = RegExp(r'^([+-]\d{4})\s+(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})');
  return raw
      .split('\n')
      .map((l) {
        final noColor = l.replaceAll(ansi, '');
        return noColor.replaceFirstMapped(head, (m) => '${m[2]} ${m[1]}');
      })
      .join('\n');
}
