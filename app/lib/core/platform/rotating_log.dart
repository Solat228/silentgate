import 'dart:async';
import 'dart:convert';
import 'dart:io';

/// Файловый лог с усечением: пишет строки и не даёт файлу расти без предела.
///
/// Вынесено из `TunHelper`, где эта логика уже выстрадана: у пользователя
/// `singbox.log` дорос до **758 МБ**, потому что усечение проверялось только при
/// открытии, а внутри сессии ядро писало без ограничений. Второй урок оттуда же:
/// хвост нужно читать **с конца файла**, иначе кнопка «Написать в поддержку»
/// затягивает сотни мегабайт в память и подвешивает приложение.
///
/// ⚠️ Класс намеренно **инстансный**, а не статический: в одном процессе живут
/// два разных лога (TUN-ядро и прокси-ядро), и общий счётчик размера у них
/// разъезжался бы с реальностью.
///
/// ⚠️ ЗДЕСЬ ЖЕ ЖИВЁТ ОБРЕЗКА — И ЭТО ГЛАВНОЕ ПРАВИЛО ФАЙЛА. Обрезать лог
/// откуда-то ещё (`File.writeAsString('')` мимо этого класса) НЕЛЬЗЯ. Причина
/// измерена на живых файлах владельца 12.08.2026: в `app.log` 93 % содержимого
/// оказались НУЛЕВЫМИ БАЙТАМИ (434 847 подряд), в `singbox.log` — 98 %.
/// `openWrite(FileMode.append)` в Dart запоминает смещение ОДИН раз, в момент
/// открытия, и дальше пишет по нему; после чужой обрезки поток продолжает
/// писать по старому адресу, а Windows добивает пропуск нулями. Отсюда же
/// [truncate]: обрезка обязана идти через тот же объект, чтобы поток был
/// ПЕРЕСОЗДАН, а не продолжил писать в пустоту.
class RotatingLog {
  RotatingLog(this.path,
      {this.maxBytes = 512 * 1024, this.keepPrevious = false});

  final String path;

  /// Порог ротации. При достижении файл начинается заново — так дешевле и
  /// надёжнее, чем перекладывать хвост построчно: лог нужен для диагностики
  /// «прямо сейчас», а не как архив. С [keepPrevious] прежняя часть при этом
  /// не пропадает, а уезжает в соседний файл.
  final int maxBytes;

  /// Потолок ОДНОЙ части лога ядра (sing-box: TUN, прокси, маршрутизатор
  /// выходов).
  ///
  /// ⚠️ ЧИСЛО ВЫВЕДЕНО ИЗ ЗАМЕРА, А НЕ ВЗЯТО КРАСИВЫМ. У владельца уровень лога
  /// `debug`, и 19.08.2026 в `singbox.log` за **55 секунд** легло **187 КБ** —
  /// это ~3,4 КБ/с. Прежние 512 КБ давали при таком темпе **две с половиной
  /// минуты** истории: обрыв в 01:29 не пережил даже подъёма туннеля в 02:44.
  /// 8 МиБ при 3,4 КБ/с — это ~40 минут на часть, а с [keepPrevious] на диске
  /// лежат от одной до двух частей, то есть 40–80 минут. Столько и нужно:
  /// пользователь пишет в поддержку не в секунду аварии, а когда заметит.
  ///
  /// Верхняя граница расхода — 16 МиБ на лог (две части). Это осознанный
  /// размен: диагностика обрыва против места на диске. Старые части удаляет
  /// та же настройка «срок хранения логов» (`LogRetention` → `LogMaintenance`),
  /// второй политики хранения здесь НЕТ и заводить её нельзя.
  static const coreLogMaxBytes = 8 * 1024 * 1024;

  /// Хранить ли ПРЕДЫДУЩУЮ часть лога (`<имя>.prev.log`) при достижении порога.
  ///
  /// ⚠️ ЗАВЕДЕНО ПО ЖИВОМУ СЛУЧАЮ 19.08.2026. Обрезка «в ноль» уничтожает ровно
  /// те строки, ради которых лог и читают. В отчёте владельца было два обрыва
  /// туннеля (01:29 и 02:20), а в самом `singbox.log` к моменту разбора лежали
  /// 55 секунд с 02:44:42 — окна ни одной из аварий не осталось, и доказать
  /// или опровергнуть утечку по логам не удалось.
  ///
  /// С этим флагом достигший порога файл не стирается, а СДВИГАЕТСЯ в соседний:
  /// на диске всегда лежит от одного до двух порогов истории, а «последние
  /// строки перед аварией» переживают ротацию — они и нужны для разбора.
  final bool keepPrevious;

  int _written = 0;

  /// [open] уже отработал (успешно или нет). Именно это, а не наличие потока,
  /// разрешает запись: потока больше нет ни у кого (см. [_appendLine]).
  bool _opened = false;

  /// Мы — владелец файла, то есть только нам можно его ОБРЕЗАТЬ.
  ///
  /// ⚠️ У владельца запущены ДВЕ копии приложения, и обе пишут в один файл.
  /// Обрезка из второй копии портит лог первой гарантированно: её поток
  /// продолжит писать по своему старому смещению (см. шапку класса).
  bool _owner = false;

  /// Захваченная блокировка диапазона ЗА пределами файла (см. [_claimOwnership]).
  RandomAccessFile? _ownerLock;

  /// Смещение блокировки — заведомо дальше любого реального размера лога,
  /// чтобы блокировка не мешала собственным записям (Windows-блокировки
  /// обязательные: диапазон, запертый одним дескриптором, недоступен другому
  /// даже внутри того же процесса).
  static const _lockOffset = 1 << 40;

  /// Открытие мемоизировано: [open] зовут и явно, и (для гостя) косвенно, а
  /// повторный захват блокировки означал бы потерю владения на ровном месте.
  Future<void>? _opening;

  /// Закрыт окончательно. Ставится ДО первого await в [close], иначе идущая
  /// ротация переоткрывала файл уже после закрытия и дескриптор жил до конца
  /// процесса.
  bool _closed = false;

  /// Хвост очереди записи.
  ///
  /// ⚠️ Записи ОБЯЗАНЫ идти строго по одной. `onLine` вызывается для каждой
  /// строки чанка синхронно подряд (`LineSplitter` отдаёт их пачкой), а
  /// [write] после `await _restart()` отпускает цикл событий. Без очереди
  /// каждая строка пачки запускала СВОЮ ротацию: файл усекался повторно,
  /// стирая только что записанное, порядок строк переворачивался, а прежние
  /// `IOSink` терялись не закрытыми. На практике это значило, что FATAL-строка,
  /// ради которой лог и заводили, пропадала именно в момент аварии.
  Future<void> _queue = Future<void>.value();

  bool get isOpen => _opened && !_closed;

  /// Владеем ли мы файлом. Гость (вторая копия приложения, второй экземпляр
  /// хелпера) писать может, а обрезать — нет.
  bool get isOwner => _owner;

  /// Путь предыдущей части лога: `singbox.log` → `singbox.prev.log`.
  ///
  /// ⚠️ ИМЯ ОБЯЗАНО ОСТАВАТЬСЯ `*.log`, и это не вкусовщина. Срок хранения
  /// логов — уже существующая настройка пользователя (`LogRetention`), а её
  /// чистка и перепись (`LogMaintenance`) ходят по маске `*.log`. Назови файл
  /// `singbox.log.1` — он выпадет из обеих: у логов появится вторая, никем не
  /// управляемая политика хранения, а на диске — файл, который не удаляется
  /// никогда и которого не видно на экране логов.
  static String previousPathFor(String path) {
    const suffix = '.log';
    if (path.toLowerCase().endsWith(suffix)) {
      return '${path.substring(0, path.length - suffix.length)}.prev$suffix';
    }
    return '$path.prev$suffix';
  }

  /// Открывает файл на дозапись. Существующий лог, уже переросший порог,
  /// ротируется сразу — иначе новая сессия начиналась бы с переполненного
  /// файла.
  ///
  /// ⚠️ ИМЕННО РОТИРУЕТСЯ, А НЕ УСЕКАЕТСЯ. Раньше здесь стояло
  /// `writeAsString('')`, и запуск ядра поверх полного лога стирал его целиком
  /// — то есть ровно ту историю, за которой в лог и приходят после обрыва.
  /// Теперь прежняя часть уезжает в `*.prev.log` (при [keepPrevious]).
  ///
  /// Идемпотентна: повторный вызов возвращает тот же Future.
  Future<void> open() => _opening ??= _open();

  Future<void> _open() async {
    if (_opened) return;
    try {
      await File(path).parent.create(recursive: true);
    } catch (_) {}
    await _claimOwnership();
    try {
      final f = File(path);
      var size = 0;
      if (await f.exists()) {
        size = await f.length();
        // ⚠️ Ротация — только владельцу. Гость, обрезавший файл при открытии,
        // разом обнулил бы смещение живого потока первой копии, и весь пропуск
        // Windows залила бы нулями.
        if (size > maxBytes && _owner) {
          await _rollover();
          size = 0;
        }
      }
      _written = size;
      // ⚠️ ПОТОК НЕ ОТКРЫВАЕТСЯ ВООБЩЕ — ни владельцем, ни гостем. Запись идёт
      // отдельным открытием на строку (см. [_appendLine]): так смещение всегда
      // равно реальному концу файла, что бы ни делал второй процесс.
    } catch (_) {
      // Лог не имеет права уронить подъём туннеля: не смогли — работаем без него.
    }
    _opened = true;
  }

  /// Пробуем стать владельцем: запираем однобайтовый диапазон далеко за концом
  /// файла. Блокировка снимается операционной системой сама, если процесс умер,
  /// — поэтому она переживает аварийное завершение, в отличие от файла-метки.
  ///
  /// Не смогли даже открыть файл — считаем себя владельцем: иначе единственная
  /// копия приложения из-за случайной ошибки навсегда осталась бы без ротации,
  /// и лог рос бы без предела (ровно та беда, ради которой класс и написан).
  Future<void> _claimOwnership() async {
    RandomAccessFile? raf;
    try {
      raf = await File(path).open(mode: FileMode.append);
    } catch (_) {
      _owner = true;
      return;
    }
    try {
      await raf.lock(FileLock.exclusive, _lockOffset, _lockOffset + 1);
      _ownerLock = raf;
      _owner = true;
    } catch (_) {
      // Диапазон занят — файл уже ведёт другой экземпляр.
      _owner = false;
      try {
        await raf.close();
      } catch (_) {}
    }
  }

  /// Пишет строку (перевод строки добавляется сам). Когда файл перерастает
  /// порог — начинается заново прямо на лету, без перезапуска приложения.
  Future<void> write(String line) {
    if (_closed) return Future<void>.value();
    // Ставим в очередь, а не пишем сразу: см. комментарий к [_queue].
    _queue = _queue.then((_) => _writeOne(line)).catchError((_) {});
    return _queue;
  }

  Future<void> _writeOne(String line) async {
    // Без open() запись игнорируется: лог не имеет права создавать файлы сам по
    // себе — иначе он появлялся бы у тех, кто ядро ни разу не запускал.
    if (_closed || !_opened) return;
    try {
      // ⚠️ ВЛАДЕЛЕЦ ПИШЕТ ТЕМ ЖЕ СПОСОБОМ, ЧТО И ГОСТЬ, И ЭТО НЕ УПРОЩЕНИЕ РАДИ
      // упрощения. Раньше владелец держал долгоживущий `IOSink`, и его смещение
      // фиксировалось при открытии: строки, дописанные второй копией
      // приложения между записями владельца, ЗАТИРАЛИСЬ. Проверено опытом
      // (`test/log_two_copies_test.dart`): файл выходил 38 байт вместо 51 —
      // строка гостя исчезала бесследно.
      //
      // Это ровно та же болезнь, от которой лечили сам этот класс, только с
      // другого конца: ДВА РАЗНЫХ СПОСОБА ПИСАТЬ В ОДИН ФАЙЛ всегда разъезжаются,
      // потому что каждый ведёт своё представление о его конце. Способ теперь
      // один, а владение решает ровно один вопрос — кому можно обрезать.
      //
      // Цена — открытие файла на строку вместо буферизованного потока. Для
      // объёмов нашего лога (тысячи строк за сессию) это незаметно, а
      // предсказуемость важнее.
      if (_owner && _written >= maxBytes) await _restart();
      await _appendLine(line);
      // Считаем БАЙТЫ, а не символы: поле называется maxBytes и сравнивается с
      // размером файла. На кириллице (а наши собственные строки русские) счёт
      // по символам занижал объём вдвое, по эмодзи — вчетверо.
      _written += utf8.encode(line).length + 1;
    } catch (_) {}
  }

  /// Дописать строку ОТДЕЛЬНЫМ открытием файла — единственный способ записи.
  ///
  /// Дороже долгоживущего потока, но единственно верный, когда в файл пишет
  /// больше одного процесса: смещение у `FileMode.append` фиксируется при
  /// открытии, поэтому долгоживущий поток затирает чужие строки, а после
  /// обрезки заливает разрыв нулями. Никто не держит дескриптор — и лог можно
  /// удалить чисткой по сроку хранения, не дожидаясь выхода из приложения.
  Future<void> _appendLine(String line) async {
    try {
      await File(path).writeAsString('$line\n', mode: FileMode.append);
    } catch (_) {}
  }

  /// СТЕРЕТЬ лог по явной команде (кнопка «Очистить логи»), не ломая запись.
  ///
  /// ⚠️ Единственный разрешённый способ очистить лог. Прямой
  /// `File.writeAsString('')` мимо этого метода оставляет живой поток с
  /// прежним смещением — и файл заполняется нулями до этого смещения (см.
  /// шапку класса). [header] — строка, с которой начинается новый файл.
  ///
  /// ⚠️ ЭТО НЕ РОТАЦИЯ, И РАЗНИЦА СУЩЕСТВЕННА. Здесь предыдущая часть
  /// (`*.prev.log`) тоже УДАЛЯЕТСЯ: человек нажал «очистить» и вправе ожидать,
  /// что данных не осталось. Ротация по порогу, наоборот, прежнюю часть
  /// БЕРЕЖЁТ — см. [_rollover].
  ///
  /// ⚠️ И ЭТОТ МЕТОД НЕЛЬЗЯ ЗВАТЬ ПРИ СТАРТЕ ЯДРА. Именно так и потерялись
  /// журналы двух обрывов 19.08.2026: `TunHelper.run` начинал каждую сессию с
  /// `truncate()`, а восстановление после обрыва — это и есть новая сессия.
  /// Лог аварии уничтожался тем самым перезапуском, который аварией вызван.
  ///
  /// Гость (вторая копия) чужой лог не трогает вовсе: молча ничего не делает.
  Future<void> truncate({String header = ''}) {
    _queue = _queue.then((_) => _truncateOne(header)).catchError((_) {});
    return _queue;
  }

  Future<void> _truncateOne(String header) async {
    if (_closed) return;
    await open();
    if (!_owner) return;
    // ⚠️ ПРЕДЫДУЩАЯ ЧАСТЬ УДАЛЯЕТСЯ, И ИМЕННО ЗДЕСЬ, А НЕ ЧЕРЕЗ [_restart].
    // Первая версия звала `_restart`, а тот делает РОТАЦИЮ — то есть заново
    // копировал стираемый файл в `*.prev.log`. Человек нажимал «Очистить
    // логи», получал сообщение об успехе, а данные оставались лежать рядом.
    try {
      final prev = File(previousPathFor(path));
      if (await prev.exists()) await prev.delete();
    } catch (_) {}
    try {
      await File(path).writeAsString(header);
      _written = utf8.encode(header).length;
    } catch (_) {}
  }

  /// Дописать всё, что осело в буфере потока, на диск.
  ///
  /// Нужно перед чтением файла (экран логов, отчёт поддержки): `writeln`
  /// буферизуется, и без сброса последние — самые важные — строки в файле ещё
  /// не лежат.
  Future<void> flush() {
    // Потока нет — сбрасывать буфер нечего. Но ждать очередь ОБЯЗАТЕЛЬНО:
    // строки пишутся по одной через [_queue], и без этого читатель увидел бы
    // файл без последних — самых нужных — строк.
    _queue = _queue.then((_) async {}).catchError((_) {});
    return _queue;
  }

  Future<void> _restart({String header = ''}) async {
    if (_closed) return;
    await _rollover();
    if (header.isEmpty) return;
    try {
      await File(path).writeAsString(header, mode: FileMode.append);
      _written += utf8.encode(header).length;
    } catch (_) {}
  }

  /// Начать файл заново, сохранив прежнюю часть при [keepPrevious].
  ///
  /// ⚠️ ПРЕЖНЯЯ ЧАСТЬ КОПИРУЕТСЯ, А НЕ ПЕРЕИМЕНОВЫВАЕТСЯ, И ЭТО ПРОВЕРЕНО
  /// ОПЫТОМ НА WINDOWS, а не выбрано из вкусовых соображений. Мы держим
  /// открытым дескриптор владения ([_ownerLock]) на том же файле, а Dart
  /// открывает файлы без `FILE_SHARE_DELETE`: `File.rename` падает с
  /// «файл занят другим процессом» (errno 32), тогда как `File.copy` и
  /// обрезка на том же дескрипторе работают. Отпускать блокировку на время
  /// ротации нельзя — в это окно владение подхватила бы вторая копия
  /// приложения, и ротация исчезла бы у обеих.
  ///
  /// Копия делается ДО обрезки: если копирование не удалось, файл всё равно
  /// начинается заново. Иначе первая же ошибка копирования вернула бы нас к
  /// болезни, ради которой класс и написан, — логу без предела (758 МБ).
  Future<void> _rollover() async {
    try {
      final f = File(path);
      if (keepPrevious && await f.exists() && await f.length() > 0) {
        try {
          await f.copy(previousPathFor(path));
        } catch (_) {}
      }
      await f.writeAsString('');
      _written = 0;
    } catch (_) {}
  }

  Future<void> close() async {
    // Флаг ДО await: иначе запись, уже стоящая в очереди, переоткроет файл.
    _closed = true;
    try {
      await _queue;
    } catch (_) {}
    // Потока закрывать нечего: запись идёт отдельными открытиями и уже
    // завершилась вместе с очередью выше.
    // Блокировку владения отпускаем ЯВНО: иначе следующий экземпляр в этом же
    // процессе (тесты, перезапуск ядра) считал бы себя гостем и перестал бы
    // ротировать файл.
    final lock = _ownerLock;
    _ownerLock = null;
    _owner = false;
    try {
      await lock?.unlock(_lockOffset, _lockOffset + 1);
      await lock?.close();
    } catch (_) {}
  }

  /// Последние [lines] строк лога С УЧЁТОМ РОТАЦИИ: сперва берётся текущая
  /// часть, и если её не хватило — недостающее добирается из предыдущей
  /// (`*.prev.log`), которая в выводе идёт ВЫШЕ (она старше).
  ///
  /// ⚠️ БЕЗ ЭТОГО РОТАЦИЯ ЛЕЧИЛА БЫ ВПОЛОВИНУ. Ротация случается ровно тогда,
  /// когда ядро разговорилось, — то есть в аварии. Читатель, знающий только
  /// про `singbox.log`, получил бы в отчёте поддержки первые строки новой
  /// части («--- запуск sing-box»), а всё, что ядро сказало перед обрывом,
  /// осталось бы в соседнем файле, которого никто не открывает.
  static Future<String> tailAcrossRotation(String path,
      {int lines = 40, int tailBytes = 512 * 1024}) async {
    final current = await tail(path, lines: lines, tailBytes: tailBytes);
    final have =
        current.isEmpty ? 0 : const LineSplitter().convert(current).length;
    if (have >= lines) return current;
    final previous = await tail(previousPathFor(path),
        lines: lines - have, tailBytes: tailBytes);
    if (previous.isEmpty) return current;
    if (current.isEmpty) return previous;
    return '$previous\n$current';
  }

  /// Последние [lines] строк файла [path].
  ///
  /// Читает не более [tailBytes] с КОНЦА: файл может быть на сотни мегабайт.
  /// Первая (заведомо оборванная) строка отбрасывается, битые UTF-8-границы
  /// не бросают исключение.
  static Future<String> tail(String path,
      {int lines = 40, int tailBytes = 512 * 1024}) async {
    RandomAccessFile? raf;
    try {
      final f = File(path);
      if (!await f.exists()) return '';
      final size = await f.length();
      raf = await f.open();
      final from = size > tailBytes ? size - tailBytes : 0;
      await raf.setPosition(from);
      final bytes = await raf.read(size - from);
      var text = utf8.decode(bytes, allowMalformed: true);
      if (from > 0) {
        final nl = text.indexOf('\n');
        if (nl >= 0) text = text.substring(nl + 1);
      }
      final all = const LineSplitter().convert(text);
      return all.length <= lines
          ? all.join('\n')
          : all.sublist(all.length - lines).join('\n');
    } catch (_) {
      return '';
    } finally {
      try {
        await raf?.close();
      } catch (_) {}
    }
  }
}
