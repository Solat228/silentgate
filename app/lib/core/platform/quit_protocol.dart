/// Договор между УСТАНОВЩИКОМ и работающим приложением: «закройся сам».
///
/// ⚠️ РАДИ ЧЕГО ОН ВООБЩЕ ЕСТЬ. Обновление поверх запущенного клиента упиралось
/// в человека: установщик показывал «обнаружен запущенный экземпляр» и ждал,
/// пока тот пойдёт в трей и нажмёт «Выход». А с треем приложение запущено почти
/// всегда — то есть ручное действие требовалось на САМОМ ЧАСТОМ пути
/// обновления. Теперь установщик просит приложение закрыться само.
///
/// ⚠️ ЭТОТ ФАЙЛ — ЕДИНСТВЕННЫЙ ИСТОЧНИК ПРАВДЫ ДЛЯ ДВУХ СТОРОН, КОТОРЫЕ НИЧЕМ
/// НЕ СВЯЗАНЫ. Скрипт Inno (`installer/silentgate.iss`) не компилируется вместе
/// с Dart: разъедутся коды возврата или слова протокола — не заметит ни
/// компилятор, ни анализатор, а расплата придёт в готовой поставке молчаливым
/// отказом обновления. Поэтому в `.iss` те же числа объявлены `#define`, а
/// `test/installer_test.dart` сверяет их с константами отсюда.
///
/// ⚠️ КОМАНДА ВЫХОДА НАМЕРЕННО НЕ ИМЕЕТ ФОРМЫ ССЫЛКИ, и причина глубже, чем
/// «схему можно кликнуть с сайта». `main.dart` берёт из аргументов запуска
/// ЛЮБУЮ поддерживаемую ссылку, а наш же второй экземпляр пересылает её
/// первичному, САМ ПОДСТАВИВ ВЕРНЫЙ СЕКРЕТ (`SingleInstance.forward`). То есть
/// от ссылки секрет не защищает вовсе — курьером выступаем мы сами. Поэтому
/// вторая строка сообщения — ровно `quit` / `quit-force`, сравнение с
/// литералом, и `quit` в `AppUrlScheme.controlActions` НЕ добавляется. Канал
/// ссылок и канал выхода физически не пересекаются.
abstract final class QuitProtocol {
  /// Просьба выйти. Литерал, а не ссылка (см. заголовок файла).
  static const request = 'quit';

  /// То же, но с уже полученным согласием человека на разрыв живого туннеля.
  static const requestForce = 'quit-force';

  /// Ответ приложения: принято, гашусь.
  static const answerBye = 'bye';

  /// Ответ приложения: VPN активен, сам себя не выключу.
  static const answerBusy = 'busy';

  /// Аргументы командной строки помощника (`silentgate.exe --quit`).
  static const argQuit = '--quit';
  static const argQuitForce = '--quit-force';

  /// Коды возврата помощника. ⚠️ Те же числа лежат в `.iss` как `#define`.
  ///
  /// `exitBye` = 0 не «на всякий случай»: это единственный успех, и любое
  /// другое число обязано уводить установщик на штатный диалог Inno.
  static const exitBye = 0;

  /// VPN активен — отказ. Не 1: единица слишком похожа на «что-то упало».
  static const exitBusy = 10;

  /// Не достучались: порт свободен, ответа нет, истекло время.
  static const exitNoContact = 2;

  /// Файл секрета не прочитан — сказать приложению нечего.
  ///
  /// Бытовой случай: установщик запустили «от имени другого администратора»,
  /// и `%APPDATA%` у него чужой. Молчаливо считать это успехом нельзя.
  static const exitNoSecret = 3;

  /// На порту ответил кто-то не наш.
  static const exitForeignAnswer = 4;

  /// Сколько ждать ответа. ⚠️ Потолок обязателен: на порту 47654 может сидеть
  /// чужой процесс, который примет байты и замолчит навсегда. Старая сборка,
  /// не умеющая отвечать, просто закроет сокет — это тоже надо отличать от
  /// «ответа ещё нет», и отличает именно таймаут.
  static const answerTimeout = Duration(seconds: 3);

  /// Строка запроса по её признаку «принудительно».
  static String requestLine({required bool force}) =>
      force ? requestForce : request;

  /// Разбор ВТОРОЙ строки сообщения сокета.
  ///
  /// `null` — это не просьба выйти (значит, обычная ссылка, её путь не
  /// меняется). `false` — обычный `quit`, `true` — `quit-force`.
  ///
  /// ⚠️ Сравнение с ЛИТЕРАЛОМ и без разбора URI. Любой «умный» разбор здесь
  /// означал бы второй парсер одной строки, а два разных ответа на вопрос «что
  /// это было» в этом проекте уже дважды оказывались дырой.
  static bool? parseRequest(String line) {
    final v = line.trim();
    if (v == request) return false;
    if (v == requestForce) return true;
    return null;
  }

  /// Разбор аргументов запуска: `null` — режима выхода не просили.
  static bool? forceFromArgs(List<String> args) {
    for (final a in args) {
      if (a == argQuitForce) return true;
      if (a == argQuit) return false;
    }
    return null;
  }

  /// Код возврата по ответу приложения.
  ///
  /// Пустая строка = ответа не было (закрыли сокет молча либо истекло время).
  static int codeForAnswer(String answer) {
    final v = answer.trim();
    if (v.isEmpty) return exitNoContact;
    if (v == answerBye) return exitBye;
    if (v == answerBusy) return exitBusy;
    return exitForeignAnswer;
  }
}
