import 'dart:io';

import 'package:local_notifier/local_notifier.dart';

import 'app_log.dart';

/// Системное уведомление рабочего стола (Windows).
///
/// ## Зачем оно понадобилось
///
/// Всплывающая карточка внутри приложения видна только при ОТКРЫТОМ окне. А на
/// Windows окно почти всегда свёрнуто в трей — ради этого трей и делали.
/// Получалось так: 10.08.2026 сквозная проверка канала честно отработала
/// (`Канал не отвечает: 3 проверки подряд не прошли`), приложение переподняло
/// туннель за шесть секунд и показало карточку — а владелец её не увидел вовсе
/// и написал «на пк я не заметил увед от VPNа». Механизм работал, но сообщение
/// уходило в закрытое окно.
///
/// ⚠️ ПОКАЗЫВАЕМ НЕ ВСЁ ПОДРЯД. Системное уведомление перебивает то, чем человек
/// занят, поэтому сюда попадают только события, требующие внимания: обрыв связи
/// и неудача восстановления. Обычные заметки («соединение восстановлено»,
/// «сайт заблокирован правилом») остаются внутри приложения — иначе их начнут
/// отмахивать не читая, а вместе с ними и важные.
///
/// ## ⚠️ НА ANDROID ЭТОГО КАНАЛА НЕТ ВОВСЕ, И ЭТО НЕ МЕЛОЧЬ
///
/// [show] на не-Windows выходит сразу: `local_notifier` — пакет рабочего стола
/// (Windows/macOS/Linux), на Android он не делает ничего. Значит обрыв связи и
/// провал восстановления на телефоне не видны НИГДЕ, кроме открытого
/// приложения. На Windows ровно из-за этого и делали системное уведомление
/// («на пк я не заметил увед от VPNа»), а на телефоне приложение свёрнуто не
/// «почти всегда», а всегда — то есть там проблема строго хуже.
///
/// Постоянное уведомление foreground-сервиса здесь не годится: у него канал
/// `silentgate_vpn` с `IMPORTANCE_LOW` (без звука и всплытия — так и задумано,
/// это фоновая строка состояния), и текст в нём переписывается на каждом такте
/// счётчиков. Сообщение об обрыве в нём просто утонет.
///
/// Чего конкретно не хватает (реализовать это только из Dart нельзя):
///  1. `vpn/SilentGateVpnService.kt` — ВТОРОЙ канал уведомлений
///     (`silentgate_alerts`, `IMPORTANCE_HIGH`) и метод, постящий разовое
///     уведомление с ДРУГИМ id, `setAutoCancel(true)` и переходом в
///     `MainActivity`. Именно отдельный канал: понизив важность постоянного,
///     мы бы получили назойливую строку скорости, а повысив — звук раз в
///     секунду.
///  2. `MainActivity.kt` — ветка в `METHOD_CHANNEL`, зовущая его.
///     ⚠️ И запасной путь, когда `SilentGateVpnService.instance == null`:
///     «восстановить связь не удалось» приходит как раз тогда, когда сервис
///     уже погашен, — постить придётся из контекста приложения.
///  3. Здесь — ветка Android, зовущая этот метод вместо раннего выхода.
///
/// Разрешение `POST_NOTIFICATIONS` в манифесте уже есть (нужно для Android 13+
/// даже сервису переднего плана), новых прав не потребуется. Тексты приходят
/// из движка готовой строкой (`EngineNotice.text`) — они и сейчас не
/// переводятся, так что ARB-ключей эта работа не добавляет; захотим перевод —
/// строку должен подставлять интерфейс, а не движок.
class DesktopNotice {
  static bool _ready = false;

  /// Разовая настройка. Безопасно звать много раз.
  ///
  /// ⚠️ Идентификатор приложения обязателен: без него Windows не показывает
  /// уведомление вовсе — оно уходит в «центр уведомлений» безымянным
  /// отправителем, и пользователь его не находит.
  static Future<void> ensureReady() async {
    if (_ready || !Platform.isWindows) return;
    try {
      await localNotifier.setup(
        appName: 'SilentGate',
        // Ярлык нужен Windows, чтобы связать уведомление с приложением.
        shortcutPolicy: ShortcutPolicy.requireCreate,
      );
      _ready = true;
    } catch (e) {
      // Уведомление — не то, ради чего стоит рушить подключение.
      AppLog.w('Системные уведомления недоступны: $e');
    }
  }

  /// Показать уведомление.
  ///
  /// Там, где системного канала нет (сегодня — всё, кроме Windows), событие
  /// уходит в журнал. ⚠️ Молчать здесь было нельзя: в отчёте поддержки не
  /// оставалось даже следа, что пользователю пытались что-то сказать, — а
  /// разбирать «VPN отвалился, я ничего не заметил» без этой строки нечем.
  /// Заметки такого рода приходят редко (одна на весь обрыв, дальше не чаще
  /// раза в 15 минут), журнал они не зальют.
  static Future<void> show(String title, String body) async {
    if (!Platform.isWindows) {
      AppLog.w('Системное уведомление показать нечем на этой платформе: '
          '$title — $body');
      return;
    }
    await ensureReady();
    if (!_ready) return;
    try {
      final n = LocalNotification(title: title, body: body);
      await n.show();
    } catch (e) {
      AppLog.w('Не удалось показать системное уведомление: $e');
    }
  }
}
