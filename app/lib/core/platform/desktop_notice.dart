import 'dart:io';

import 'package:flutter/services.dart';
import 'package:local_notifier/local_notifier.dart';

import 'app_log.dart';

/// Системное уведомление (Windows и Android).
///
/// ## Зачем оно понадобилось
///
/// Всплывающая карточка внутри приложения видна только при ОТКРЫТОМ окне. А на
/// Windows окно почти всегда свёрнуто в трей — ради этого трей и делали.
/// Получалось так: 10.08.2026 сквозная проверка канала честно отработала
/// (`Канал не отвечает: 3 проверки подряд не прошли`), приложение переподняло
/// туннель за шесть секунд и показало карточку — а владелец её не увидел вовсе
/// и написал «на пк я не заметил увед от VPNа». Механизм работал, но сообщение
/// уходило в закрытое окно.
///
/// ⚠️ ПОКАЗЫВАЕМ НЕ ВСЁ ПОДРЯД. Системное уведомление перебивает то, чем человек
/// занят, поэтому сюда попадают только события, требующие внимания: обрыв связи
/// и неудача восстановления. Обычные заметки («соединение восстановлено»,
/// «сайт заблокирован правилом») остаются внутри приложения — иначе их начнут
/// отмахивать не читая, а вместе с ними и важные.
///
/// ## ⚠️ НА ANDROID КАНАЛ ПОЯВИЛСЯ 20.08.2026 — И ЭТО БЫЛА НЕ МЕЛОЧЬ
///
/// До этого [show] на не-Windows выходил сразу: `local_notifier` — пакет
/// рабочего стола, на Android он не делает ничего. То есть обрыв связи и провал
/// восстановления на телефоне не были видны НИГДЕ, кроме открытого приложения.
/// На Windows ровно из-за этого и делали системное уведомление («на пк я не
/// заметил увед от VPNа»), а на телефоне приложение свёрнуто не «почти всегда»,
/// а ВСЕГДА — то есть там дыра была строго шире.
///
/// Поймано живым прогоном в эмуляторе: сторож канала осудил мёртвый профиль и
/// честно попросил показать уведомление, а журнал ответил «Системное
/// уведомление показать нечем на этой платформе». Механизм работал целиком, и
/// упирался в последний шаг.
///
/// Устройство — `vpn/AlertNotice.kt`. Ключевое, что там объяснено подробнее:
///  * **отдельный канал** `silentgate_alerts` с `IMPORTANCE_HIGH`. Постоянное
///    уведомление сервиса не годится: у него `IMPORTANCE_LOW` (там раз в
///    секунду переписывается скорость), и сообщение об обрыве в нём утонет;
///    понизить нельзя, повысить — звук раз в секунду;
///  * **не метод сервиса**, а объект, которому хватает любого контекста:
///    «восстановить связь не удалось» приходит тогда, когда сервис уже погашен.
///
/// Разрешение `POST_NOTIFICATIONS` в манифесте уже было (нужно для Android 13+
/// даже сервису переднего плана), новых прав не потребовалось. Тексты приходят
/// из движка готовой строкой (`EngineNotice.text`) — они не переводятся, так
/// что ARB-ключей это не добавило; захотим перевод — строку должен подставлять
/// интерфейс, а не движок.
class DesktopNotice {
  static bool _ready = false;

  /// Разовая настройка. Безопасно звать много раз.
  ///
  /// ⚠️ Идентификатор приложения обязателен: без него Windows не показывает
  /// уведомление вовсе — оно уходит в «центр уведомлений» безымянным
  /// отправителем, и пользователь его не находит.
  static Future<void> ensureReady() async {
    if (_ready || !Platform.isWindows) return;
    try {
      await localNotifier.setup(
        appName: 'SilentGate',
        // Ярлык нужен Windows, чтобы связать уведомление с приложением.
        shortcutPolicy: ShortcutPolicy.requireCreate,
      );
      _ready = true;
    } catch (e) {
      // Уведомление — не то, ради чего стоит рушить подключение.
      AppLog.w('Системные уведомления недоступны: $e');
    }
  }

  /// Канал к нативному слою Android. Тот же, что у остальных команд движка:
  /// заводить второй ради одного метода значило бы плодить точки отказа.
  static const _android = MethodChannel('lol.silentgate/vpn');

  /// Показать уведомление.
  ///
  /// Там, где системного канала нет, событие уходит в журнал. ⚠️ Молчать здесь
  /// нельзя: в отчёте поддержки не оставалось бы даже следа, что пользователю
  /// пытались что-то сказать, — а разбирать «VPN отвалился, я ничего не
  /// заметил» без этой строки нечем. Заметки такого рода приходят редко (одна
  /// на весь обрыв, дальше не чаще раза в 15 минут), журнал они не зальют.
  static Future<void> show(String title, String body) async {
    if (Platform.isAndroid) {
      try {
        await _android.invokeMethod<void>(
            'alert', {'title': title, 'body': body});
      } catch (e) {
        // ⚠️ ЖУРНАЛИМ САМО СОБЫТИЕ, А НЕ ТОЛЬКО ОШИБКУ. Отказ канала здесь
        // означает, что человек об обрыве не узнал, — и в отчёте поддержки
        // должно остаться, ЧТО именно он не увидел.
        AppLog.w('Не удалось показать уведомление Android ($e): $title — $body');
      }
      return;
    }
    if (!Platform.isWindows) {
      AppLog.w('Системное уведомление показать нечем на этой платформе: '
          '$title — $body');
      return;
    }
    await ensureReady();
    if (!_ready) return;
    try {
      final n = LocalNotification(title: title, body: body);
      await n.show();
    } catch (e) {
      AppLog.w('Не удалось показать системное уведомление: $e');
    }
  }
}
