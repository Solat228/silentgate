import 'dart:io';

import 'package:flutter/foundation.dart';

import '../../engine/windows/elevation.dart';
import 'cp866.dart';

/// Восстановление сети после сбоя/выключения ПК с включённым VPN.
///
/// ⚠️ ДВА НАБОРА, А НЕ ОДИН, И ЭТО ГЛАВНОЕ ЗДЕСЬ. До 10.09.2026 кнопка была
/// одна и запускала всё разом, включая три команды, которые НЕ «восстанавливают»
/// сеть, а перекраивают её:
///   * `ipconfig /release` отпускает аренду DHCP на ВСЕХ адаптерах сразу,
///     включая виртуальные коммутаторы Hyper-V и VirtualBox. Именно так владелец
///     дважды оставался без сети (4–6.08 и 2.09.2026);
///   * `netsh int ip reset` сбрасывает стек TCP/IP к заводскому и стирает
///     статические адреса и маршруты — у владельца шлюз виртуальной сети
///     восстанавливали руками;
///   * `netsh winsock reset` чистит каталог Winsock (LSP) и ломает стороннее ПО,
///     встроившееся в стек; вступает в силу только после перезагрузки.
/// Человек, у которого «пропал интернет после VPN», в 90 % случаев лечится
/// первыми пятью безобидными командами. Платить за них сносом статики нельзя —
/// поэтому опасная четвёрка живёт за отдельной кнопкой и отдельным
/// подтверждением, где перечислена поимённо.
class NetworkRecovery {
  /// Мягкий набор: ничего не стирает, перезагрузки не требует.
  ///
  /// ⚠️ ЭТОТ СПИСОК — ГРАНИЦА БЕЗОПАСНОГО. Любая команда, добавленная сюда,
  /// выполнится по кнопке, у которой в подтверждении написано «ничего не
  /// стирается, перезагрузка не нужна». Если новая команда это обещание
  /// нарушает — ей место в [_fullExtra], а не здесь. Стережёт
  /// `network_recovery_test.dart`.
  static const softCommands = <String>[
    'ipconfig /flushdns',
    'netsh winhttp reset proxy',
    // ⚠️ Единственная НОВАЯ команда набора. Кеш ARP дёшев и безопасен (система
    // наполнит его заново за секунды), но после падения туннеля именно он
    // иногда держит запись мёртвого шлюза, и без его чистки машина продолжает
    // слать кадры в никуда, пока запись не протухнет сама.
    'netsh interface ip delete arpcache',
    r'reg delete "HKCU\Software\Microsoft\Windows\CurrentVersion\Internet Settings" /v ProxyEnable /f',
    r'reg delete "HKCU\Software\Microsoft\Windows\CurrentVersion\Internet Settings" /v ProxyServer /f',
  ];

  /// Добавка полного сброса — ровно то, чего нет в мягком наборе.
  ///
  /// ⚠️ Каждая строка отсюда названа в тексте подтверждения полного сброса
  /// (аренда DHCP, стёртая статика, перезагрузка). Дописать сюда команду и не
  /// дописать её в текст — значит сделать с машиной человека то, о чём его не
  /// предупредили.
  static const _fullExtra = <String>[
    'ipconfig /release',
    'ipconfig /renew',
    'netsh winsock reset',
    'netsh int ip reset',
  ];

  /// Полный набор = мягкий ЦЕЛИКОМ плюс добавка.
  ///
  /// ⚠️ СОБИРАЕТСЯ ИЗ [softCommands], А НЕ ПЕРЕПИСЫВАЕТСЯ ВТОРЫМ СПИСКОМ. Две
  /// копии одного набора обязательно разъедутся: правку внесут в одну, и
  /// «полный сброс» перестанет включать в себя мягкий — то есть кнопка,
  /// обещающая «всё то же самое и сверх того», молча начнёт делать меньше.
  static const fullCommands = <String>[...softCommands, ..._fullExtra];

  /// ⚠️ ПОДМЕНА ИСПОЛНЕНИЯ ДЛЯ СТРАЖА — НЕ УДОБСТВО, А ЕДИНСТВЕННЫЙ СПОСОБ
  /// ПРОВЕРИТЬ КНОПКУ ВООБЩЕ.
  ///
  /// Ниже запускаются команды, которые сбрасывают winsock и IP-стек ТОЙ САМОЙ
  /// машины, где идёт прогон тестов, и требуют перезагрузки. Настоящий вызов из
  /// теста оборвал бы сеть разработчику — поэтому подменяется ровно исполнение,
  /// а весь путь «нажатие → диалог подтверждения → запуск» остаётся настоящим.
  ///
  /// Аргумент `full` обязателен: без него страж не отличил бы мягкую кнопку от
  /// полного сброса и обе выглядели бы «дошедшими до исполнителя» одинаково —
  /// то есть перепутанные местами обработчики прошли бы мимо теста.
  /// В приложении поле всегда `null`.
  @visibleForTesting
  static Future<bool> Function(bool full)? runnerForTests;

  /// ⚠️ ПОДМЕНА ТОЛЬКО ЭЛЕВАЦИИ — ЧТОБЫ СТРАЖ УВИДЕЛ НАСТОЯЩИЕ БАЙТЫ ФАЙЛА.
  ///
  /// [runnerForTests] обрывает путь ДО записи .bat, поэтому проверить его
  /// кодировку через него нельзя. Этот хук оставляет запись настоящей и
  /// подменяет ровно запуск — иначе прогон тестов сбросил бы сеть машине
  /// разработчика. В приложении поле всегда `null`.
  @visibleForTesting
  static Future<bool> Function(String exe, String args)? launcherForTests;

  /// Путь временного .bat. Публичный, потому что страж читает записанные байты.
  ///
  /// ⚠️ У НАБОРОВ РАЗНЫЕ ФАЙЛЫ, И ЭТО НЕ КОСМЕТИКА. `cmd` дочитывает батник по
  /// байтовым смещениям ПО ХОДУ исполнения, а не забирает его в память целиком.
  /// Один путь на два набора означал бы, что вторая нажатая кнопка перезапишет
  /// файл, который прямо сейчас исполняется под администратором, и продолжится
  /// он с середины чужой строки — та самая поломка, ради которой весь этот файл
  /// пишется в cp866.
  static String batPathFor({required bool full}) {
    final name = full ? 'silentgate_netreset.bat' : 'silentgate_netrecover.bat';
    return '${Directory.systemTemp.path}${Platform.pathSeparator}$name';
  }

  /// Строки батника без разделителей.
  ///
  /// ⚠️ Весь текст обязан помещаться в cp866 (см. [buildScript]). Символ вне
  /// таблицы — «…», неразрывный пробел, тире-длиннее-дефиса — станет «?», и
  /// человек, которому сейчас сбрасывают сеть, прочитает мусор. Стережёт это
  /// `network_recovery_bat_encoding_test.dart`; ASCII-замену подбирать ЗДЕСЬ,
  /// при сборке строк, а не в кодировщике.
  static List<String> scriptLinesFor({required bool full}) => <String>[
        '@echo off',
        full
            ? 'echo Полный сброс сети SilentGate...'
            : 'echo Мягкое восстановление сети SilentGate...',
        ...(full ? fullCommands : softCommands),
        'echo.',
        // ⚠️ Хвост про перезагрузку — ТОЛЬКО у полного набора. В мягком её
        // требовать нечему, а напугать человека лишней перезагрузкой значит
        // приучить его к мысли, что и безопасная кнопка чем-то грозит.
        full
            ? 'echo Готово. Перезагрузите компьютер: сброс winsock и IP-стека '
                'вступит в силу только после перезагрузки.'
            : 'echo Готово. Перезагрузка не требуется.',
        'pause',
      ];

  /// Содержимое батника В БАЙТАХ cp866 с разделителями CRLF.
  ///
  /// ⚠️ ИМЕННО БАЙТЫ, А НЕ СТРОКА. `writeAsString` пишет UTF-8, а `cmd`
  /// перечитывает .bat по БАЙТОВЫМ СМЕЩЕНИЯМ и на многобайтных символах
  /// сбивается: исполнение продолжается с середины строки, часть команд
  /// теряется. Файл идёт под администратором и правит winsock/IP-стек — сброс
  /// «наполовину» оставляет человека без сети. Правило — `CLAUDE.md`, пункт 3.
  ///
  /// CRLF обязателен по той же причине: голый LF `cmd` разбирает не везде.
  static List<int> buildScript({required bool full}) =>
      Cp866.encode('${scriptLinesFor(full: full).join('\r\n')}\r\n');

  /// Записывает .bat и запускает его элевейтнуто (с видимым окном).
  /// Возвращает true, если запущено.
  ///
  /// ⚠️ ОДНА ТОЧКА ЗАПИСИ И ЗАПУСКА НА ОБА НАБОРА. Второй такой метод означал
  /// бы второй способ ошибиться с кодировкой, CRLF и элевацией — а страж на
  /// байты файла ходит через этот вызов.
  static Future<bool> run({required bool full}) async {
    final hook = runnerForTests;
    if (hook != null) return hook(full);
    final bat = File(batPathFor(full: full));
    await bat.writeAsBytes(buildScript(full: full));
    final args = '/c "${bat.path}"';
    final launch = launcherForTests;
    if (launch != null) return launch('cmd.exe', args);
    // Асинхронно: синхронный вызов через FFI умеет не возвращаться вовсе
    // (см. Elevation) и заморозил бы интерфейс на всё время работы батника.
    return Elevation.runElevatedAsync('cmd.exe', args, show: true);
  }
}
