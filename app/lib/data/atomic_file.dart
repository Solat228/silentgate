import 'dart:io';

/// Атомарная запись файла: пишем во временный, затем переименовываем поверх.
///
/// Зачем: обычный `writeAsString` сначала обрезает файл до нуля и только потом
/// пишет содержимое. Если процесс умрёт между этими шагами, на диске останется
/// пустой или обрезанный JSON. Дальше он читается как «битый» и молча
/// откатывается в дефолты — то есть пользователь незаметно теряет настройки
/// (в том числе выключенный kill switch) или весь список подписок.
///
/// На Windows это редкость (процесс обычно завершается штатно), а на Android
/// система убивает приложение в фоне регулярно и без предупреждения, поэтому
/// защита нужна на обеих платформах — формат файлов общий.
///
/// `rename` в пределах одного каталога атомарен и на NTFS, и на ext4/f2fs.
abstract final class AtomicFile {
  /// Записать [content] в [file] так, чтобы читатель увидел либо прежнее
  /// содержимое, либо новое целиком — но никогда не половину.
  ///
  /// Возвращает `false`, если записать не удалось (вызывающие сторы такие
  /// ошибки исторически глотают: потеря настроек не должна ронять туннель).
  static Future<bool> writeString(File file, String content) async {
    final tmp = File('${file.path}.tmp');
    try {
      await tmp.writeAsString(content, flush: true);
      await tmp.rename(file.path);
      return true;
    } catch (_) {
      // Подчищаем времянку, чтобы она не копилась рядом с данными.
      try {
        if (await tmp.exists()) await tmp.delete();
      } catch (_) {}
      return false;
    }
  }
}
