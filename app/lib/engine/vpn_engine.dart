/// Опции подключения: вариация обхода (fragment/fingerprint) + полные настройки
/// приложения. Настройки передаются целиком, чтобы новые параметры TUN/DNS доходили
/// до движка автоматически, без правки цепочки вызовов.
class ConnectionOptions {
  final OutboundVariant variant;
  final AppSettings settings;

  /// Серверы именованных выходов, УЖЕ разрешённые из ключей: `id → серверы`.
  ///
  /// ⚠️ Разрешает их состояние приложения, а не движок. Правило хранит ключ
  /// сервера (share-ссылку), сопоставить его с живым `VpnServer` можно только
  /// по полному каталогу подписок — а он есть у `AppState` и намеренно не
  /// прокидывается в движок: тот не должен знать ни про подписки, ни про то,
  /// из какой именно взят сервер. Владелец разрешил брать выходы из РАЗНЫХ
  /// подписок одновременно, и здесь это уже неразличимо — что и требуется.
  ///
  /// Пусто — один туннель, как было всегда.
  /// Дополнительные серверы, на которые ссылаются правила: ключ → сервер.
  /// Основного сервера сессии здесь НЕТ — он живёт под тегом `proxy`.
  final Map<String, VpnServer> exitServers;

  /// Из [exitServers] — те, что попали туда ТОЛЬКО ради отдельного порта API.
  ///
  /// ⚠️ БЕЗ ЭТОГО РАЗДЕЛЕНИЯ ПОРТ АКТИВНОГО СЕРВЕРА ПЕРЕХВАТЫВАЕТ ПРАВИЛА.
  /// Активный сервер получает свой outbound, чтобы его порт из `/v1/exits`
  /// куда-то вёл. Но список выходов — единственный источник правды о живых
  /// тегах, и правило «сайт через сервер X», где X и есть активный сервер,
  /// начинало уходить ВТОРЫМ соединением к тому же узлу (панель показывает
  /// удвоенный «онлайн»), да ещё и мимо панельного outbound'а Xray. Эти ключи
  /// доходят до `SingboxConfigBuilder.apiOnlyExitKeys`, и правила их не видят.
  final Set<String> apiOnlyExitKeys;

  const ConnectionOptions({
    this.variant = OutboundVariant.none,
    this.settings = AppSettings.defaults,
    this.exitServers = const {},
    this.apiOnlyExitKeys = const {},
  });

  CaptureMode get captureMode => settings.captureMode;
  SplitTunnelConfig get split => settings.splitTunnel;
}

/// Абстракция движка VPN. UI работает только с этим интерфейсом,
/// а конкретная реализация подставляется по платформе (см. engine_factory.dart).
abstract class VpnEngine {
  /// Пользователь свернул/развернул уведомление кнопкой в шторке (Android).
  /// Обработчик ставит владелец настроек — см. `VpnEngineBase`.
  set onCompactToggledInShade(void Function(bool compact)? handler);

  /// Поток изменений статуса подключения.
  Stream<VpnStatus> get statusStream;

  /// Поток статистики трафика (обновляется во время подключения).
  Stream<TrafficStats> get statsStream;

  /// Домены, которые ядро отвергло по правилу «Блок».
  ///
  /// ⚠️ Нужен потому, что показать заглушку по https НЕЛЬЗЯ: чтобы браузер
  /// принял хоть какой-то ответ — даже редирект, — нужен сертификат для чужого
  /// домена. Без него соединение обрывается раньше, чем мы успеем что-то
  /// сказать, и пользователь видит безымянное `ERR_CONNECTION_RESET`. Поэтому
  /// объясняем не в браузере, а в приложении: единственное место, где мы можем
  /// назвать причину честно.
  ///
  /// Поток объявлен ЗДЕСЬ, а не только в базе: `AppState` работает с движком
  /// через этот интерфейс, и без объявления подписка не компилируется.
  Stream<String> get blockedHostEvents;

  /// События для всплывающих сообщений: обрыв, восстановление, отказ, блокировка.
  ///
  /// ⚠️ Именно поток, а не поле статуса. Обрыв, который восстановился за пару
  /// секунд, в статусе не остаётся — строка возвращается в «Подключено», и
  /// пользователь не узнаёт, что связь рвалась вовсе.
  Stream<EngineNotice> get notices;

  /// Текущий статус (синхронно).
  VpnStatus get status;

  /// Локальный HTTP-прокси порт активного ядра — для живой проверки сервисов
  /// через уже поднятое соединение (без отдельного ядра/системного прокси).
  /// Осмыслен только при [status] == connected.
  int get httpProxyPort => 10809;

  /// Подключиться к выбранному серверу с опциями (вариация обхода, режим захвата, split).
  Future<void> connect(VpnServer server,
      {ConnectionOptions options = const ConnectionOptions()});

  /// Подключиться в режиме автовыбора: balancer + burstObservatory по всем серверам,
  /// ядро само переключается на самый быстрый.
  Future<void> connectBalancer(List<VpnServer> servers,
      {ConnectionOptions options = const ConnectionOptions()});

  /// Отключиться и вернуть систему в исходное состояние.
  Future<void> disconnect();

  /// Отключение ПОД СМЕНУ СЕРВЕРА: погасить ядро, но не снимать захват трафика,
  /// чтобы у машины не мигал маршрут по умолчанию (BACKLOG #30).
  ///
  /// Тело по умолчанию — обычное отключение: платформа, которая так не умеет,
  /// просто ведёт себя как раньше, а не ломается.
  Future<void> disconnectKeepingCapture() => disconnect();

  /// Можно ли удержать текущий захват, если следующая сессия пойдёт с [next].
  /// ⚠️ «Нет» по умолчанию: платформа, не знающая про захват, обязана честно
  /// отключаться целиком, иначе смена способа захвата оставит живой туннель.
  bool canKeepCaptureFor(AppSettings next) => false;

  /// Сигнал о смене сетевого окружения (Wi-Fi ↔ кабель, выход из сна, новый IP).
  /// Туннель поверх старого адаптера мёртв, даже если процессы живы, — движок
  /// сам решает, восстанавливать ли соединение (настройка «автопереподключение»).
  Future<void> onNetworkChanged() async {}

  /// Подхватить туннель, поднятый ПРОШЛЫМ запуском интерфейса.
  ///
  /// Зовётся один раз при старте. Умолчание — ничего не делать: на Windows
  /// туннель и интерфейс живут в одном процессе, и подхватывать нечего.
  ///
  /// На Android иначе: `VpnService` переживает смерть Activity, а состояние
  /// движка — нет. Без подхвата приложение показывало «Отключено» при
  /// РАБОТАЮЩЕМ VPN, а Connect поднимал второй сеанс поверх живого.
  Future<void> adoptRunningTunnel() async {}

  /// Вернуть сессию подхваченному туннелю: без неё автопереподключение и kill
  /// switch молча выключены (подробности — в `VpnEngineBase.armAdoptedSession`).
  /// Зовётся интерфейсом сразу после [adoptRunningTunnel], потому что данные для
  /// сессии — выбранный сервер и настройки — есть именно у него.
  Future<void> armAdoptedSession(
      List<VpnServer> servers, ConnectionOptions options) async {}

  /// Запасные серверы для режима «Авто (лучший сервер)»: если текущий не поднялся
  /// после всех попыток, движок берёт следующий отсюда. В ручном режиме — пусто:
  /// выбор пользователя не подменяем.
  set fallbackServers(List<VpnServer> servers) {}

  /// Серверы, чьи адреса обязаны идти мимо туннеля (см. `EngineBase`).
  /// ⚠️ Не то же, что [fallbackServers]: переключаться на них никто не будет,
  /// речь только о защите от петли и о стабильности конфига TUN.
  set bypassCandidates(List<VpnServer> servers) {}

  /// Имена ВСЕЙ нашей инфраструктуры: серверы подписки и её собственный хост.
  ///
  /// Резолв этих имён обязан идти напрямую. Иначе выходит круг: чтобы дойти до
  /// сервера, нужен его адрес, а адрес спрашивается через туннель, который к
  /// этому серверу ещё не построен. Реализация по умолчанию пустая — платформам
  /// без TUN это не нужно.
  set knownServerDomains(List<String> domains) {}

  /// Название активной подписки — для первой строки уведомления.
  /// Задаётся интерфейсом: движок про подписки ничего не знает.
  set subscriptionTitle(String title) {}

  /// Путь к КЭШИРОВАННОМУ логотипу подписки — значок в шторке уведомления.
  ///
  /// Именно путь к файлу, а не байты: картинка уже лежит на диске, а гонять её
  /// через канал на каждом такте статистики (раз в секунду) значило бы
  /// копировать десятки килобайт впустую. Нативная сторона читает файл сама и
  /// только когда путь изменился.
  ///
  /// Пусто — логотипа нет, показывается обычный значок приложения.
  set subscriptionLogoPath(String path) {}

  /// Раскладка уведомления: с именем подписки (false) или без него (true).
  set compactNotification(bool compact) {}

  /// Освободить ресурсы.
  Future<void> dispose();
}
