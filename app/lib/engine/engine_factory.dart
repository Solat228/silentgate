import 'dart:io';

import 'android/android_engine.dart';
import 'vpn_engine.dart';
import 'windows/windows_engine.dart';

/// Создаёт реализацию движка под текущую платформу.
///
/// Диспетчеризация рантайм-ная, а не через условные импорты: те различают
/// доступность библиотек (`dart.library.io`), а не операционную систему,
/// поэтому развести Windows и Android на этапе компиляции ими нельзя.
///
/// ⚠️ ЗДЕСЬ СТОЯЛО «Android-движок пока каркасный… подключение честно сообщает,
/// что не реализовано». Это перестало быть правдой в 1.5.0 и оставалось в коде
/// до 1.9.3: Android выпускается, туннель поднимается обоими ядрами, движок —
/// это 2200 строк Dart и 2700 строк Kotlin. Комментарий, описывающий состояние
/// годичной давности, хуже отсутствующего: следующий читатель поверит ему
/// раньше, чем коду.
///
/// Обе платформы реализованы полностью; чего Android не догнал по сравнению с
/// Windows (пинг профилей «Авто», автоподбор TUN, автонастройка) — перечислено
/// в `docs/ROADMAP.md`, вехе M7.
VpnEngine createVpnEngine() {
  if (Platform.isWindows) return WindowsEngine();
  if (Platform.isAndroid) return AndroidEngine();
  throw UnsupportedError(
    'Движок для ${Platform.operatingSystem} ещё не реализован. '
    'Порядок платформ — docs/ROADMAP.md.',
  );
}
