  /// его действие — знак, что прошлые неудачи больше не в счёт.
  void resetHealthGuard() => _healthRestarts = 0;

  /// Кончаются ли попытки. При kill switch — нет: см. [_scheduleRetryLocked].
  ///
  /// ⚠️ СПРАШИВАЕТ ТОЛЬКО KILL SWITCH, И ЭТО НАМЕРЕННО. «Не мигать сетью»
  /// ([keepCaptureBetweenAttempts]) удерживает захват, но бесконечных попыток
  /// НЕ обещает: это разные обещания, и путать их нельзя.
  bool endlessRetries(EngineSession session) =>
      session.options.settings.killSwitch;

  /// Оставлять ли захват трафика (TUN/системный прокси) между попытками.
  ///
  /// ⚠️ ОДИН МЕХАНИЗМ — ДВА РАЗНЫХ ОБЕЩАНИЯ.
  ///
  /// Kill switch держит захват, чтобы трафик НЕ УТЁК мимо VPN, и ради этого
  /// готов держать его бесконечно. `seamlessKeepTun` — про другое: снятый и
  /// заново поднятый TUN дёргает маршрут по умолчанию, и это пользователь
  /// замечает сильнее самого разрыва. У VPN на роутере такого нет вовсе — там
  /// при переподключении не меняются ни адрес, ни таблица маршрутов, пакеты
  /// просто теряются, и TCP их переотправляет; у клиентского VPN «моргание»
  /// маршрута рвёт то, что пережило бы потерю пакетов.
  ///
  /// ⚠️ ЧЕГО `seamlessKeepTun` НЕ ДЕЛАЕТ: он НЕ включает блокировку. Попытки
  /// остаются конечными ([maxAttempts]), статус не помечается `blocking`,
  /// уведомления «трафик заблокирован» нет — всё это принадлежит ТОЛЬКО kill
  /// switch (см. [endlessRetries] и `_scheduleRetryLocked`). Когда попытки
  /// кончатся, вызывающий сходит в [cleanup], и захват снимется сам.
  ///
  /// ⚠️ И честно о цене, потому что молчать о ней нельзя: пока захват стоит, а
  /// ядра нет, пакеты в туннель заходят и никуда не выходят. «Удерживается
  /// только адаптер, а трафик идёт как раньше» не бывает ни на Windows
  /// (адаптер с метрикой 0 забирает весь трафик машины), ни на Android (всё
  /// уходит в tun fd). Разница с kill switch не в том, проходит ли трафик, а в
  /// том, сколько это длится и обещаем ли мы это вслух.
  /// ⚠️ `seamlessKeepTun` ДЕЙСТВУЕТ ТОЛЬКО ТАМ, ГДЕ ЕСТЬ ЧТО УДЕРЖИВАТЬ.
  ///
  /// Найдено ревью 18.08.2026. Условие было `killSwitch || seamlessKeepTun`,
  /// без оглядки на способ захвата, а галочка включена по умолчанию. В режиме
  /// СИСТЕМНОГО ПРОКСИ (тоже умолчание) удерживать нечего: адаптера там нет
  /// вовсе, зато остаётся запись WinINET на `127.0.0.1:<порт>` — и пока ядро
  /// поднимается заново (до ~2 минут на восьми попытках), браузеры получают
  /// ERR_PROXY_CONNECTION_FAILED. При этом `killSwitch` выключен, статус
  /// «Переподключение…» о блокировке не говорит, а подпись галочки обещает
  /// «удерживается только сам адаптер». То есть чистый минус без плюса.
  ///
  /// В смешанном режиме (`alsoSetSystemProxy`) та же беда: адаптер удержать
  /// полезно, но вместе с ним удержится и мёртвый системный прокси.
  bool keepCaptureBetweenAttempts(AppSettings s) =>
      s.killSwitch ||
      (s.seamlessKeepTun &&
          s.captureMode == CaptureMode.tun &&
          !s.alsoSetSystemProxy);

