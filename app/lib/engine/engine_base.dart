  @override
  Future<void> connect(VpnServer server,
      {ConnectionOptions options = const ConnectionOptions()}) async {
    // Резолвим ДО сборки конфига: с доменом в outbound'е ядро полезло бы за
    // адресом уже из-под поднятого туннеля — и упёрлось бы в собственный
    // перехват DNS (см. SingboxOutboundFactory.build).
    final s = await sessionFor(server, options);
    await connectWith(s.configJson, options, s.servers, core: s.core);
  }

  @override
  Future<void> connectBalancer(List<VpnServer> servers,
      {ConnectionOptions options = const ConnectionOptions()}) async {
    final s = await balancerSessionFor(servers, options);
    if (s == null) return;
    await connectWith(s.configJson, options, s.servers, core: s.core);
  }

  /// Сессия одиночного сервера — БЕЗ подъёма туннеля.
  ///
  /// Вынесено из [connect], чтобы ту же сессию можно было собрать для уже
  /// РАБОТАЮЩЕГО туннеля (см. [armAdoptedSession]). Дублировать сборку нельзя:
  /// разойдясь, копии дадут разное поведение при обрыве и при обычном
  /// подключении, и заметить это будет нечем.
  Future<EngineSession> sessionFor(
      VpnServer server, ConnectionOptions options) async {
    prepareLocalProxyAuth(options);
    final resolved = pickOneIpPerHost(await resolveServerHosts([server]));
    final cfg = configFor(server, options, resolvedIps: resolved);
    return EngineSession(cfg.json, options, [server], cfg.core);
  }

  /// Сессия автовыбора — БЕЗ подъёма туннеля.
  Future<EngineSession?> balancerSessionFor(
      List<VpnServer> servers, ConnectionOptions options) async {
    if (servers.isEmpty) return null;
    prepareLocalProxyAuth(options);
    // Одно ядро на сессию: смешать hysteria2 и VLESS в одном балансировщике
    // нельзя. Xray-серверы идут в его balancer, иначе — urltest в sing-box.
    final xrayOnes =
        servers.where((s) => s.core == ProxyCore.xray).toList(growable: false);
    if (xrayOnes.isNotEmpty) {
      return EngineSession(_authedBuilder.buildBalancerJson(xrayOnes), options,
          xrayOnes, ProxyCore.xray);
    }
    final resolved = pickOneIpPerHost(await resolveServerHosts(servers));
    return EngineSession(buildSingboxJson(servers, resolvedIps: resolved),
        options, servers, ProxyCore.singbox);
  }

  /// ⚠️ ВЕРНУТЬ СЕССИЮ ТУННЕЛЮ, ПОДХВАЧЕННОМУ ОТ ПРОШЛОГО ЗАПУСКА ИНТЕРФЕЙСА.
  ///
  /// На Android `VpnService` переживает смерть Activity вместе с изолятом, и
  /// [adoptRunningTunnel] показывает «Подключено» для живого туннеля. Но сессии
  /// у движка при этом НЕТ — конфиг остался в умершем изоляте, — а по ней
  /// гейтится ВСЁ автовосстановление: [scheduleRetry] выходит первой же
  /// строкой `session == null`, ещё до проверки `autoReconnect`.
  ///
  /// Последствие было тихим и опасным: пользователь свернул приложение, вернулся
  /// — обе настройки в интерфейсе включены, отчёт поддержки печатает их
  /// активными, а на первом же обрыве не происходит ни одной попытки повтора и
  /// ни секунды удержания трафика. Kill switch живёт внутри той же ветки
  /// (`teardownCore(keepCapture: …)`), поэтому трафик идёт открыто ровно тогда,
  /// когда пользователь считает себя защищённым.
  ///
  /// Данные для сессии есть у интерфейса — тот же сервер и те же настройки, из
  /// которых туннель и поднимался (выбор персистится). Поэтому не сохраняем
  /// ничего на диск: интерфейс просто отдаёт их обратно движку.
  Future<void> armAdoptedSession(
      List<VpnServer> servers, ConnectionOptions options) async {
    // Живую сессию не трогаем: она точнее любой реконструкции.
    if (_session != null || servers.isEmpty || !_status.isConnected) return;
    try {
      _session = servers.length == 1
          ? await sessionFor(servers.first, options)
          : await balancerSessionFor(servers, options);
      AppLog.i('Подхваченному туннелю возвращена сессия: '
          'автопереподключение и kill switch снова в силе');
    } catch (e) {
      // Не смогли собрать — честно в лог. Туннель работает, но автозащиты нет.
      AppLog.w('Не удалось восстановить сессию подхваченного туннеля: $e. '
          'Автопереподключение и kill switch не сработают до переподключения');
    }
  }

  Future<void> connectWith(String configJson, ConnectionOptions options,
      List<VpnServer> servers,
      {ProxyCore core = ProxyCore.xray}) async {
    if (_status.isConnected || _status.state == VpnConnectionState.connecting) {
      return;
    }
    // Запоминаем сессию — по ней восстанавливаемся при обрыве и смене сети.
    _session = EngineSession(configJson, options, servers, core);
    _userStopped = false;
    _attempt = 0;
    // Факт, а не признак: сюда приходят ТОЛЬКО по команде человека (кнопка,
    // url-схема, локальный API). Автоповтор идёт через `scheduleRetry` и этот
    // флаг снимает. См. [isFreshUserConnect].
    _freshUserConnect = true;
    _lastUpAt = null;
    // ⚠️ ЗДЕСЬ НАКОПИТЕЛЬ БОЛЬШЕ НЕ ЧИСТИТСЯ, И ЭТО ИСПРАВЛЕНИЕ, А НЕ ПОСЛАБЛЕНИЕ.
    //
    // Чистка стояла на КАЖДОЙ команде подключения — то есть и на смене сервера.
    // Из-за неё правило обхода всякий раз пересобиралось с нуля, а резолв в
    // жизни неполон (часть имён не отвечает: на стенде из 15 серверов в кэше
    // оказывалось 2). Набор адресов выходил разным от подъёма к подъёму, конфиг
    // вместе с ним — и сверка «тот же ли туннель» честно уходила в пересоздание.
    // Живой прогон 17.08.2026: строки «Туннель не пересоздаю» не было НИ РАЗУ,
    // при каждой смене сервера в журнале снова шёл «TUN автоподбор».
    //
    // Условие, ради которого чистка ставилась, никуда не делось и соблюдается:
    // адреса ЧУЖОЙ подписки в правиле остаться не должны. Но решает это смена
    // СОСТАВА кандидатов, а не факт нажатия «Подключиться» — см. сеттер
    // [bypassCandidates]: он и чистит набор, когда список серверов сменился.
    // Подключение по команде пользователя обнуляет предохранитель сторожа
    // канала: его действие — знак, что прошлые безрезультатные попытки больше
    // не в счёт (сменил сервер, починил сеть, просто попробовал снова).
    resetHealthGuard();
    await startSession();
  }

  /// IP-адреса серверов — чтобы увести их мимо туннеля. Резолвим ДО его подъёма
  /// (обычным DNS): без этого исключения трафик самого ядра к серверу вернулся бы
  /// в туннель — петля, и сеть умирает целиком.
  /// Плоская проекция [resolveServerHosts]: сам резолв, кэш последнего успеха и
  /// запись в лог при провале живут там, чтобы не расходились две реализации.
  Future<List<String>> resolveServerIps(List<VpnServer> servers) async {
    final hosts = await resolveServerHosts(servers);
    return hosts.values.expand((e) => e).toSet().toList();
  }

  /// Адреса, которые уходят мимо туннеля (правило `ip_cidr → direct`).
  ///
  /// ⚠️ ЗАЧЕМ ЗДЕСЬ ЧТО-ТО КРОМЕ СЕРВЕРОВ СЕССИИ. Конфиг TUN запекает адрес
  /// ВЫБРАННОГО сервера, поэтому смена сервера меняла конфиг — а значит
  /// требовала снять туннель и поднять заново. Снятие и подъём дёргают маршрут
  /// по умолчанию, и это пользователь замечает сильнее самого разрыва.
  /// Если адреса всех кандидатов лежат в правиле ЗАРАНЕЕ, конфиг перестаёт
  /// зависеть от того, кто из них выбран, и хватает перезапуска одного Xray
  /// (`WindowsEngine.raiseTun` сверяет готовый конфиг и не трогает туннель).
  ///
  /// ⚠️ КАНДИДАТЫ — ТОЛЬКО ТЕ, ПРО КОГО ДВИЖОК ТОЧНО ЗНАЕТ, ЧТО ЭТО СЕРВЕРЫ:
  /// сессия и [fallbackServers]. Полного списка серверов подписки движку никто
  /// не отдаёт: единственный вход — [knownServerDomains], а туда `AppState`
  /// подмешивает ещё и ХОСТ ПАНЕЛИ. Отправить его адрес мимо туннеля нельзя:
  /// у пользователя, чей провайдер блокирует панель, страница подписки
  /// перестала бы открываться ровно при включённом VPN. Поэтому здесь — только
  /// объекты `VpnServer`.
  ///
  /// ⚠️ СПИСОК СОРТИРУЕТСЯ. Порядок приходит от резолва и от порядка серверов
  /// в подписке (а тот меняется от закрепления), и без сортировки конфиг
  /// «дышал» бы между сборками — то есть туннель пересоздавался бы на ровном
  /// месте, при том что содержимое правила то же самое.
  ///
  /// [resolvedHosts] — то, что платформа резолвит и так; выключенный флаг
  /// отдаёт РОВНО прежний список (состав и порядок), это и есть путь отката.
  Future<List<String>> tunnelBypassIps(
      Map<String, List<String>> resolvedHosts, AppSettings s) async {
    final ips = resolvedHosts.values.expand((e) => e).toSet();
    if (!s.seamlessServerSwitch) return ips.toList();
    // Кандидаты = запасные (режим «Авто») + ВСЕ известные серверы подписки.
    // Второе слагаемое и есть то, чего не хватало: без него в ручном режиме
    // список сводился к одному выбранному серверу и «дышал» при каждой смене.
    final others = <String, VpnServer>{
      for (final v in [..._fallbacks, ..._bypassCandidates]) v.key: v,
    }.values.toList();
    if (others.isNotEmpty) {
      final extra = await resolveServerHosts(others);
      ips.addAll(extra.values.expand((e) => e));
    }
    // ⚠️ НАКОПИТЕЛЬ, А НЕ ПЕРЕСЧЁТ С НУЛЯ — ИНАЧЕ ВЕСЬ ПУНКТ НЕ РАБОТАЕТ ТАМ,
    // РАДИ ЧЕГО НАПИСАН.
    //
    // Оба слагаемых выше УМЕНЬШАЮТСЯ по ходу перебора запасных серверов:
    // `scheduleRetry` берёт следующего через `_fallbacks.removeAt(0)` (то есть
    // вычёркивает его из запаса) и кладёт в сессию ТОЛЬКО его одного
    // (`_session = EngineSession(…, [next], …)`). В режиме «Авто» первая сборка
    // видит все серверы подписки плюс запас, а после первого же перехода —
    // один сервер плюс остаток запаса. Пересчёт с нуля давал бы на каждом шаге
    // всё более короткий список, конфиг менялся бы, и туннель пересоздавался
    // бы ровно на переходе между серверами — то есть в единственном сценарии,
    // где сегодня вообще может сработать переиспользование живого туннеля.
    //
    // Накопление заодно гасит «дыхание» round-robin DNS: у имени с несколькими
    // A-записями очередной резолв возвращает их в другом составе, и без памяти
    // о прошлых адресах конфиг менялся бы сам по себе.
    //
    // ⚠️ Набор живёт, пока не сменился СОСТАВ кандидатов, — чистит его сеттер
    // [bypassCandidates], а не факт подключения (чистка по каждому нажатию
    // ломала переиспользование туннеля, см. `connectWith`). Иначе адреса
    // прежней подписки остались бы в правиле навсегда, а правило это выпускает
    // трафик к ним МИМО туннеля.
    _bypassIps.addAll(ips);
    return _bypassIps.toList()..sort();
  }

  /// Адреса «мимо туннеля», накопленные для ТЕКУЩЕГО СОСТАВА подписки.
  ///
  /// ⚠️ Живёт, пока не сменился состав кандидатов: чистит [bypassCandidates],
  /// а НЕ `connectWith`. Чистка по каждому нажатию ломала переиспользование
  /// туннеля — список пересобирался с нуля, а резолв в жизни неполон.
  final Set<String> _bypassIps = {};

  // ── Страница «сайт заблокирован» ───────────────────────────────────────────


  // ── Автовосстановление ─────────────────────────────────────────────────────

  /// Запланировать повторную попытку, если включено автопереподключение и
  /// пользователь не отключался сам. Возвращает true, если попытка запланирована.
  Future<bool> scheduleRetry(String reason) async {
    final session = _session;
    if (session == null || _userStopped) return false;
    if (!session.options.settings.autoReconnect) return false;

    // Дальше идёт АВТОПОВТОР, а не команда человека, — чем бы ни кончилась
    // прошлая попытка. Без этой строки признак «свежее подключение» жил бы до
    // следующего нажатия и снимал бы платформенные предохранители на каждом
    // круге (на Android — отказ от гео-баз, см. `AndroidEngine`).
    _freshUserConnect = false;

    // ⚠️ «ПОДНЯЛСЯ И ТУТ ЖЕ УМЕР» — ЭТО НЕ УСПЕХ, А ПРОДОЛЖЕНИЕ СЕРИИ ОТКАЗОВ.
    //
    // У владельца на Android туннель поднимался, `markConnected` обнулял
    // счётчик, ядро падало через доли секунды — и так раз в секунду БЕЗ КОНЦА:
    // предел в восемь попыток не достигался никогда, потому что счётчик каждый
    // круг начинался заново. С включённым kill switch это означает телефон,
    // у которого интернета нет вообще и который сам не выздоровеет.
    final up = _lastUpAt;
    if (up != null && DateTime.now().difference(up) < _flapWindow) {
      _attempt = _attemptBeforeUp;
      AppLog.w('Туннель развалился через ${DateTime.now().difference(up).inMilliseconds} мс '
          'после подъёма — считаю это продолжением серии отказов, а не новой '
          'сессией (попыток уже $_attempt из $maxAttempts)');
    }
    _lastUpAt = null;

    // ⚠️ Повтор лечит ОБРЫВ, но не отсутствующий файл.
    //
    // Случай из жизни: файл ядра пропал из папки программы, и каждое нажатие
    // «Подключить» падало с «Не удается найти указанный файл». Приложение
    // послушно перезапускалось 31 раз подряд в течение суток, показывая
    // «Переподключение…», а настоящую причину видел только тот, кто открывал
    // лог. Пользователь всё это время считал, что «просто не работает».
    //
    // Такие отказы неустранимы повтором по своей природе: пока файла нет, ничего
    // не изменится. Останавливаемся сразу и говорим, ЧЕГО не хватает.
    if (_isUnrecoverable(reason)) {
      AppLog.e('Автопереподключение отменено: $reason. Повтор тут не поможет — '
          'не хватает файла программы, переустановите приложение.');
      _userStopped = true;
      return false;
    }

    // ОДНА попытка на один обрыв. Обрыв приходит несколькими событиями подряд:
    // при hysteria2 в TUN-режиме одновременно умирают процесс туннеля и процесс
    // прокси-ядра, у каждого свой onCoreDied, плюс сверху может прилететь смена
    // сети. Без этого стража каждое событие жгло бы отдельную попытку — в логе
    // все 8 попыток («через 0 с», «через 3 с», «через 8 с»…) отрабатывали в одну
    // миллисекунду, backoff не выдерживался вовсе, и первый же случайный сбой
    // навсегда исчерпывал лимит. Пока запланированная попытка не отработала,
    // новые события считаем тем же самым обрывом.
    //
    // ⚠️ Флаг, а не только проверка таймера: ниже стоит `await teardownCore`, и
    // на этом await управление уходит в цикл событий. Одной проверки таймера
    // мало — второе событие успевало проскочить до того, как таймер вообще
    // создан. Флаг ставится СИНХРОННО, до первого await.
    if (_retryPending || (_retryTimer?.isActive ?? false)) return true;
    _retryPending = true;
    try {
      return await _scheduleRetryLocked(reason, session);
    } finally {
      _retryPending = false;
    }
  }

  /// Обёртка для тестов: правило важное, а метод приватный.
  @visibleForTesting
  static bool isUnrecoverableForTest(String reason) => _isUnrecoverable(reason);

  /// Отказ, который повтором не лечится.
  ///
  /// Сейчас это единственный класс: не найден исполняемый файл ядра. Текст
  /// приходит от системы и локализован, поэтому смотрим и на русский вариант, и
  /// на английский, и на код ошибки Windows (2 — ERROR_FILE_NOT_FOUND,
  /// 3 — ERROR_PATH_NOT_FOUND).
  static bool _isUnrecoverable(String reason) {
    final r = reason.toLowerCase();
    return r.contains('не удается найти указанный файл') ||
        r.contains('не удаётся найти указанный файл') ||
        r.contains('cannot find the file') ||
        r.contains('the system cannot find the path') ||
        r.contains('no such file or directory') ||
        r.contains('errno = 2') ||
        r.contains('errno = 3');
  }

  bool _retryPending = false;

  /// Уже сказали пользователю про ЭТОТ обрыв. Сбрасывается при восстановлении.
  ///
  /// ⚠️ Одна заметка на серию, а не на попытку. Попыток бывает восемь подряд, а
  /// при kill switch они не кончаются вовсе — всплывашка на каждую превратила
  /// бы уведомления в шум, который отмахивают не читая. Решение владельца от
  /// 08.08.2026: три события на весь обрыв.
  bool _noticedDrop = false;

  /// Когда сообщили, что связь восстановить не удаётся. Нужно, чтобы при
  /// бесконечных попытках (kill switch) напоминать не чаще раза в 15 минут:
  /// иначе пользователь, ушедший с включённым VPN, не узнает о проблеме ВООБЩЕ,
  /// потому что ветка «попытки исчерпаны» там недостижима по построению.
  DateTime? _noticedFailedAt;
  static const _failedNoticeEvery = Duration(minutes: 15);

  Future<bool> _scheduleRetryLocked(String reason, EngineSession session) async {
    if (!_noticedDrop) {
      _noticedDrop = true;
      emitNotice(EngineNoticeKind.reconnecting, 'Связь оборвалась, восстанавливаю',
          detail: reason);
    } else if (endlessRetries(session)) {
      final since = _noticedFailedAt;
      if (since == null ||
          DateTime.now().difference(since) >= _failedNoticeEvery) {
        _noticedFailedAt = DateTime.now();
        emitNotice(EngineNoticeKind.failed, 'Связь до сих пор не восстановлена',
            detail: 'Попыток: $_attempt. Причина: $reason');
      }
    }

    // ⚠️ ПРИ ВКЛЮЧЁННОМ KILL SWITCH ПОПЫТКИ НЕ ЗАКАНЧИВАЮТСЯ.
    //
    // Раньше их было восемь на любой случай: 0,8 + 3 + 8 + 20×5 ≈ 112 секунд.
    // Дальше `scheduleRetry` возвращал false, вызывающий шёл в `cleanup()`, а тот
    // снимает TUN и системный прокси — и с этой секунды трафик идёт открыто под
    // реальным IP, без ограничения по времени. То есть обещание «не выпущу
    // трафик мимо VPN» действовало ровно две минуты, а сценарий, ради которого
    // kill switch и включают («поставил закачку и ушёл»), им не покрывался
    // вовсе: сервер лёг ночью, две минуты приложение держало оборону, потом
    // сдалось и открыло канал до утра.
    //
    // Решение владельца: держать блокировку до вмешательства человека. Вечные
    // попытки здесь не опасны — опасно как раз их прекращение: пока они идут,
    // захват трафика не снимается, и утечки нет. Пауза при этом упирается в
    // потолок `backoff` (20 с), то есть это три попытки в минуту, а не спам.
    // Вернувшийся через час сервер подхватится сам.
    final endless = session.options.settings.killSwitch;
    if (endless && _blockingSince == null) {
      _blockingSince = DateTime.now();
      AppLog.w('Kill switch: ТРАФИК ЗАБЛОКИРОВАН до восстановления связи '
          '(причина обрыва: $reason). Попытки не прекращаются — решение '
          'владельца: держать блокировку до вмешательства пользователя.');
    }
    if (!endless && _attempt >= maxAttempts) {
      AppLog.e('Автопереподключение: исчерпаны попытки ($maxAttempts)');
      emitNotice(EngineNoticeKind.failed, 'Не удалось восстановить связь',
          detail: 'Попыток: $maxAttempts. Причина обрыва: $reason');
      return false;
    }

    // Попытки на текущем сервере исчерпаны — пробуем следующий (только в режиме
    // «Авто (лучший сервер)»: там пользователь и просил «выбери рабочий»).
    if (_attempt >= maxAttempts - 1 && _fallbacks.isNotEmpty) {
      final next = _fallbacks.removeAt(0);
      AppLog.w('Переключаюсь на запасной сервер: ${next.displayName}');
      await teardownCore(
          keepCapture: keepCaptureBetweenAttempts(session.options.settings));
      if (_userStopped) return false; // отключились, пока гасили ядро
      _attempt = 0;
      // Через тот же configFor: у запасного сервера может быть свой профиль
      // панели или JSON-правка, и собирать его «из полей» — значит их потерять.
      // Резолв обязателен и здесь: запасной сервер поднимается, когда туннель
      // уже стоял, то есть в самой опасной для рантайм-резолва обстановке.
      final cfg = configFor(next, session.options,
          resolvedIps: pickOneIpPerHost(await resolveServerHosts([next])));
      _session = EngineSession(cfg.json, session.options, [next], cfg.core);
      setStatus(VpnConnectionState.connecting,
          message: 'Пробую другой сервер: ${next.displayName}…');
      _retryTimer?.cancel();
      _retryTimer = Timer(const Duration(seconds: 1), () => _runAttempt());
      return true;
    }

    _attempt++;
    final delay = backoff[_attempt.clamp(1, backoff.length) - 1];
    // ⚠️ Печатаем миллисекунды у коротких пауз. Первая задержка — 800 мс, и в
    // журнале она выглядела как «через 0 с»: разбор сбоя начинался с ложного
    // вывода, будто повтор идёт мгновенно и подряд.
    final human = delay.inSeconds >= 1
        ? '${delay.inSeconds} с'
        : '${delay.inMilliseconds} мс';
    AppLog.w('Автопереподключение: $reason → попытка $_attempt через $human');

    // Kill switch: НЕ снимаем захват трафика между попытками — иначе на время
    // паузы трафик пошёл бы напрямую, мимо VPN. «Не мигать сетью»
    // (`seamlessKeepTun`) держит захват по другой причине и без обещания
    // блокировки — см. [keepCaptureBetweenAttempts].
    await teardownCore(
        keepCapture: keepCaptureBetweenAttempts(session.options.settings));

    // teardownCore идёт долго (остановка процесса до 3 с + снятие TUN), и за это
    // время пользователь успевает нажать «Отключить». Без этой проверки мы
    // возвращали статус в «Подключение…» и ставили таймер уже ПОСЛЕ отключения:
    // пользователь навсегда оставался в «Подключение…», а повторный connectWith
    // отсекался гвардом «уже подключаемся».
    if (_userStopped) return false;

    // При вечных попытках «из 8» было бы враньём, а главное — надо СКАЗАТЬ, что
    // трафик сейчас заблокирован: без этого человек видит пропавший интернет и
    // не понимает, что это работает защита, а не поломка.
    setStatus(VpnConnectionState.connecting,
        message: endless
            ? 'Соединение потеряно, трафик заблокирован. '
                'Переподключение через ${delay.inSeconds} с (попытка $_attempt)…'
            : 'Переподключение через ${delay.inSeconds} с '
                '(попытка $_attempt из $maxAttempts)…',
        blocking: endless);

    _retryTimer?.cancel();
    _retryTimer = Timer(delay, () => _runAttempt());
    return true;
  }

  /// Выполнить запланированную попытку.
  ///
  /// ⚠️ Исключение внутри колбэка таймера ловить НЕКОМУ: запланированная попытка
  /// была единственной, и любой сбой подъёма (занятый порт, отказ ядра, отвал
  /// прав) навсегда оставлял движок в «Подключение…» без единого сообщения.
  /// Перехватываем и планируем следующую попытку — лимит и backoff при этом
  /// продолжают работать, а при их исчерпании пользователь увидит ошибку.
  Future<void> _runAttempt() async {
    if (_userStopped) return;
    try {
      await startSession();
    } catch (e) {
      AppLog.e('Попытка восстановления не удалась: $e');
      if (!await scheduleRetry('ошибка восстановления')) {
        setStatus(VpnConnectionState.error, message: '$e');
      }
    }
  }

  /// Номер текущей попытки восстановления (0 — обычное подключение).
  ///
  /// Счётчик ведёт база; наследникам он нужен только для текста статуса. Пока
  /// его не было, `WindowsEngine` держал СВОЁ поле `_attempt`, которое никто не
  /// увеличивал, — номер попытки в статусе и в логе всегда оставался нулём.
  int get attempt => _attempt;

  /// Сколько попыток восстановления израсходовано на текущем сервере.
  @visibleForTesting
  int get attemptsUsed => _attempt;

  /// Снять ожидающую попытку, не выполняя её, — чтобы в тестах не ждать backoff
  /// по-настоящему (первая пауза 800 мс, дальше до 20 с).
  @visibleForTesting
  void dropPendingRetry() {
    _retryTimer?.cancel();
    _retryTimer = null;
  }

  /// Внешний сигнал: сетевое окружение изменилось (Wi-Fi ↔ кабель, сон, новый IP).
  /// Туннель поверх старого адаптера уже мёртв, даже если процессы живы.
  @override
  /// Умолчание: подхватывать нечего — туннель и интерфейс живут в одном
  /// процессе. Переопределяет только Android, где `VpnService` переживает
  /// смерть Activity (см. `VpnEngine.adoptRunningTunnel`).
  @override
  Future<void> adoptRunningTunnel() async {}

  @override
  Future<void> onNetworkChanged() async {
    final session = _session;
    if (session == null || _userStopped) return;
    if (!_status.isConnected) return;
    if (!session.options.settings.autoReconnect) return;
    // Страховка от цикла: сразу после подключения «смена сети» — это почти всегда
    // наш же туннель, а не реальное изменение.
    final since = _connectedAt;
    if (since != null && DateTime.now().difference(since) < networkGrace) {
      AppLog.i('Смена сети проигнорирована: прошло меньше '
          '${networkGrace.inSeconds} с после подключения');
      return;
    }
    if (session.options.settings.seamlessNetworkChange &&
        await _channelSurvivedNetworkChange(session)) {
      return;
    }
    AppLog.w('Смена сети — восстанавливаю подключение');
    _attempt = 0;
    await scheduleRetry('сменилось сетевое окружение');
  }

  /// Пережил ли канал смену сети. `true` — трогать соединение не нужно.
  ///
  /// ⚠️ ЗАЧЕМ ВООБЩЕ СПРАШИВАТЬ. Раньше событие `NetworkWatcher` означало
  /// приговор: ядро перезапускалось всегда. Но смена адреса — не то же самое,
  /// что смерть канала: у hysteria2 транспорт QUIC, а он умеет миграцию
  /// соединения, то есть переход Wi-Fi → LTE переживает САМ. Перезапуск по
  /// событию убивал именно ту возможность, ради которой протокол и выбирают, —
  /// и рвал все живые сессии пользователя там, где рвать было нечего.
  ///
  /// ⚠️ ПРОБА ТА ЖЕ, ЧТО У СТОРОЖА КАНАЛА ([TunnelHealth]), и берётся живой
  /// экземпляр сторожа, если он вооружён: иначе получилось бы две независимые
  /// пробы с разными кредами и портами — а чем в этом проекте кончаются два
  /// разбора одного вопроса, записано отдельным уроком.
  ///
  /// ⚠️ КАК ЭТО УЖИВАЕТСЯ СО СТОРОЖЕМ. `probeOnce()` не трогает НИ ОДНОГО его
  /// счётчика: серию промахов ведёт только его собственный такт (`_fails`
  /// внутри `TunnelHealth.start`), а предохранитель от вечного цикла
  /// (`_healthRestarts`) считает переподключения, которых здесь не происходит.
  /// Поэтому «канал жив» тут не обнуляет накопленную сторожем серию, а «канал
  /// мёртв» её не ускоряет: мы отвечаем на другой вопрос — «надо ли вообще
  /// что-то делать прямо сейчас».
  ///
  /// ⚠️ И ОДНОЙ ПРОБЫ ЗДЕСЬ ДОСТАТОЧНО, хотя сторожу нужно три промаха подряд.
  /// У сторожа одиночный промах — норма (мишень прилегла, сеть моргнула), и
  /// реагировать на него значит рвать связь по пустякам. Здесь наоборот: если
  /// проба не прошла, мы всего лишь возвращаемся к ПРЕЖНЕМУ поведению —
  /// переподключению по смене сети, — то есть худший исход ошибки равен тому,
  /// что было до этой правки.
  Future<bool> _channelSurvivedNetworkChange(EngineSession session) async {
    final auth = healthProbeAuth;
    final probe = _health ??
        createHealthProbe(
          proxyPort: httpProxyPort,
          proxyUser: auth.user,
          proxyPassword: auth.password,
        );
    if (!await probe.probeOnce()) {
      AppLog.i('Смена сети: канал не отвечает через прокси-порт '
          '$httpProxyPort — переподключаюсь');
      return false;
    }
    // ⚠️ ПОСЛЕ ДОЛГОГО AWAIT — ПЕРЕПРОВЕРКА. Проба идёт по трём мишеням до 8 с
    // на каждую, то есть до ~24 с, и за это время пользователь успевает
    // отключиться, а сессия — смениться целиком. Во всех таких случаях отвечаем
    // «не трогать»: решение по НОВОМУ состоянию принимает тот, кто его создал.
    if (_userStopped || !_status.isConnected || !identical(_session, session)) {
      AppLog.i('Смена сети: за время пробы состояние изменилось — '
          'соединение не трогаю');
      return true;
    }
    AppLog.i('Смена сети: трафик через канал по-прежнему идёт — '
        'переподключение не требуется (QUIC умеет пережить смену адреса сам)');
    return true;
  }

  /// Ядро умерло само — пробуем восстановиться, иначе показываем ошибку.
  ///
  /// [tail] — последние строки вывода ядра. ⚠️ БЕЗ НИХ ПРИЧИНА НЕВИДИМА.
  /// Раньше в журнал уходило только «Ядро Xray остановилось (код 1)», и разбор
  /// упирался в тупик: код 1 у Xray означает и занятый порт, и битый конфиг, и
  /// отвалившийся сервер. Владелец видел «весь интернет лёг» (kill switch), а
  /// в журнале не было ни строчки о том, почему. Сам Xray причину печатает —
  /// мы её просто выбрасывали.
  Future<void> onCoreDied(int code, {String tail = ''}) async {
    // Имя ядра важно: по нему пользователь понимает, куда смотреть —
    // в xray_config.json или в singbox_proxy.json.
    final name = _session?.core == ProxyCore.singbox ? 'sing-box' : 'Xray';
    final reason = _reasonFromTail(tail);
    AppLog.e('Ядро $name остановилось (код $code)'
        '${reason.isEmpty ? '' : ': $reason'}');
    if (tail.trim().isNotEmpty) {
      AppLog.e('Последние строки вывода $name:\n${tail.trim()}');
    }
    final short = 'ядро $name остановилось (код $code)'
        '${reason.isEmpty ? '' : ': $reason'}';
    if (await scheduleRetry(short)) return;
    await cleanup();
    setStatus(VpnConnectionState.error, message: _capitalize(short));
  }

  /// Человеческая причина из вывода ядра — одной строкой, для журнала и статуса.
  ///
  /// Полный вывод всё равно пишется рядом; здесь только то, что должно попасть
  /// в заголовок ошибки, иначе пользователь увидит простыню и не найдёт сути.
  static String _reasonFromTail(String tail) {
    if (tail.trim().isEmpty) return '';
    final low = tail.toLowerCase();
    // Порт занят — самая частая и самая обидная причина: ядро печатает её
    // внятно, а мы показывали голый код возврата.
    if (low.contains('address already in use') ||
        low.contains('only one usage of each socket address') ||
        low.contains('bind:')) {
      final m = RegExp(r'127\.0\.0\.1:(\d+)').firstMatch(tail);
      final port = m == null ? '' : ' ${m.group(1)}';
      return 'локальный порт$port уже занят';
    }
    if (low.contains('failed to start')) return 'ядро не смогло запуститься';
    // Иначе — первая непустая строка, обрезанная до читаемой длины.
    final first = tail
        .split('\n')
        .map((l) => l.trim())
        .firstWhere((l) => l.isNotEmpty, orElse: () => '');
    return first.length > 160 ? '${first.substring(0, 160)}…' : first;
  }

  static String _capitalize(String s) =>
      s.isEmpty ? s : s[0].toUpperCase() + s.substring(1);

  @override
  Future<void> disconnect() async {
    // ⚠️ ОТКЛЮЧЕНИЕ ОБЯЗАНО ОСТАВЛЯТЬ СЛЕД В ЖУРНАЛЕ.
    //
    // Найдено прогоном на эмуляторе 18.08.2026: подключение писалось
    // («Подключение по команде пользователя»), а отключение — НЕТ, ни на одной
    // платформе. В отчёте поддержки это значит, что намеренное выключение и
    // смерть туннеля выглядят одинаково: журнал просто обрывается. Ровно та же
    // беда уже была с перезапусками — шесть подряд шли без единого слова о
    // причине, и ради этого завели «Перезапуск туннеля по команде пользователя».
    //
    // Пишем только при живом канале: холостой вызов (а он приходит и при
    // закрытии приложения, и из `--cleanup`) засорял бы журнал шумом.
    if (_status.state != VpnConnectionState.disconnected) {
      AppLog.i('Отключение по команде пользователя');
    }
    // Явное отключение всегда отменяет автовосстановление, даже если оно уже идёт.
    _userStopped = true;
    // ⚠️ Пометку обрыва снимаем ЗДЕСЬ. Она означает «об обрыве уже сказали, и
    // при возврате связи надо сказать о восстановлении». Ручное отключение
    // закрывает ту историю: без этой строки следующее подключение — новое,
    // по кнопке — здоровалось «Соединение восстановлено», хотя ничего не
    // рвалось и восстанавливать было нечего.
    _noticedDrop = false;
    _noticedFailedAt = null;
    _generation++; // всё, что поднимется после этого момента, будет погашено
    _session = null;
    _attempt = 0;
    _fallbacks = [];
    _retryTimer?.cancel();
    _retryTimer = null;
    if (_status.state == VpnConnectionState.disconnected) {
      // Kill switch мог оставить захват при неудачном восстановлении — снимаем.
      await cleanup();
      return;
    }
    setStatus(VpnConnectionState.disconnecting);
    await cleanup();
    setStatus(VpnConnectionState.disconnected);
    emitStats(TrafficStats.zero);
  }

  /// Отключение ПОД СМЕНУ СЕРВЕРА: ядро гасим, захват трафика оставляем.
  ///
  /// ⚠️ РАДИ ЧЕГО ЭТО ЗАВЕДЕНО (BACKLOG #30, три прогона в VM).
  /// `WindowsEngine.raiseTun` умеет не пересоздавать туннель: сверяет готовый
  /// конфиг с конфигом живого туннеля и, если совпал и ядро отвечает, оставляет
  /// туннель на месте. Но смена сервера шла через `disconnect()` + `connect()`,
  /// а `disconnect` доходит до `platformCleanup` → `_tunRouter.stop()`,
  /// `_tunActive = false`, `_liveTunConfig = null`. К моменту сверки живого
  /// туннеля УЖЕ НЕТ — переиспользовать нечего, и сверка честно уходит в
  /// пересоздание. Механизм был написан и покрыт тестами, а в журнале строки
  /// «Туннель не пересоздаю» не было НИ РАЗУ: он не мог сработать на этом пути
  /// в принципе, сколько ни стабилизируй конфиг (две гипотезы про адреса
  /// проверены опытом и обе оказались мимо).
  ///
  /// ⚠️ ЭТО НЕ KILL SWITCH. Захват удерживается на считаные секунды между
  /// снятием старого ядра и подъёмом нового; трафик в это время никуда не
  /// «течёт мимо VPN» — маршрут ведёт в туннель, у которого просто нет ядра, и
  /// соединения получают отказ. Ровно так же ведёт себя удержание захвата между
  /// попытками восстановления.
  Future<void> disconnectKeepingCapture() async {
    // Дальше идёт немедленное подключение, поэтому автовосстановление старой
    // сессии должно быть отменено так же жёстко, как при обычном отключении.
    _userStopped = true;
    _noticedDrop = false;
    _noticedFailedAt = null;
    _generation++; // всё, что поднимется после этого момента, будет погашено
    _session = null;
    _attempt = 0;
    _fallbacks = [];
    _retryTimer?.cancel();
    _retryTimer = null;
    // ⚠️ Статус обязан стать «отключено»: `connectWith` отсекает вызов на живом
    // канале своей же защитой (`if (_status.isConnected) return`), и без этой
    // строки смена сервера просто не делала бы ничего.
    if (_status.state != VpnConnectionState.disconnected) {
      AppLog.i('Смена сервера: гашу ядро, захват оставляю');
      setStatus(VpnConnectionState.disconnecting);
    }
    await teardownCore(keepCapture: true);
    setStatus(VpnConnectionState.disconnected);
    emitStats(TrafficStats.zero);
  }

  /// Полная остановка. Поколение увеличивается ЗДЕСЬ — поэтому всё, что зависит
  /// от «была ли отмена», обязано проверяться ДО вызова (см. `wasAborted`
  /// в наследниках).
  Future<void> cleanup() async {
    stopBlockNotice();
    _generation++;
    _retryTimer?.cancel();
    _retryTimer = null;
    _connectedAt = null;
    await platformCleanup();
  }

  @override
  Future<void> dispose() async {
    await cleanup();
    await _statusController.close();
    await _statsController.close();
  }
}
