/// Уборка временного конфига проброс-харнесса.
///
/// ⚠️ В ЭТОМ ФАЙЛЕ ЛЕЖИТ ПАРОЛЬ ЛОКАЛЬНОГО ИНБАУНДА. Харнесс поднимает на
/// `127.0.0.1` прокси ВНУТРЬ туннеля проверяемого сервера, и с 1.4.1 этот вход
/// закрыт паролем. Пароль уезжает в конфиг ядра — обычный JSON в каталоге
/// данных пользователя. Оставленный там, он переживает прогон, перезапуск
/// приложения и вообще всё: секрет одноразовый по замыслу, но не по факту.
///
/// ⚠️ И УБИРАТЬ ЕГО НАДО НА ДВУХ ПУТЯХ, А НЕ НА ОДНОМ. Конец прогона — путь
/// очевидный; второй — откат `start()`, упавшего ПОСЛЕ записи файла (ядро не
/// нашлось, порт занят, ожидание готовности бросило). Там хендла ещё нет, звать
/// его `stop()` некому, и без явного отката файл остаётся лежать именно в том
/// случае, когда что-то пошло не так, — то есть чаще всего.
///
/// Ровно та же уборка и по той же причине уже сделана на Android
/// (`engine/android/probe_harness_android.dart`); одна копия на платформу
/// неизбежна (разные каталоги и разные владельцы), но внутри Windows она одна
/// на оба ядра — иначе две копии разъехались бы на первой же правке.
library;

import 'dart:io';

/// Удалить конфиг харнесса. Ошибку глотаем: ронять прогон ради уборки мусора
/// незачем, а отсутствующий файл — штатный случай (второй вызов уборки).
Future<void> deleteHarnessConfig(String? path) async {
  if (path == null || path.isEmpty) return;
  try {
    await File(path).delete();
  } catch (_) {}
}
