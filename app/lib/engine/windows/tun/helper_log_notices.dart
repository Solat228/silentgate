/// Что из журнала элевейтнутого помощника обязано попасть в ОБЩИЙ журнал.
///
/// ⚠️ ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ ЕСТЬ. Настоящий kill switch поднимает не
/// приложение, а помощник (`TunHelper`) — отдельный процесс с правами
/// администратора. Он пишет своим колбэком в `singbox.log`, и строки уровня
/// отказа («kill switch НЕ поднят», «нет связи с интерфейсом», исключение при
/// подъёме) в `app.log` не появлялись ВООБЩЕ. А ищут именно их: при поднятой
/// блокировке и неподнятом туннеле машина остаётся без сети, человек читает
/// это как «приложение сломалось», открывает журнал приложения — и не находит
/// там ни следа причины.
///
/// ⚠️ ПОЧЕМУ РАЗБОР, А НЕ ЗАПИСЬ СРАЗУ В ДВА ФАЙЛА. Помощник живёт в другом
/// контексте безопасности, и `app.log` ему не свой: писать туда из-под
/// администратора значит либо сменить владельца файла, либо перемешать две
/// очереди записи в один файл. Разбор на стороне приложения дешевле и не
/// трогает права.
library;

/// Признаки строки отказа. ⚠️ Список сверяется с НАСТОЯЩИМ исходником
/// помощника в `test/helper_log_notices_test.dart`: поменяли формулировку —
/// страж падает, а не мост молча замолкает.
const helperFailureMarkers = <String>[
  'НЕ ЗАПУСКАЮ ЯДРО',
  'НЕ УДАЛОСЬ ЗАПУСТИТЬ',
  'НЕ поднят',
  'не поднялся',
  'не удалось',
  'не выполнилась',
  // ⚠️ Самая важная строка из всех: ядро умерло, а блокировка держится — то
  // есть машина СЕЙЧАС без сети, и держит её наша защита, а не поломка.
  'ДЕРЖИТСЯ',
];

/// Начало последней сессии помощника в его журнале.
///
/// ⚠️ ЗАЧЕМ ГРАНИЦА. Журнал помощника переживает перезапуски НАМЕРЕННО: новая
/// сессия — это и есть восстановление после обрыва, и обрезка стирала бы
/// журнал аварии тем самым перезапуском, который аварией вызван. Значит в
/// хвосте лежат отказы прошлых сессий, и мост без границы кричал бы о давно
/// почившей беде при полностью исправном подключении. Ложная тревога здесь
/// хуже молчания: на неё перестанут смотреть, и настоящую пропустят.
const helperSessionHeader = '--- запуск sing-box ';

/// Кусок [helperLog] от последнего заголовка сессии и до конца.
///
/// Заголовка нет — отдаём журнал целиком: помощник мог упасть, не успев его
/// написать, и это ровно та авария, ради которой мост и заводится.
String lastHelperSession(String helperLog) {
  final at = helperLog.lastIndexOf(helperSessionHeader);
  return at < 0 ? helperLog : helperLog.substring(at);
}

/// Строки отказа из [helperLog], по одному разу каждая, в порядке появления.
///
/// Повтор убираем намеренно: помощник переспрашивает набор фильтров, и три
/// одинаковых строки в журнале приложения только мешают читать.
List<String> killSwitchFailures(String helperLog) {
  final out = <String>[];
  final seen = <String>{};
  for (final raw in helperLog.split('\n')) {
    final line = raw.trim();
    if (line.isEmpty) continue;
    if (!helperFailureMarkers.any(line.contains)) continue;
    if (!seen.add(line)) continue;
    out.add(line);
  }
  return out;
}
