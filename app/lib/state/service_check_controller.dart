/// Идёт ли ПРЯМО СЕЙЧАС автопрогон проверки сервисов — отметка на весь процесс.
///
/// ⚠️ ЗАЧЕМ ОТМЕТКА СНАРУЖИ КОНТРОЛЛЕРА, А НЕ ПОЛЕ-СВЯЗКА.
/// [ServiceCheckController] и `ProbeController` — два независимых провайдера,
/// и связки между ними нет ни в одном месте приложения. А занят у них ОДИН
/// ресурс: прокси-порт живого ядра. Пинг активного сервера идёт через тот же
/// порт, что и пробы сервисов, и на Windows в режиме по умолчанию туда же
/// смотрит системный прокси всей машины.
///
/// ⚠️ И ГЛАВНОЕ: РАЗРЕШЕНИЕ И ИСПОЛНЕНИЕ ОБЯЗАНЫ СПРАШИВАТЬ ОДИН КОД. Гейт
/// интерфейса (`PingGate`) и исполнитель (`ProbeController._pingBatch`)
/// спрашивают ровно это поле — разойдись они, кнопка снова обещала бы то, чего
/// исполнитель не делает (на url-схемах этот класс расхождений уже давал дыру).
class ServiceCheckActivity {
  ServiceCheckActivity._();

  /// Счётчик, а не флаг: контроллер в приложении один, но в тестах их сколько
  /// угодно, и завершение одного не должно снимать отметку с другого.
  static int _running = 0;

  /// Занят ли живой прокси-порт прогоном проверки сервисов.
  static bool get busy => _running > 0;

  static void begin() => _running++;

  static void end() {
    if (_running > 0) _running--;
  }

  /// Снять отметку целиком. Только для тестов: прогон, упавший с исключением,
  /// иначе оставил бы пинг закрытым до конца процесса.
  @visibleForTesting
  static void resetForTests() => _running = 0;
}

/// Хранит результаты живой проверки сервисов у кнопки Connect.
///
/// ⚠️ ЭПОХА РЕЗУЛЬТАТОВ — ФАКТ ПОДЪЁМА ТУННЕЛЯ, А НЕ ВЫБРАННЫЙ СЕРВЕР.
///
/// Раньше признаком служил ключ выбранного сервера, и клик по другой строке
/// списка стирал шесть готовых вердиктов и гонял пробы заново. Это было не
/// просто лишней работой, а ЛОЖЬЮ: `AppState.selectServer` живой туннель не
/// трогает (он лишь показывает «переподключитесь»), то есть трафик всё это
/// время шёл через ПРЕЖНИЙ сервер, а проверка выдавалась за проверку нового.
///
/// Правило целиком:
///  * автопрогон — ровно один раз на КАЖДЫЙ подъём туннеля ([autoCheckAll]);
///  * тап пользователя — всегда и в любом состоянии ([check]);
///  * туннель упал ⇒ колонка «через VPN» гаснет: результаты через сервер
///    больше не действуют. Замер «без VPN» переживает это ([_baseline]);
///  * смена выбранного сервера без переподключения не делает НИЧЕГО —
///    контроллер о выборе не знает вовсе.
class ServiceCheckController extends ChangeNotifier {
  final Map<ProbeService, ServiceCheckOutcome> _results = {};

  /// Результаты, снятые БЕЗ VPN — чтобы было с чем сравнивать.
  ///
  /// Держатся отдельно и переживают подключение: смысл в том, чтобы
  /// пользователь видел «до» и «после» рядом. Сбрасываются только вручную.
  final Map<ProbeService, ServiceCheckOutcome> _baseline = {};

  ServiceCheckOutcome baselineFor(ProbeService s) =>
      _baseline[s] ?? ServiceCheckOutcome.idle;

  bool get hasBaseline => _baseline.isNotEmpty;

  /// Поднят ли сейчас туннель — по последнему, что сказал экран ([setTunnelUp]).
  bool _tunnelUp = false;
  bool get tunnelUp => _tunnelUp;

  /// Номер текущего подъёма туннеля. Растёт на КАЖДОЙ смене состояния канала
  /// (поднялся и упал — два разных номера), и только на ней.
  ///
  /// Заменил прежний строковый ключ сервера: по нему нельзя было отличить
  /// «канал переподняли» от «человек ткнул в другую строку списка».
  int _session = 0;
  @visibleForTesting
  int get session => _session;

  /// Подъём, для которого автопроверка уже отработала. Держим отдельно от
  /// [_results]: результат мог не сохраниться (сервис ответил ошибкой), но
  /// повторять автопрогон всё равно нельзя — дальше только ручные проверки.
  int? _autoRanSession;

  ServiceCheckOutcome resultFor(ProbeService s) =>
      _results[s] ?? ServiceCheckOutcome.idle;

  bool get anyChecking =>
      _results.values.any((o) => o.state == ServiceCheckState.checking);

  /// Автопрогон идёт прямо сейчас (включая ожидание готовности канала).
  bool _autoRunning = false;
  bool get autoRunning => _autoRunning;

  /// Канал не заработал: ожидание готовности не прошло, пробы НЕ запускались.
  ///
  /// ⚠️ ЭТО ОТДЕЛЬНОЕ СОСТОЯНИЕ, А НЕ 14 КРАСНЫХ КРУЖКОВ. Раньше при неудаче
  /// ожидания пробы всё равно уходили в мёртвый канал «ради честного отказа», и
  /// человек видел ряд красных кружков — то есть «VPN не работает ни с чем»,
  /// хотя через полминуты работало всё. Красный кружок обязан означать вердикт
  /// о сервисе, а не о том, что ядро ещё не встало.
  bool _channelNotReady = false;
  bool get channelNotReady => _channelNotReady;

  /// Сколько автопрогонов подряд не состоялось на этом подъёме и когда была
  /// последняя неудача. Нужны обоим предохранителям повтора (см. [_retryReady]).
  int _autoFailures = 0;
  DateTime? _autoFailedAt;

  /// Сообщить состояние канала. ЕДИНСТВЕННЫЙ вход, задающий эпоху результатов.
  ///
  /// Зовётся с каждой перерисовки главного экрана, поэтому первое, что делает,
  /// — отсекает всё, кроме СМЕНЫ состояния: иначе счётчик подъёмов тикал бы на
  /// каждом такте счётчиков трафика и автопрогон шёл бы по кругу.
  ///
  /// ⚠️ Подхват уже живого туннеля при старте интерфейса (Android держит VPN
  /// без UI) сюда приходит как первое `up: true` — то есть считается подъёмом и
  /// получает свой автопрогон. Так и задумано: для человека это «включённый
  /// VPN», а проверять канал, о котором мы ничего не знаем, тем нужнее.
  void setTunnelUp(bool up) {
    if (up == _tunnelUp) return;
    _tunnelUp = up;
    _session++;
    // Результаты «через VPN» относились к прошлому каналу: он либо упал (тогда
    // показывать их как действующие — враньё), либо переподнялся (тогда их надо
    // снять заново). Замер «без VPN» не трогаем — он ни к какому каналу не
    // привязан и нужен для сравнения.
    _results.clear();
    // Новый канал — новая история: неудача прошлого подъёма не имеет права
    // запрещать автопрогон на этом.
    _channelNotReady = false;
    _autoFailures = 0;
    _autoFailedAt = null;
    notifyListeners();
    if (up) {
      // Канал вернулся — отложенный догон замера «до» отменяем: мерить мимо VPN
      // теперь всё равно нельзя, просьба остаётся ждать в [_baselineWanted].
      _catchUpTimer?.cancel();
      _catchUpTimer = null;
      return;
    }
    // Туннель погас — самое время догнать замеры «до», которые мы отложили,
    // пока он был жив (см. [ensureBaseline]). Без этого сервис, добавленный при
    // включённом VPN, так и остался бы с одним кружком до перезапуска.
    _scheduleBaselineCatchUp();
  }

  /// Не чаще одного догона замера «до» за это время.
  ///
  /// ⚠️ ЗАЧЕМ ОГРАНИЧЕНИЕ. `setTunnelUp(false)` — это ЛЮБОЙ переход в «не
  /// подключено», а не только «человек нажал Отключить»: окно переподключения
  /// сторожа канала, kill switch, смена сети, перезапуск туннеля по правке
  /// настроек. На каждом таком мигании уходила пачка ПРЯМЫХ проб — до
  /// четырнадцати запросов наружу за окно, и так на каждое окно подряд.
  @visibleForTesting
  static Duration baselineCatchUpCooldown = const Duration(seconds: 60);

  DateTime? _lastCatchUp;
  Timer? _catchUpTimer;

  /// Догон замера «до»: первый — сразу, повторы — не чаще [baselineCatchUpCooldown].
  ///
  /// ⚠️ ПЕРЕДНИМ ФРОНТОМ, А НЕ ПРОСТО ОТЛОЖЕННЫМ ЗАПУСКОМ: обычное отключение
  /// пользователем — тоже первый переход, и заставлять его ждать полминуты
  /// «на случай, если это мигание» значит наказать частый случай ради редкого.
  /// Зато повтор внутри окна не выполняется сразу, а откладывается на конец
  /// окна — один догон вместо десятка.
  void _scheduleBaselineCatchUp() {
    if (_baselineWanted.isEmpty) return;
    final last = _lastCatchUp;
    final left = last == null
        ? Duration.zero
        : baselineCatchUpCooldown - DateTime.now().difference(last);
    if (left <= Duration.zero) {
      _lastCatchUp = DateTime.now();
      unawaited(ensureBaseline(_baselineWanted.toList()));
      return;
    }
    _catchUpTimer?.cancel();
    _catchUpTimer = Timer(left, () {
      _catchUpTimer = null;
      // Канал мог вернуться, пока ждали: тогда замер «до» опять не наш случай.
      if (_tunnelUp || _baselineWanted.isEmpty) return;
      _lastCatchUp = DateTime.now();
      unawaited(ensureBaseline(_baselineWanted.toList()));
    });
  }

  @override
  void dispose() {
    // Иначе отложенный догон выстрелит в уничтоженный контроллер и уронит
    // `notifyListeners()` — а прогон тестов увидит это как чужое падение.
    _catchUpTimer?.cancel();
    _catchUpTimer = null;
    super.dispose();
  }

  /// Единственный автоматический прогон всех [services] — на подъёме туннеля.
  ///
  /// Повторный вызов для того же подъёма игнорируется, поэтому перестроение
  /// интерфейса (смена темы, поворот экрана, возврат с другого экрана, тик
  /// счётчиков раз в секунду) не запускает пробы заново: после СОСТОЯВШЕГОСЯ
  /// прогона сервисы проверяются только вручную. Новый подъём = новый [_session].
  ///
  /// ⚠️ «Не состоялся» и «состоялся с плохими вердиктами» — разные вещи.
  /// Прогон, до которого дело не дошло (канал не заработал), повторяется сам
  /// после паузы и по кнопке ([retryAutoCheck]); прогон, который прошёл и
  /// вернул красные кружки, — это ответ, и повторять его незачем.
  Future<void> autoCheckAll(int httpPort, List<ProbeService> services) async {
    // ⚠️ Порт и ПУСТОЙ НАБОР проверяем ДО всего остального.
    //
    // Порт активного ядра появляется не в ту же миллисекунду, что статус
    // «Подключено», и отметка, поставленная на нуле, съела бы единственный
    // автопрогон подъёма целиком — молча, навсегда, до переподключения.
    //
    // Пустой набор — то же самое с другой стороны: проверки выключены
    // настройкой (`ServiceChecks.selected`), делать нечего, и «эпоху» тратить
    // не на что. Иначе включение проверок при уже поднятом туннеле не
    // запускало бы ничего до переподключения — хотя человек только что
    // попросил проверять.
    //
    // ⚠️ И `services.isEmpty` обязан стоять ЗДЕСЬ, до `_waitProxyUsable`, а не
    // полагаться на то, что `Future.wait([])` ниже отработает вхолостую. Пустой
    // список доходил до ожидания готовности канала и слал до шести проб на
    // gstatic.com через туннель — при снятой галочке «не проверять при
    // подключении», то есть ровно тогда, когда человек попросил в сеть не
    // ходить вовсе.
    if (!_tunnelUp ||
        httpPort <= 0 ||
        services.isEmpty ||
        _autoRanSession == _session) {
      return;
    }
    // Главный экран зовёт это с КАЖДОЙ перерисовки (счётчики тикают раз в
    // секунду), а прогон длится десятки секунд: без этой строки поверх идущей
    // пачки вставала бы вторая, третья и так далее.
    if (_autoRunning) return;
    if (!_retryReady()) return;

    final session = _session;
    _autoRunning = true;
    _channelNotReady = false;
    // Отметка занятости берётся ДО ожидания готовности, а не только на время
    // пачки: пинг, начатый за секунду до пачки, будет идти одновременно с ней —
    // то есть ровно то столкновение на живом порту, ради которого гейт и есть.
    ServiceCheckActivity.begin();
    notifyListeners();

    // ⚠️ ЭПОХА ТРАТИТСЯ ПО ФАКТУ ПРОГОНА, А НЕ АВАНСОМ.
    //
    // Здесь стояло `_autoRanSession = _session` ДО первой пробы, и одна
    // неудачная пачка закрывала автопроверку НАВСЕГДА — до переподключения.
    // Владелец видел это так: «не пингуется с самого начала после включения
    // VPN», и дальше уже ничего не менялось само.
    var ran = false;
    try {
      // ⚠️ Дождаться, пока канал ЗАРАБОТАЕТ, а не пока поднимется туннель.
      //
      // «Подключено» выставляется, как только встал туннель, но за ним ещё
      // стартует прокси-ядро, и первые секунды прокси-порт принимает
      // соединения, никуда их не доставляя.
      if (!await _waitProxyUsable(httpPort)) {
        // Пачку НЕ запускаем: 14 красных кружков человек читает как «через VPN
        // не работает ничего», хотя канал просто ещё не встал. Показываем
        // отдельное состояние, которое можно повторить ([retryAutoCheck]).
        AppLog.w('Проверка сервисов: канал не отвечает — автопрогон '
            'не запускался (порт $httpPort)');
        return;
      }
      await _runPack(services, httpPort);
      // Канал сменился, пока шла пачка: прогон относился к прошлому подъёму,
      // и «отработано» ему записывать нельзя (у нового подъёма свой прогон).
      if (_session != session) return;
      ran = true;
      _autoRanSession = session;
      _autoFailures = 0;
      _autoFailedAt = null;
    } finally {
      _autoRunning = false;
      ServiceCheckActivity.end();
      // Неудача — только та, что случилась на НАШЕМ подъёме: переподключение
      // во время ожидания к состоянию канала отношения не имеет.
      if (!ran && _session == session) {
        _channelNotReady = true;
        _autoFailures++;
        _autoFailedAt = DateTime.now();
      }
      notifyListeners();
    }
  }

  /// Пауза перед автоматическим повтором после неудачи и потолок таких повторов.
  ///
  /// ⚠️ ПОЧЕМУ ОГРАНИЧЕНИЯ ВООБЩЕ ЕСТЬ. Отметка «подъём отработан» теперь
  /// ставится только по факту прогона — значит `autoCheckAll`, который зовут с
  /// каждой перерисовки, после неудачи будет пробовать снова. Без паузы это
  /// превратилось бы в бесконечный поток проб в неработающий канал: лечение
  /// оказалось бы хуже болезни, которую чинили.
  @visibleForTesting
  static Duration autoRetryDelay = const Duration(seconds: 20);
  @visibleForTesting
  static int autoRetryLimit = 2;

  bool _retryReady() {
    final failedAt = _autoFailedAt;
    if (failedAt == null) return true;
    // Автоматических попыток — считанные штуки; дальше только по просьбе
    // человека ([retryAutoCheck]), иначе мёртвый канал доил бы сеть до
    // отключения VPN.
    if (_autoFailures > autoRetryLimit) return false;
    return DateTime.now().difference(failedAt) >= autoRetryDelay;
  }

  /// Повторить автопрогон по просьбе человека — из плашки «канал не готов».
  ///
  /// Снимает и паузу, и счётчик автоматических попыток: нажатие означает «я
  /// вижу, что канал уже работает», и спорить с этим нечем.
  Future<void> retryAutoCheck(int httpPort, List<ProbeService> services) {
    _autoFailures = 0;
    _autoFailedAt = null;
    _channelNotReady = false;
    return autoCheckAll(httpPort, services);
  }

  /// Сколько проб сервисов идёт одновременно.
  ///
  /// ⚠️ ПУЛ, А НЕ `Future.wait` ПО ВСЕМУ СПИСКУ — И ПОТОЛОК ЗДЕСЬ НИЖЕ, ЧЕМ У
  /// ПИНГА. Владелец включил все 14 сервисов и получил «всё сломалось и не
  /// пингуется с самого начала»: четырнадцать проб уходили в ОДИН порт живого
  /// ядра в одну миллисекунду, а на Windows в режиме по умолчанию туда же
  /// смотрит системный прокси всей машины — то есть заодно и браузер человека.
  /// У пинга потолок восемь, но там N разных харнесс-портов; здесь порт один.
  ///
  /// То же правило уже выписано рядом: `probe_controller` берёт `Pool`, а в
  /// `auto_config_engine` про это есть отдельное предупреждение.
  @visibleForTesting
  static const int concurrency = 3;

  /// Прогнать набор с ограничением одновременности.
  Future<void> _runPack(List<ProbeService> services, int httpPort) async {
    final pool = Pool(concurrency);
    await Future.wait([
      for (final s in services) pool.run(() => check(s, httpPort)),
    ]);
  }

  /// Ждать, пока через прокси реально проходит запрос.
  ///
  /// Проверяем сквозным запросом, а не открытием сокета: порт слушает СРАЗУ,
  /// поэтому «подключился к порту» ничего не доказывает. Берём самый дешёвый
  /// ответ — пустой 204.
  /// Сколько раз и с какой паузой ждать готовности канала.
  ///
  /// Вынесено в поля, чтобы тесты не ждали полминуты вхолостую: на закрытом
  /// порту ждать нечего, а в бою этот запас — единственное, что отличает
  /// «через VPN ничего не работает» от «ядро ещё не встало».
  @visibleForTesting
  static int readinessAttempts = 6;
  @visibleForTesting
  static Duration readinessDelay = const Duration(seconds: 2);

  /// Чем проверяется один сервис. Боевое значение задано здесь и в приложении
  /// не меняется НИКОГДА — подменяется только в тестах.
  ///
  /// ⚠️ Развилка нужна не для удобства. Правило «когда прогонять» — про
  /// состояние канала, а не про сеть; тест, ходящий наружу, проверял бы заодно
  /// погоду на серверах YouTube и падал бы у того, кто запустил его без
  /// интернета. Ровно этот класс правил здесь уже ломали дважды, и оба раза
  /// молча.
  @visibleForTesting
  static Future<ServiceCheckOutcome> Function(int httpPort, ProbeService s)
      prober = ServiceChecker.check;

  /// Одна попытка «проходит ли через прокси запрос».
  ///
  /// Отдельным полем — чтобы страж «при выключенных проверках в сеть не ходим»
  /// мог это СОСЧИТАТЬ. Прежде счётчика не было, и пустой набор доходил до
  /// ожидания готовности канала незамеченным: тесты видели лишь то, что проб
  /// сервисов не было, а шесть запросов на gstatic.com при снятой галочке — нет.
  @visibleForTesting
  static Future<bool> Function(int httpPort) readinessProbe =
      defaultReadinessProbe;

  /// Боевая реализация [readinessProbe]. Публичная только затем, чтобы тест мог
  /// вернуть её на место в `tearDown`, — в приложении зовётся лишь через поле.
  static Future<bool> defaultReadinessProbe(int httpPort) async {
    final r = await ProxyProbe.check(
      httpPort,
      'http://www.gstatic.com/generate_204',
      head: true,
      timeout: const Duration(seconds: 4),
    );
    return r.ok;
  }

  Future<bool> _waitProxyUsable(int httpPort) async {
    if (httpPort <= 0) return false;
    final session = _session;
    for (var attempt = 0; attempt < readinessAttempts; attempt++) {
      // Пользователь мог отключиться или переподключиться, пока мы ждём.
      if (_session != session) return false;
      if (await readinessProbe(httpPort)) return true;
      await Future<void>.delayed(readinessDelay);
    }
    // Канал так и не заработал — и это НЕ повод гнать в него пачку проб.
    //
    // Раньше здесь стояло `return _session == session`, то есть «пробуем всё
    // равно, пусть человек увидит честный отказ». Честным он не был: четырнадцать
    // красных кружков читаются как «VPN не работает ни с чем», хотя проверялось
    // ядро, которое ещё не встало. Отказ теперь называет себя сам —
    // [channelNotReady] — и его можно повторить.
    return false;
  }

  /// Проверить один сервис.
  ///
  /// [httpPort] == 0 — проба идёт НАПРЯМУЮ, мимо VPN: это замер «до», нужный
  /// для сравнения. Результат кладётся в отдельную полку и не смешивается с
  /// замером через туннель, иначе сравнивать было бы не с чем.
  Future<void> check(ProbeService s, int httpPort) async {
    final baseline = httpPort <= 0;
    final store = baseline ? _baseline : _results;
    if (store[s]?.state == ServiceCheckState.checking) return;
    final session = _session; // к какому подъёму относится эта проверка
    store[s] = ServiceCheckOutcome.checking;
    notifyListeners();
    final out = await prober(httpPort, s);
    // Проба идёт до ~16 с. Если за это время туннель упал или переподнялся
    // ([setTunnelUp]), результат относится к СТАРОМУ каналу — не пишем его.
    // Замера «до» это не касается: он к каналу не привязан.
    if (!baseline && _session != session) return;
    store[s] = out;
    notifyListeners();
  }

  /// Снять замер «до подключения» — по всем сервисам сразу, напрямую.
  ///
  /// Тем же пулом, что и прогон через туннель: порт живого ядра тут ни при чём,
  /// но четырнадцать одновременных запросов наружу — это всё равно пачка,
  /// которая приходится ровно на момент отключения VPN, когда сеть у человека и
  /// так перестраивается.
  Future<void> checkBaseline(List<ProbeService> services) =>
      _runPack(services, 0);

  /// Сервисы, которым замер «до» нужен, но ещё не снят.
  ///
  /// Накапливается [ensureBaseline] и разгружается при выключении туннеля.
  /// ⚠️ Отсюда НЕ вычёркиваются сервисы, которые пользователь потом убрал из
  /// набора: контроллер о наборе не знает вовсе (и знать не должен — состав
  /// живёт в настройках). Цена ошибки — один прямой запрос на сервис, который
  /// сейчас не показывается; цена обратного решения — потерянный замер.
  final Set<ProbeService> _baselineWanted = {};

  /// Замер «до» отложен и ждёт выключения VPN (для тестов и диагностики).
  @visibleForTesting
  Set<ProbeService> get baselineWanted => Set.unmodifiable(_baselineWanted);

  /// Догнать замер «до» для сервисов, которых в нём ещё нет.
  ///
  /// ⚠️ ЗАЧЕМ ЭТО ЕСТЬ. Жалоба владельца по скриншоту: пара кружков «было →
  /// стало» рисовалась только у трёх сервисов набора по умолчанию, а у
  /// добавленных позже висел одинокий кружок. Причина — [autoBaseline]:
  /// он отрабатывает ОДИН раз за запуск и ровно по тому набору, который был
  /// выбран в тот момент. Сервис, включённый через минуту, замера «до» не
  /// получал НИКОГДА — до перезапуска приложения.
  ///
  /// Меряются только недостающие: у кого замер уже есть (в том числе неудачный
  /// или идущий прямо сейчас), тот не перепроверяется — иначе каждое открытие
  /// подменю гоняло бы полтора десятка запросов заново.
  ///
  /// ⚠️ ЗАМЕР «ДО» ИМЕЕТ СМЫСЛ ТОЛЬКО ПРИ ВЫКЛЮЧЕННОМ ТУННЕЛЕ. При живом
  /// канале проба ушла бы ЧЕРЕЗ него и легла в графу «без VPN» — сравнение
  /// стало бы ложью, причём правдоподобной. Поэтому на живом канале мы не
  /// «меряем как получится» и не отказываемся молча, а ЗАПОМИНАЕМ просьбу и
  /// выполняем её при первом же выключении туннеля ([setTunnelUp]). До тех пор
  /// у сервиса честно написано «Без VPN не проверялось».
  ///
  /// [vpnActive] — признак живого канала со стороны интерфейса (порт ядра).
  /// Он есть у колонки проверок раньше, чем контроллеру сообщат [setTunnelUp],
  /// и служит вторым предохранителем: достаточно ОДНОГО признака живого
  /// канала, чтобы замер отложить.
  Future<void> ensureBaseline(List<ProbeService> services,
      {bool vpnActive = false}) async {
    if (services.isEmpty) return;
    _baselineWanted.addAll(services);
    if (_tunnelUp || vpnActive) return;

    // ⚠️ ПРОВАЛИВШИЙСЯ ЗАМЕР ПЕРЕМЕРЯЕМ, А НЕ СЧИТАЕМ ОТВЕТОМ.
    //
    // Найдено скептиком 18.08.2026. Догон срабатывает по `setTunnelUp(false)`, а
    // это ЛЮБОЙ переход в «не подключено» — в том числе окно переподключения и
    // kill switch, где трафик заблокирован НАМЕРЕННО и ядро уже погашено. Пробы
    // в этот момент падают все до одной, и прежний отбор («мерим только тех, у
    // кого записи нет») закреплял этот провал НАВСЕГДА: запись есть, значит
    // больше не меряем. Наружу — ровно тот случай, ради которого правку и
    // делали: сервис, добавленный при живом VPN, получал вечный красный кружок
    // «без VPN» вместо честного «не проверялось».
    //
    // Контроллер не знает про `connecting` и про блокировку — и знать не должен.
    // Поэтому предохранитель не в угадывании момента, а в том, что НЕУДАЧА не
    // считается измеренной величиной.
    bool needs(ProbeService s) {
      final have = _baseline[s];
      return have == null || have.state == ServiceCheckState.fail;
    }

    final missing = [
      for (final s in services)
        if (needs(s)) s,
    ];

    // Набор «ждущих» обязан сокращаться: у кого замер уже есть и он не провал —
    // тому ждать нечего. Раньше снимались только `missing`, поэтому множество
    // навсегда оставалось непустым и дёргало догон на КАЖДОМ отключении.
    _baselineWanted.removeWhere((s) => !needs(s));

    if (missing.isEmpty) return;
    await checkBaseline(missing);

    // Снимаем только тех, у кого замер получился. Остальные ждут следующего
    // выключения канала — именно так провал перестаёт быть окончательным.
    _baselineWanted.removeWhere((s) => !needs(s));
  }

  bool _baselineRan = false;

  /// Автоматический замер «до» — один раз за запуск приложения.
  ///
  /// Смысл всей пары «до → после» в сравнении, а сравнивать было не с чем:
  /// замер «до» снимался только вручную, и пользователь видел одинокий кружок
  /// «через VPN», по которому нельзя понять, VPN ли починил сервис или тот и
  /// так работал.
  ///
  /// ⚠️ Вызывать ТОЛЬКО при выключенном VPN. Если туннель уже поднят (например,
  /// приложение подхватило живое соединение при старте), проба уйдёт ЧЕРЕЗ него
  /// и запишется в графу «без VPN» — сравнение станет ложью, причём
  /// правдоподобной.
  ///
  /// Один раз за запуск, а не за экран: возврат с настроек не должен гонять
  /// шесть проб заново.
  ///
  /// ⚠️ ФЛАГ СТЕРЕЖЁТ ТОЛЬКО ЭТОТ, СТАРТОВЫЙ ПРОГОН — и больше ничего. Догон
  /// сервисов, добавленных позже, живёт в [ensureBaseline] и от флага не
  /// зависит: раньше он взводился здесь и не сбрасывался нигде, из-за чего
  /// каждый новый сервис оставался без замера «до» навсегда.
  Future<void> autoBaseline(List<ProbeService> services) async {
    // Пусто — проверки выключены настройкой: не помечаем замер сделанным, иначе
    // включение проверок в этом же запуске осталось бы без половины сравнения.
    if (services.isEmpty) return;
    if (_baselineRan) return;
    _baselineRan = true;
    await ensureBaseline(services);
  }
}
