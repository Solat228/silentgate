/// Ошибки, которые приложение распознаёт само и потому умеет перевести.
///
/// Динамические ошибки (текст исключения от сети или ядра) кодом не
/// обозначаются: переводить их нечем, и они уходят в интерфейс как есть.
///
/// [fallback] — русский текст для лога и отчёта поддержки: они принципиально
/// не переводятся, чтобы обращения разбирались на одном языке. В интерфейсе
/// используется `appErrorText` (`core/i18n/enum_labels.dart`).
enum AppErrorCode {
  invalidJson('Некорректный JSON'),
  pickServerFirst('Сначала выберите сервер'),
  importSubscriptionFirst('Сначала импортируйте подписку');

  const AppErrorCode(this.fallback);

  final String fallback;
}
