package lol.silentgate

import android.app.Application
import android.system.Os
import android.util.Log
import java.io.File

/**
 * Приложение целиком. Существует ради ОДНОЙ вещи — переменной окружения,
 * которую надо выставить раньше всего остального.
 *
 * ⚠️ ЧЕСТНО О ТОМ, ЧТО ЭТА ПЕРЕМЕННАЯ ДАЁТ: НИЧЕГО ДЛЯ ГЕО-БАЗ.
 * `android.system.Os.setenv` правит окружение **libc**, а рантайм Go держит
 * СВОЮ копию, снятую при собственной инициализации, и в libc больше не
 * заглядывает — поэтому `os.Getenv` внутри ядра её не видит НИКОГДА, сколько бы
 * рано мы её ни ставили. Каталог гео-баз ядру задаёт блок `env` ВНУТРИ конфига
 * (`AndroidEngine._withAssetEnv`), и только он: это зафиксировано тестами
 * самого libXray и проверено на эмуляторе `sg-test`.
 *
 * Строку оставляем как безвредное умолчание для путей, где конфиг собираем не
 * мы. Каталог создаём заранее по той же причине: пустой каталог ядру не мешает,
 * а его отсутствие добавило бы к разбору лишний слой.
 *
 * ⚠️ ЗДЕСЬ БЫЛ `Class.forName("…libXray.LibXray")` — УБРАН, И ВОЗВРАЩАТЬ ЕГО
 * НЕЛЬЗЯ. Его добавили в 1.5.0 вместе с комментарием, утверждавшим, что
 * принудительная загрузка ядра сразу после `setenv` и есть лечение гео-баз.
 * Сообщение того же коммита говорит обратное: «ПРОВЕРЕНО ОПЫТОМ —
 * принудительная загрузка ядра сразу после setenv отказ НЕ вылечила».
 * То есть строка не делала ничего полезного, а стоила дорого: `LibXray.<clinit>`
 * трогает `go.Seq`, а тот в своём `<clinit>` зовёт `System.loadLibrary("cores")`
 * — то есть СИНХРОННО, НА ГЛАВНОМ ПОТОКЕ, ДО СТАРТА FLUTTER подгружал
 * `libcores.so` (58 МБ под arm64-v8a) и поднимал рантайм Go. И делал это при
 * КАЖДОМ старте процесса, включая те, где ядро вообще не нужно: холодный запуск
 * интерфейса, привязка плитки быстрых настроек, отдача файла через FileProvider.
 * Ядро подтягивается лениво тем, кому оно действительно нужно
 * (`SilentGateVpnService`, `PlatformChannels`), — так и должно быть.
 */
class SilentGateApplication : Application() {

    companion object {
        /**
         * Контекст приложения для тех мест, где своего нет.
         *
         * ⚠️ Нужен ровно одному потребителю — обновлению плитки быстрых настроек
         * из статического [lol.silentgate.vpn.SilentGateVpnService.notifyState].
         * Там смена состояния объявляется из companion object, а экземпляр
         * сервиса к тому моменту уже может быть снят, поэтому брать контекст у
         * него нельзя. Контекст ПРИЛОЖЕНИЯ живёт столько же, сколько процесс, и
         * утечки активности здесь не бывает.
         */
        @Volatile
        var appContext: android.content.Context? = null
            private set
    }

    override fun onCreate() {
        super.onCreate()
        appContext = applicationContext
        runCatching {
            // Тот же каталог, куда кладёт файлы Dart-сторона (`GeoAssets.dir()`).
            // Создаём заранее: пустой каталог ядру не мешает, а его отсутствие
            // добавило бы к разбору лишний слой «а туда ли вообще смотрели».
            val geo = File(filesDir, "SilentGate/geo")
            if (!geo.exists()) geo.mkdirs()
            Os.setenv("XRAY_LOCATION_ASSET", geo.absolutePath, true)
            // ⚠️ НИЧЕГО ТЯЖЁЛОГО ЗДЕСЬ БОЛЬШЕ НЕТ И БЫТЬ НЕ ДОЛЖНО.
            // `Application.onCreate` идёт на главном потоке ДО первого кадра
            // Flutter и выполняется при КАЖДОМ старте процесса — в том числе
            // когда система лишь привязывает плитку быстрых настроек. Всё, что
            // грузит ядра, обязано подтягиваться лениво, у потребителя.
            Log.i("SilentGateApp", "Каталог гео-баз: ${geo.absolutePath}")
        }.onFailure {
            Log.w("SilentGateApp", "Не удалось указать каталог гео-баз: ${it.message}")
        }
    }
}
